# ============================ 结果模型 ============================


@dataclass
class 结构结果:
    """结构层输出。**层间只传数据结构**（架构文档第三节），不传字符串拼出来的东西。"""

    标题: str = ""
    年份: int | None = None
    类型: str = "unknown"            # tv / movie / unknown（与评测口径一致）
    季: int | None = None
    集: int | None = None
    集到: int | None = None          # ``E01-E12`` / ``01-12`` 的区间上界
    特别篇: bool = False             # 第 0 季（NCOP/NCED/SP/OVA/特别篇…）
    季来源: str = ""                 # 目录 / 文件名 / 特别篇 / 默认：诊断与打分都要用
    文件标题: str = ""               # 文件名切出来的标题（可能为空）
    目录标题: str = ""               # 目录链里找到的标题（可能为空）
    文件名: str = ""
    目录链: tuple[str, ...] = field(default_factory=tuple)

    def 是剧集(self) -> bool:
        return self.类型 == "tv"

    def 查询词们(self) -> list[str]:
        """③ 候选生成要用的查询词（排序过的多个，不是只有一个）。

        为什么中英混排要拆开：TMDB 的中文名与原名是两个索引，混着搜经常两边都不像；
        整串、中文段、拉丁段三个词一起给检索层，命中率比只给整串高得多。
        """
        词们: list[str] = []
        if self.标题:
            词们.append(self.标题)
        中文段 = "".join(re.findall(r"[\u4e00-\u9fff\u3040-\u30ff]+", self.标题))
        拉丁段 = " ".join(re.findall(r"[A-Za-z0-9][A-Za-z0-9'&:!.\-]*", self.标题)).strip()
        if 中文段 and 中文段 != self.标题:
            词们.append(中文段)
        if 拉丁段 and 拉丁段 != self.标题:
            词们.append(拉丁段)
        # 去重但保序（顺序就是"先搜哪个"的优先级）
        出: list[str] = []
        for 词 in 词们:
            if 词 and 词 not in 出:
                出.append(词)
        return 出

    def 一句话(self) -> str:
        """日志/界面用的一行摘要。"""
        尾巴 = [f"标题「{self.标题 or '空'}」"]
        if self.年份:
            尾巴.append(str(self.年份))
        尾巴.append(self.类型)
        if self.季 is not None:
            尾巴.append(f"S{self.季:02d}")
        if self.集 is not None:
            尾巴.append(f"E{self.集:02d}" + (f"-E{self.集到:02d}" if self.集到 else ""))
        if self.特别篇:
            尾巴.append("特别篇")
        if self.季来源:
            尾巴.append(f"季来自{self.季来源}")
        return "｜".join(尾巴)


# ============================ 中文数字 ============================

_中文数字表 = {"零": 0, "一": 1, "二": 2, "两": 2, "三": 3, "四": 4, "五": 5,
           "六": 6, "七": 7, "八": 8, "九": 9}
_中文单位表 = {"十": 10, "百": 100, "千": 1000}


def 中文数字(文本: str) -> int | None:
    """``十二`` → 12、``三`` → 3、``24`` → 24；认不出返回 None。

    为什么必须支持中文数字：``第三集``/``第十二集`` 是国产剧与老番剧的常见写法，
    而老实现只认阿拉伯数字，于是这两条样本的集号整个丢了（评测报告第 7/8 条）。
    """
    文本 = (文本 or "").strip()
    if not 文本:
        return None
    if 文本.isdigit():
        return int(文本)
    总 = 0
    段 = 0
    for 字 in 文本:
        if 字 in _中文数字表:
            段 = _中文数字表[字]
        elif 字 in _中文单位表:
            单位 = _中文单位表[字]
            总 += (段 or 1) * 单位
            段 = 0
        else:
            return None
    return 总 + 段 if (总 or 段) else None


_数字或中文 = r"(?:\d{1,4}|[零一二两三四五六七八九十百千]{1,4})"


# ============================ 季目录 / 特别篇目录 ============================

_季目录 = re.compile(r"^(?:season|s)[\s._-]*0*(\d{1,2})$|^第\s*(\d{1,2})\s*[季部]$"
                 r"|^第\s*([零一二两三四五六七八九十]{1,3})\s*[季部]$", re.I)
#: 特别篇**目录**（Jellyfin 惯例是 Season 00 / Specials / Extras）。
_特别篇目录 = re.compile(r"^(?:specials?|season[\s._-]*0{1,2}|s0{1,2}|extras?|特别篇|特别版|番外篇?|特典)$", re.I)
#: 目录名里**夹着**的季标识（``仙逆 第2季``/``Show S02``）。为什么单独一条：
#: 只有"整名就是季目录"的正则不够用 —— 网盘里"剧名 + 第N季"是常态
#: （老实现的 ``命名解析._目录季号`` 就认它；P5 接线时把它补回结构层，
#: 否则 ``仙逆 第2季/146.mp4`` 会被当成第 1 季，文件挂到错的季上）。
#: ``s(\d)`` 那条必须排除 ``S01E05``（那是集不是季），也不能粘着别的数字。
_目录里夹季 = re.compile(
    r"第\s*(\d{1,2})\s*季|第\s*([零一二两三四五六七八九十]{1,3})\s*季"
    r"|(?<![A-Za-z0-9])(?:season|s)[\s._-]*0*(\d{1,2})(?![\s._-]*e\d)(?![0-9])", re.I)


def 是季目录(名字: str) -> bool:
    """这个名字是不是季目录（``Season 02`` / ``第2季`` / ``S02``）。"""
    return bool(_季目录.match(归一化.转半角(名字 or "").strip()))


def 是特别篇目录(名字: str) -> bool:
    """这个名字是不是"第 0 季"目录（``Specials`` / ``Season 00`` / ``特别篇``）。"""
    return bool(_特别篇目录.match(归一化.转半角(名字 or "").strip()))


def _扫目录季(目录们: Sequence[str]) -> tuple[int | None, bool]:
    """目录链（由近到远）里找季号与特别篇标记；最近的目录优先。

    两遍扫：**先认"整名就是季目录"**（``Season 02``/``第2季``/``S02``/``Specials``，
    最可信），再认"名字里夹着季标识"（``仙逆 第2季``/``Show S02``）。
    为什么要分两遍而不是一个正则：夹在名字里的写法误判面更大，只有在前一遍
    一无所获时才该动用它。
    """
    for 名 in 目录们:
        文本 = 归一化.转半角(名 or "").strip()
        if not 文本:
            continue
        if 是特别篇目录(文本):
            return 0, True
        if (m := _季目录.match(文本)):
            数字 = m.group(1) or m.group(2) or m.group(3)
            号 = 中文数字(数字)
            if 号 is not None:
                return 号, 号 == 0
    for 名 in 目录们:
        文本 = 归一化.转半角(名 or "").strip()
        if not 文本:
            continue
        if (m := _目录里夹季.search(文本)):
            数字 = m.group(1) or m.group(2) or m.group(3)
            号 = 中文数字(数字)
            if 号 is not None:
                return 号, 号 == 0
    return None, False


# ============================ 结构标记 ============================


@dataclass
class _标记:
    """名字里的一处"结构标记"。切点取最靠左的那个，季/集各取最靠左的有效值。"""

    起点: int
    终点: int
    优先级: int
    季: int | None = None
    集: int | None = None
    集到: int | None = None
    是特别: bool = False
    是打包无集: bool = False
    写法: str = ""


# --- ① 打包/更新写法（必须排在"第N集"前面：``更新至第24集`` 是"从 1 集到 24 集"，
#        不是"第 24 集"；老实现把它当成第 24 集，评测报告第 32 条就是这么错的）---
_更新至 = re.compile(r"(?:更新至|更新到|已更新|连载至|连载)\s*(?:第\s*)?(" + _数字或中文 + r")\s*(?:[集话話回])?")
_全N集 = re.compile(r"(?:全|共|总共|一共)\s*(" + _数字或中文 + r")\s*[集话話回]")
_N集全 = re.compile(r"(" + _数字或中文 + r")\s*[集话話回]\s*全")

# --- ② S01E138 / s3e05 / S01E01E02 / S01E01-E12 ---
_季集 = re.compile(r"(?<![A-Za-z0-9])s(\d{1,2})[\s._-]*e(\d{1,3})"
                 r"(?:[\s._-]*(?:-?\s*e|-)\s*(\d{1,3}))?(?![0-9])", re.I)
# --- ③ 1x03 / 03x05（``1920x1080`` 不会命中：``(?<![A-Za-z0-9])`` 挡住数字中间的位置）---
_叉集 = re.compile(r"(?<![A-Za-z0-9])(\d{1,2})[xX](\d{1,3})"
                 r"(?:[\s._-]*(?:-?\s*[xX]|-)\s*(\d{1,3}))?(?![0-9])")
# --- ④ E01-E12 / E08（``S01E…`` 由 ② 先命中，位置更靠左）---
_裸E = re.compile(r"(?<![A-Za-z0-9])[Ee](\d{1,3})(?:[\s._-]*(?:-?\s*[Ee]|-)\s*(\d{1,3}))?(?![0-9])")
# --- ⑤ 第03集 / 第3话 / 第十二集 / 第06回 ---
_第集 = re.compile(r"第\s*(" + _数字或中文 + r")\s*[集话話回]")
# --- ⑥ 03话 / 12集（没有"第"）---
_裸集 = re.compile(r"(?<![0-9A-Za-z第])(" + _数字或中文 + r")\s*[集话話回]")
# --- ⑦ 打包区间 01-12（要求两个端点都像集号，免得把 ``H265-10bit``/``2024-2025`` 当区间）---
_区间 = re.compile(r"(?<![0-9A-Za-z])(\d{1,4})\s*[-~]\s*(\d{1,4})(?![0-9])")
# --- ⑧ 合集/完结：没有集号，但它们是"剧集"的铁证 ---
_打包无集 = re.compile(r"合集|完结|全集|全季|整季|打包")
# --- ⑨ 特别篇（第 0 季）：SP01 里的 01 是集号，NCOP 后面没有数字就不是 ---
_特别词 = re.compile(r"(?<![A-Za-z0-9])(?:ncop|nced|ova|oad|sp|specials|special|"
                  r"特别篇|特别版|番外篇|番外|特典)(?![A-Za-z])", re.I)
#: 特别词后面**紧贴**的数字（``SP01`` / ``OVA.02``）。为什么不允许多个空格：
#: ``OVA [1080p]`` 里的 1080 是清晰度，不是集号 —— 中间隔了空格就必须当没看见。
_特别集号 = re.compile(r"(?:\s*[._-]\s*)?(\d{1,3})(?![0-9A-Za-z])")
# --- ⑩ 文件名里的季：S03 / Season 2 / 第3季 / 第二季（``S01E01`` 由 ② 处理）---
_文件名季 = re.compile(r"(?:^|(?<=[^A-Za-z0-9]))(?:(?:season|s)[\s._-]*0*(\d{1,2})(?![\s._-]*e\d)(?![0-9])"
                   r"|第\s*(\d{1,2})\s*[季部]|第\s*([零一二两三四五六七八九十]{1,3})\s*[季部])", re.I)
# --- ⑪ 年份（防分辨率：``1920x1080`` 里的 1920 不算年份）---
_括号年 = re.compile(r"[\[(]\s*((?:19|20)\d{2})\s*[\])]")
_裸年 = re.compile(r"(?<![0-9xX×])((?:19|20)\d{2})(?![0-9])(?![pPiI])(?![xX×]\d)")
# --- ⑫ 独立的裸数字（``146.SDR…`` / ``05.mkv`` / ``[05]``）---
#: 为什么捕获串里保留前导零：``05`` 与 ``5`` 的区别正是"这是集号"的最强信号，
#: 把 ``0*`` 写在捕获组外面就等于把这个信号丢了。
_开头数字 = re.compile(r"(?<![0-9A-Za-z])(\d{1,4})(?![0-9])")
#: ``10.Cloverfield.Lane`` 这类"数字 + 英文单词"的片名：数字后面紧跟大写开头的英文词。
_数字后像片名 = re.compile(r"^[\s._-]+[A-Z][a-z]{2,}")
#: 数字后面紧跟 ``-``/``~`` 且横线后面是空格/结尾（``12 - 某集标题``）：
#: 这是"集号 + 分集标题"的写法。为什么要求横线后面有空格/结尾：``Kaijuu 8-gou``
#: 这种罗马字片名里，数字后面也紧跟一个横线 —— 少了这个要求，"8号"会被读成第 8 集。
_数字后是横线 = re.compile(r"^\s*[-~](?:\s|$)")
#: 数字**前面**紧跟 ``-``/``~``（``咒术回战 - 12 [1080p]``）：番剧命名的另一大套路
#: ``标题 - 集号``（老实现只认"数字在前"，这一类全丢，评测报告第 17/18/19 条）。
#: 为什么敢认这条：``H265-10bit`` 这种"横线后面也是数字"的情况早已被"标签区间"排除掉了。
_数字前是横线 = re.compile(r"(?:^|[\s._])[-~]\s*$")


#: 数据源 ID 标签（``[tmdbid-123]``/``{imdbid-tt0816692}``）：里面的数字是**元数据**，
#: 既不是集号也不是年份 —— 老实现是先把它整块摘掉再找数字，结构层这里把它排除掉。
_数据源ID括号 = re.compile(r"[\[{]\s*(?:imdb|tmdb|tvdb)\s*(?:id)?\s*[-=:]\s*[^\]}\s]+\s*[\]}]", re.I)
#: 数字后面紧跟分隔符（``146.SDR``/``12.标题``）：这是"集号在最前面"的写法，
#: 老实现（``命名解析._摘开头集号``）认它；这里配合"数字前面没有实词"一起用。
_数字后是分隔符 = re.compile(r"^[\s._\-]")
#: 数字前面只有分隔符/括号（= 它就在名字开头）。
_头只剩分隔符 = re.compile(r"^[\s._\-\[\]()【】{}·|]*$")


def _在方括号里(文本: str, 位置: int) -> bool:
    """这个位置是不是落在 ``[...]`` 里面（``[05]`` 里的 05 是集号，方括号是强信号）。"""
    return 文本.rfind("[", 0, 位置) > 文本.rfind("]", 0, 位置)


def _后面紧接方括号(文本: str, 位置: int) -> bool:
    """数字后面（跳过分隔符）紧接的是不是 ``[``。

    用来区分两种"数字后面跟着拉丁词"：``10.Cloverfield.Lane`` 是片名的一部分，
    而 ``12 [Bilibili][WEB-DL]`` 后面那些词**在方括号里**，是平台/标签而不是标题
    （番剧命名的方括号里十有八九是元数据，真标题在方括号外面）。
    """
    位 = 位置
    while 位 < len(文本) and 文本[位] in " \t._-":
        位 += 1
    return 位 < len(文本) and 文本[位] == "["


def _是年份样子(文本: str) -> bool:
    """4 位数、落在 1900~今年+1 之间 → 更像年份而不是集号。

    为什么上界是"今年+1"：``Blade Runner 2049`` 的 2049 是片名，不是年份；
    未来年份只可能是片名的一部分（老实现也是这么防的）。
    """
    if len(文本) != 4 or not 文本.isdigit():
        return False
    号 = int(文本)
    return 1900 <= 号 <= time.localtime().tm_year + 1


def _扫标记(文本: str, 有季上下文: bool) -> list[_标记]:
    """把名字里的结构标记全找出来（不判断谁赢，交给 :func:`抽取` 按位置+优先级选）。

    ``扫描``：把方括号换成**等长**空格之后再匹配 —— 这样 ``[05]`` 里的 05 会被当成
    "被分隔符包住的独立数字"，而所有匹配位置又原样对应回 ``文本``。
    """
    扫描 = 文本.translate(str.maketrans({"[": " ", "]": " ", "(": " ", ")": " "}))
    # 数字落在这四类区间里就不是集号：发布标签、年份本身、分辨率对、数据源 ID 标签
    排除段 = (归一化.标签段们(扫描) + 归一化.分辨率段们(扫描)
            + [(m.start(), m.end()) for m in _裸年.finditer(扫描)]
            + [(m.start(), m.end()) for m in _数据源ID括号.finditer(文本)])
    标记们: list[_标记] = []

    def 有重叠(起: int, 终: int) -> bool:
        return any(起 < 终_ and 终 > 起_ for 起_, 终_ in 排除段)

    # ① 打包/更新（集 = 1，上界进 集到）
    for 正则 in (_更新至, _全N集, _N集全):
        for m in 正则.finditer(扫描):
            号 = 中文数字(m.group(1))
            if 号:
                标记们.append(_标记(m.start(), m.end(), 1, 集=1, 集到=号, 写法="打包上界"))
    # ② S/E
    for m in _季集.finditer(扫描):
        标记们.append(_标记(m.start(), m.end(), 2, 季=int(m.group(1)), 集=int(m.group(2)),
                        集到=int(m.group(3)) if m.group(3) else None, 写法="S01E01"))
    # ③ 1x03
    for m in _叉集.finditer(扫描):
        标记们.append(_标记(m.start(), m.end(), 3, 季=int(m.group(1)), 集=int(m.group(2)),
                        集到=int(m.group(3)) if m.group(3) else None, 写法="1x03"))
    # ④ E01-E12
    for m in _裸E.finditer(扫描):
        标记们.append(_标记(m.start(), m.end(), 4, 集=int(m.group(1)),
                        集到=int(m.group(2)) if m.group(2) else None, 写法="E01"))
    # ⑤ 第N集 / 第N话 / 第N回
    for m in _第集.finditer(扫描):
        号 = 中文数字(m.group(1))
        if 号 is not None:
            标记们.append(_标记(m.start(), m.end(), 5, 集=号, 写法="第N集"))
    # ⑥ N集 / N话 / N回
    for m in _裸集.finditer(扫描):
        号 = 中文数字(m.group(1))
        if 号 is not None:
            标记们.append(_标记(m.start(), m.end(), 6, 集=号, 写法="N集"))
    # ⑦ 打包区间 01-12（上界 < 1900 才认：``2024-2025`` 是年份区间，不是集号区间；
    #    区间端点落在发布标签里也不认：``Part.2 - 03`` 的 "2" 是"第 2 部"不是第 2 集）
    for m in _区间.finditer(扫描):
        if 有重叠(m.start(), m.end()):
            continue
        下, 上 = int(m.group(1)), int(m.group(2))
        if 0 < 下 < 上 < 1900:
            标记们.append(_标记(m.start(), m.end(), 7, 集=下, 集到=上, 写法="区间"))
    # ⑧ 合集/完结
    for m in _打包无集.finditer(扫描):
        标记们.append(_标记(m.start(), m.end(), 8, 是打包无集=True, 写法="合集/完结"))
    # ⑨ 特别篇（SP01 的 01 是集号）
    for m in _特别词.finditer(扫描):
        if (尾 := _特别集号.match(扫描[m.end():])):
            标记们.append(_标记(m.start(), m.end() + 尾.end(), 9, 集=int(尾.group(1)),
                            是特别=True, 写法="特别篇"))
            continue
        标记们.append(_标记(m.start(), m.end(), 9, 是特别=True, 写法="特别篇"))
    # ⑩ 文件名季
    for m in _文件名季.finditer(扫描):
        数字 = m.group(1) or m.group(2) or m.group(3)
        号 = 中文数字(数字)
        if 号 is not None:
            标记们.append(_标记(m.start(), m.end(), 10, 季=号, 写法="文件名季"))
    # ⑪ 独立裸数字（口径最松也最容易误判的一条，所以放在最后、判据写得最谨慎）
    for m in _开头数字.finditer(扫描):
        起, 终 = m.start(), m.end()
        数字 = m.group(1)
        if 有重叠(起, 终):
            continue                                  # 标签/年份/分辨率里的数字不是集号
        if _是年份样子(数字):
            continue                                  # 2012.mp4 / 1917.2019.1080p
        if len(数字) == 4 and not 数字.startswith("0") and not 有季上下文 \
                and not _在方括号里(文本, 起):
            continue                                  # 裸的 4 位数字（1408）更像片名/年份
        前导零 = len(数字) > 1 and 数字.startswith("0")
        in括号 = _在方括号里(文本, 起)
        尾 = 扫描[终:]
        头 = 扫描[:起]
        头空 = bool(_头只剩分隔符.match(头))
        尾空 = not 尾.strip(" \t._-")
        尾部裸 = not 归一化.清标题(尾)
        # ⚠️ 末尾**光秃秃**的裸数字要格外保守：``13 Going on 30.mkv`` 的 30、
        # ``Movie 3.mkv`` 的 3 都是片名的一部分（老实现坑 2 的回归测试钉着：
        # 没有前导零、没有季目录上下文、数字前面又有实词 → 不当集号；
        # ``Movie 03.mkv`` 才是第 3 集）。而 ``…Immortal.146.2160p…`` 里的 146
        # 后面还跟着标签，是合法集号 —— 两者的差别就是"数字后面还有没有东西"。
        可疑末尾裸数字 = (尾空 and not 前导零 and not in括号 and not 有季上下文
                    and not 头空 and not _数字后是横线.match(尾)
                    and not _数字前是横线.search(头))
        if 可疑末尾裸数字:
            continue
        if not (前导零 or in括号 or _数字后是横线.match(尾) or _数字前是横线.search(头)
                or 尾部裸 or (头空 and _数字后是分隔符.match(尾))):
            continue                                  # 数字后面还有实词 → 它是片名的一部分
        if not 前导零 and not in括号 and not _后面紧接方括号(文本, 终) \
                and _数字后像片名.match(尾):
            continue                                  # ``10.Cloverfield.Lane``
        标记们.append(_标记(起, 终, 11, 集=int(数字), 写法="裸数字"))
    return 标记们


# ============================ 标题清洗 ============================

_括号片段 = re.compile(r"\[([^\[\]]*)\]|\(([^()]*)\)")


def _切括号(文本: str) -> list[tuple[bool, str]]:
    """按方括号/圆括号切成 ``[(是否括号里, 文本)]``，括号外壳丢掉。"""
    出: list[tuple[bool, str]] = []
    位 = 0
    for m in _括号片段.finditer(文本):
        if m.start() > 位:
            出.append((False, 文本[位:m.start()]))
        出.append((True, m.group(1) if m.group(1) is not None else m.group(2)))
        位 = m.end()
    if 位 < len(文本):
        出.append((False, 文本[位:]))
    return [段 for 段 in 出 if 段[1].strip()]


def _像标题内容(文本: str) -> bool:
    """去掉标签后还剩不剩"像标题的字"（中文/日文/韩文，或 ≥2 个连续拉丁字母）。"""
    剩 = 归一化.去发布标签(归一化.去网址(文本 or ""))
    return bool(re.search(r"[\u4e00-\u9fff\u3040-\u30ff\uac00-\ud7af]|[A-Za-z]{2,}", 剩))


def _是组名(内容: str, 段们: list[tuple[bool, str]], 位置: int) -> bool:
    """开头那个方括号是不是字幕组/压制组的名字。

    两条判据（任一即可）：
    * 名字里有组名迹象（``字幕组``/``喵萌奶茶屋``/``Lilith-Raws``/``电影天堂``…）；
    * 它是**第一个**段，而且后面还有别的内容像标题 —— 番剧命名的固定套路是
      ``[组名] 标题 …``，光看 ``[Sakurato]`` 认不出是组名，但"后面跟着标题"能说明它是。
    第二条特意要求"后面有标题"：``[葬送的芙莉莲][05][1080p]`` 这种"标题就在第一个方括号里"
    的写法才不会被砍掉。
    """
    if 归一化.有组名迹象(内容) or 归一化.是广告内容(内容) or 归一化.是数据源ID(内容):
        return True
    if 位置 != 0:
        return False
    后面 = [文 for _, 文 in 段们[位置 + 1:]]
    return any(_像标题内容(文) for 文 in 后面)


def _清前缀(文本: str) -> str:
    """把"切点之前的那一段"清成标题：丢组名/标签/广告方括号，脱掉标题方括号的壳。"""
    段们 = _切括号(文本 or "")
    留下: list[str] = []
    for i, (是括号, 内容) in enumerate(段们):
        if not 是括号:
            留下.append(内容)
            continue
        if 归一化.是数据源ID(内容) or 归一化.是广告内容(内容) or 归一化.是发布标签(内容) \
                or not 归一化.有实词(内容):
            continue
        if _是组名(内容, 段们, i):
            continue
        留下.append(内容)
    return 归一化.清标题(" ".join(留下))


# ============================ 年份 / 标题 / 类型 ============================


def _选年份(文本: str, 前缀: str) -> tuple[int | None, int, int]:
    """按口径选年份，返回 ``(年份, 起点, 终点)``；选不出来就是 ``(None, -1, -1)``。

    口径是"从后往前取**能留下非空标题**的那个"：
    * ``2012.mp4``：唯一的候选被摘掉后标题空了 → 年份 null（2012 是片名）；
    * ``1917.2019.1080p``：摘 2019 还剩 1917 → 2019 是年份；
    * ``2001.A.Space.Odyssey.1968``：摘 1968 还剩 2001 → 1968 是年份；
    * ``Blade.Runner.2049.2017``：2049 超过"今年+1"，压根不是候选，标题里的 2049 留着。

    括号里的年份（``流浪地球 (2019)``）优先：Jellyfin 官方写法里它就是年份，
    比裸数字可信。
    """
    候选: list[re.Match] = list(reversed(list(_括号年.finditer(文本))))
    if not 候选:
        候选 = list(reversed(list(_裸年.finditer(文本))))
    for m in 候选:
        年 = int(m.group(1))
        if not (1900 <= 年 <= time.localtime().tm_year + 1):
            continue
        新前缀 = 前缀[:m.start()] + " " + 前缀[m.end():] if m.start() < len(前缀) else 前缀
        if _清前缀(新前缀):
            return 年, m.start(), m.end()
    return None, -1, -1


def _目录链年份(目录们: Sequence[str]) -> int | None:
    """目录链（由近到远）里**括号中的**年份；找不到就是 ``None``。

    只认括号：``剧名 (2016)`` 是 Jellyfin 官方写法；而 ``2012``/``1917`` 这种
    裸数字目录多半是分类目录或片名，拿来当年份会让整部作品配错。
    """
    for 名 in 目录们:
        文本 = 归一化.转半角(名 or "")
        if not 文本:
            continue
        for m in reversed(list(_括号年.finditer(文本))):
            年 = int(m.group(1))
            if 1900 <= 年 <= time.localtime().tm_year + 1:
                return 年
    return None


def _定目录标题(目录们: Sequence[str]) -> str:
    """目录链（由近到远）里第一个"不是季目录、也不是分类目录"的名字，就是标题来源。"""
    for 名 in 目录们:
        文本 = 归一化.去网址(归一化.转半角(名 or ""))
        if not 文本.strip() or 是季目录(文本) or 是特别篇目录(文本) or 归一化.是通用目录(文本):
            continue
        净 = _清前缀(_去目录年份(文本))
        if 净:
            return 净
    return ""


def _去目录年份(文本: str) -> str:
    """目录名里的年份也摘掉（``沙丘 (2021)`` → ``沙丘``）。

    为什么不复用 :func:`_选年份`：目录名没有"集号切点"，年份出现在哪都不影响
    "拿它当标题"的意愿 —— 只要摘掉后还剩字就行；摘完不剩字（目录就叫 ``2012``）
    就保留原名，那是它唯一能提供的信息。
    """
    出 = 文本
    位置们 = sorted([m for m in _括号年.finditer(文本)] + [m for m in _裸年.finditer(文本)],
                 key=lambda m: m.start(), reverse=True)
    for m in 位置们:
        剩 = (出[:m.start()] + " " + 出[m.end():]).strip()
        if 归一化.清标题(归一化.去发布标签(剩)):
            出 = 剩
    return 出


# ============================ 主入口 ============================


def _合并目录链(父目录名: str, 路径目录们: Sequence[str],
            目录链: Iterable[str]) -> list[str]:
    """把三种来源的目录信息合成"由近到远"的一条链，去重保序。

    为什么要允许"从路径里自己往上找"：``葬送的芙莉莲/Season 01/05.mkv`` 的标题在**祖父目录**
    里，只给一层父目录（``Season 01``）永远抽不出标题（评测报告第 3 条）。
    """
    出: list[str] = []
    for 名 in [父目录名, *路径目录们, *目录链]:
        名 = (名 or "").strip()
        if 名 and 名 not in 出:
            出.append(名)
    return 出


def 抽取(文件名: str, 父目录名: str = "", 目录链: Iterable[str] = ()) -> 结构结果:
    """抽出一条样本的结构。``文件名`` 可以只是文件名，也可以是整条路径。

    ``父目录名``：文件所在目录（可为空，空的就从 ``文件名`` 路径里取）。
    ``目录链``：**由近到远**的更上层目录名（含紧邻父目录也行，会去重），
    给那些"只拿到名字、拿不到整条路径"的调用方用。
    """
    段们 = 归一化.切路径(文件名)
    名 = 段们[-1] if 段们 else ""
    路径目录们 = list(reversed(段们[:-1]))
    链 = _合并目录链(父目录名, 路径目录们, 目录链)
    结果 = 结构结果(文件名=名, 目录链=tuple(链))
    if not 名:
        return 结果

    主名, 扩展名 = 归一化.切扩展名(名)

    文本 = 归一化.转半角(主名)
    文本 = 归一化.去网址(文本)
    文本 = 归一化.去发布组尾巴(文本)

    目录季, 目录特别 = _扫目录季(链)
    标记们 = _扫标记(文本, 有季上下文=目录季 is not None)
    标记们.sort(key=lambda m: (m.起点, m.优先级))
    切点 = 标记们[0].起点 if 标记们 else len(文本)
    前缀 = 文本[:切点]

    文件季 = next((m.季 for m in 标记们 if m.季 is not None), None)
    集标记 = next((m for m in 标记们 if m.集 is not None), None)
    集 = 集标记.集 if 集标记 else None
    集到 = 集标记.集到 if 集标记 else None
    特别 = 目录特别 or any(m.是特别 for m in 标记们)
    打包无集 = any(m.是打包无集 for m in 标记们)
    结果.特别篇 = 特别
    结果.集 = 集
    结果.集到 = 集到

    # 季：目录 > 文件名 > 特别篇(0) > 默认 1（口径第 1 条，顺序不能动）
    if 目录季 is not None:
        结果.季, 结果.季来源 = 目录季, "目录"
    elif 文件季 is not None:
        结果.季, 结果.季来源 = 文件季, "文件名"
    elif 特别:
        结果.季, 结果.季来源 = 0, "特别篇"
    elif 集 is not None:
        结果.季, 结果.季来源 = 1, "默认"

    # 年份（口径第 3 条）——标题得先能算出来，年份才知道摘哪个
    结果.年份, 年起, 年终 = _选年份(文本, 前缀)
    文件内年份 = 结果.年份 is not None
    if not 文件内年份:
        # 文件名里没有年份时，**目录名括号里的年份**就是它的年份
        # （Jellyfin 官方写法：``怪奇物语 (2016)/Season 01/…``）。
        # 为什么值得单独抽：年份是打分里最硬的一条独立证据 —— "剧名与年份都对得上"
        # 才敢自动入库（见 ``决策._精确一致``）；只看文件名的话，这种最规范的目录
        # 反而永远拿不到年份信号。**只认括号里的**（``(2016)``）：裸数字目录
        # （``2012``/``1917``）是分类目录或片名，拿来当年份会错得离谱。
        结果.年份 = _目录链年份(链)

    前缀去 = 前缀
    if 文件内年份 and 年起 < len(前缀):
        前缀去 = 前缀[:年起] + " " + 前缀[年终:]
    结果.文件标题 = _清前缀(前缀去)
    结果.目录标题 = _定目录标题(链)
    结果.标题 = 结果.文件标题 or 结果.目录标题
    if not 结果.标题:
        # 兜底：切点之前确实什么都没有（``05.mkv`` / ``[05].mkv`` / ``S01E01 - 1080p.mkv``），
        # 就把整名去掉标记与年份再清一遍。
        # ⚠️ **必须先把标记本身挖成等长空格**：不挖的话 ``S01E01 - 1080p.mkv`` 会把
        # 季集标记当成片名（老实现"坑 5"的回归测试盯着这条：标题宁可空着，
        # 也不能是 ``S01E01`` —— 那会被下游当成片名去搜）。
        兜文本 = 文本
        for 标 in sorted(标记们, key=lambda x: -x.起点):
            兜文本 = 兜文本[:标.起点] + " " * (标.终点 - 标.起点) + 兜文本[标.终点:]
        兜 = _清前缀(兜文本)
        if 结果.年份 is not None:
            兜 = _清前缀(兜.replace(str(结果.年份), " "))
        结果.标题 = 兜

    # 类型：有季/集/特别篇/打包信号 → 剧集；否则只有"真的视频文件"才敢说电影。
    # 为什么没有扩展名就不敢说电影：没有扩展名的东西更可能是个**目录**
    # （``猜剧集路径`` 那条路会把目录名喂进来），说成电影会让库里凭空多一条错记录。
    是媒体文件 = 扩展名 in 归一化.视频扩展名
    有剧集信号 = 集 is not None or 结果.季 is not None or 特别 or 打包无集
    if 扩展名 and not 是媒体文件:
        结果.类型 = "unknown"        # 图片/字幕/nfo 不是媒体条目（季集照抽：字幕配对要用）
    elif 有剧集信号:
        结果.类型 = "tv"
    elif 结果.标题 and 是媒体文件:
        结果.类型 = "movie"
    else:
        结果.类型 = "unknown"
    return 结果
