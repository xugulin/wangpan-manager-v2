"""② 结构抽取：从"文件名 + 目录链"里抽出 ``标题 / 年份 / 类型 / 季 / 集 / 集到``。

口径（**权威**，来自用户确认 + ``数据/识别评测.md``）
==================================================
这一层是纯规则，所以它必须接近满分（结构 ≥ 99%、标题清洗 ≥ 98%，
见 ``docs/识别/00_架构.md`` 第二节）。四条口径原文照抄，谁都不许自己改：

1. **季优先级**：目录里的季 > 文件名里的季 > 默认 1。
   "有集号但两处都没写季" → 季 = 1（Jellyfin 对没有季目录的剧的默认行为，
   真机 ``146.SDR…`` / ``131.SDR…`` 两条样本确认过）。反过来，
   **没有集号的整季包/合集** → 季 = null（没有集号就不许瞎填 1）。
2. **打包写法**（``E01-E12`` / ``01-12`` / ``更新至12`` / ``全12集``）语义都是
   "从第 1 集开始的打包" → 集 = 1，区间上界放 ``集到``（标注 schema 里没有这一列）。
3. **年份**：从后往前取"能留下非空标题"的那个（``2012.mp4`` → 年份 null；
   ``1984.1984`` → 1984；``2001.A.Space.Odyssey.1968`` → 1968）。
4. **特别篇 / NCOP / NCED / OVA / SP → 第 0 季**，并把这类词从标题里摘掉。
5. 中英混排的标题**两种写法都保留**（``葬送的芙莉莲 Sousou no Frieren``），
   因为 ③ 候选生成要把两种写法都拿去搜。

设计：先把"名字里的结构标记"全部找出来（集号/季/年份/打包/特别篇），
**切点 = 最靠左的那个标记**，切点之前才是标题。为什么这么切：

* ``仙逆.Renegade.Immortal.146.2160p…`` 集号在标题后面 → 标题在前面；
* ``03 小标题.mkv``、``12 - 某集标题.mp4`` 集号在最前面，切点之前是空的 →
  标题自然落到目录名上（这两条的期望标题正是父目录 ``某剧``）——
  **不需要为"单集标题"单独写规则**，切点机制天然把"集号在前的单集标题"排除掉了；
* ``[Sakurato] Sousou no Frieren [03][AVC-8bit 1080p AAC][CHS]`` 集号在方括号里 →
  切点之前还剩"组名 + 标题"，组名方括号被丢掉，标题留下。

依赖方向：只用 ``wangpan.identify.归一化``（以及标准库），
**绝不 import 现有 scrape 层** —— 那一层正在被改造成"兼容薄壳"，谁依赖谁就跟着碎。
"""

