#: 分隔符：文件名里用来分段的符号（P1 的归一化会统一一遍，这里再兜一次底）
_分隔符 = re.compile(r"[._\-–—~+\[\]()【】（）{}<>《》「」『』:：;；,，!！?？|/\\'\"“”‘’*]+")
_空白 = re.compile(r"\s+")
_中日韩 = re.compile(r"[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uac00-\ud7af]+")
_英数词 = re.compile(r"[A-Za-z][A-Za-z0-9']*|\d+")
_纯数字 = re.compile(r"^\d{1,4}$")

#: **带连字符的标记要先合并**，否则会被 :data:`_分隔符` 劈成两半，
#: 其中半个还可能撞上正常片名：``WEB-DL`` → ``WEB`` + ``DL``（DL 不是词），
#: ``Blu-ray`` → ``Blu`` + ``ray``（**ray 是 2004 年的电影《Ray》**！）。
#: 所以只对"能确定是标记家族"的几个写法下手，不做通用连字符合并
#: （通用合并会把 ``Spider-Man`` 与 ``Three-Body`` 粘成一体，那才是灾难）。
_连字标记 = (
    (re.compile(r"(?i)web[\-_.]?dl"), "webdl"),
    (re.compile(r"(?i)web[\-_.]?rip"), "webrip"),
    (re.compile(r"(?i)blu[\-_.]?ray"), "bluray"),
    (re.compile(r"(?i)bd[\-_.]?rip"), "bdrip"),
    (re.compile(r"(?i)br[\-_.]?rip"), "brrip"),
    (re.compile(r"(?i)hd[\-_.]?rip"), "hdrip"),
    (re.compile(r"(?i)dvd[\-_.]?rip"), "dvdrip"),
    (re.compile(r"(?i)dts[\-_.]?hd"), "dtshd"),
    (re.compile(r"(?i)dd\+"), "ddp"),
)


def 清洗(文本: Any) -> str:
    """轻量清洗：全角→半角、合并连字标记、分隔符→空格、压空白。

    **不在这里做 P1 的活**（去广告尾巴、统一季集写法），因为 P2 拿到的可能是
    ``标题候选们`` 或目录名这种"半成品"，只需要一个稳定的分词基础。
    用 NFKC 而不是自己写全角映射表：中文全角数字/字母/标点它一次全cover，
    而且 ``Ⅳ`` 这种罗马数字也会变成 ``IV``（``Planet Earth II`` 这类标题用得上）。
    """
    文本 = unicodedata.normalize("NFKC", str(文本 or "")).strip()
    if not 文本:
        return ""
    for 模式, 替换 in _连字标记:
        文本 = 模式.sub(替换, 文本)
    return _空白.sub(" ", _分隔符.sub(" ", 文本)).strip()


def 分词(文本: str) -> list[str]:
    return [x for x in 清洗(文本).split(" ") if x]


def 含中文(文本: str) -> bool:
    return bool(_中日韩.search(文本 or ""))


def 是纯数字(文本: str) -> bool:
    return bool(_纯数字.match((文本 or "").strip()))


def _移除标记(片段: str) -> tuple[str, int]:
    """把一个 token 里"看得出来的标记子串"抹掉，返回 ``(剩下的信息量, 命中了几处标记)``。

    用途只有一个：判断 ``4K高码``（= ``4k`` + ``高码``）这种**拼接型**标记。
    只按词表与正则删，不做模糊匹配，避免把正常标题啃掉一块。
    命中数要一起返回：``2012`` 抹完后当然什么都不剩，但它一个标记都没命中过，
    不能因此被当成标记（这正是"纯数字不能一律丢"的另一种踩法）。
    """
    剩余 = 片段.lower()
    命中 = 0
    for 词 in 标签词表:
        if 词 in 剩余:
            命中 += 剩余.count(词)
            剩余 = 剩余.replace(词, "")
    for 正则 in 标签正则们:
        剩余, 次数 = 正则.subn("", 剩余)
        命中 += 次数
    return re.sub(r"[\d\W_]+", "", 剩余), 命中


def 是标签(片段: str) -> bool:
    """这个 token 是不是"纯标记"（画质/编码/字幕/站名…）？

    ``1080p`` / ``x265`` / ``中字`` / ``S01E138`` / ``第03集`` / ``4K高码`` 都算；
    ``沙丘2`` / ``1917`` / ``10`` / ``The`` / ``Se7en`` 都不算。
    """
    token = (片段 or "").strip()
    if not token:
        return True
    if token.lower() in 标签词表:
        return True
    if any(正则.match(token.lower()) for 正则 in 标签正则们):
        return True
    # 组合型：必须"真认出过标记"且抹完不剩东西，才算整个 token 是标记的堆叠。
    # 少了"必须命中过"这一条，纯数字（2012）会被误判成标记 —— 那就把片名删瞎了。
    剩余, 命中 = _移除标记(token)
    return 命中 > 0 and 剩余 == ""


def 是通用目录(文本: str) -> bool:
    return 清洗(文本).strip().lower() in 通用目录词


def 去重键(文本: str) -> str:
    """查询词的去重键：忽略大小写、空格与标点。

    ``Spider-Man`` 与 ``Spider Man`` 送进 TMDB 是同一个查询（标注集也是这么比标题的），
    不去重就会白发一次请求、还会把同一部片算成两批候选。
    """
    return re.sub(r"[^0-9a-z\u4e00-\u9fff\u3040-\u30ff\uac00-\ud7af]+", "",
                  (文本 or "").lower())


def 去标签(文本: str, *, 年份: Optional[int] = None, 季: Optional[int] = None,
           集: Optional[int] = None) -> tuple[str, list[str]]:
    """按 token 去掉标记、"结构数字"与"数字残渣"，返回 ``(留下来的文本, 丢掉了什么)``。

    三类要丢的东西，每一类都有真机理由：

    * **标记**：``1080p`` / ``x265`` / ``中字``（见 :func:`是标签`）；
    * **结构数字**：等于 年份 / 季 / 集 的 token（见模块开头的"纯数字不能一律丢掉"）。
      **多 token 时才摘**：``1917 2019`` 里的 2019 是年份要摘掉，
      但 ``1984 1984`` 摘完就空了 —— 那就一个都不摘（片名可能就叫 1984）；
    * **数字残渣**：贴着标记或贴着别的数字的纯数字（``DDP5 1`` 里的 1、``5 1`` 里的两个数）。
      ``2049`` / ``10`` / ``2001`` 这些真正属于片名的数字**不贴标记、也不成串**，
      所以留得下来；而"被小数点劈开的音轨号 5.1"必然贴着标记或成串，必然被丢掉。
      判断邻居时把结构数字当"透明"：``1917 2019`` 的 2019 会被摘掉，
      它不该把 1917 连累成残渣。
    """
    tokens = 分词(文本)
    if not tokens:
        return "", []
    结构数字 = {str(x) for x in (年份, 季, 集) if x is not None}
    标记位 = [是标签(t) for t in tokens]
    数字位 = [是纯数字(t) for t in tokens]

    def 结构数字位(位: int) -> bool:
        return 0 <= 位 < len(tokens) and tokens[位] in 结构数字

    def 数字残渣(位: int) -> bool:
        for 邻居 in (位 - 1, 位 + 1):
            if 结构数字位(邻居):
                continue                      # 会被摘掉的结构数字不算邻居
            if 0 <= 邻居 < len(tokens) and (标记位[邻居] or 数字位[邻居]):
                return True
        return False

    丢掉: list[str] = []
    留下: list[str] = []
    for 位, token in enumerate(tokens):
        if 标记位[位] or 结构数字位(位) or (数字位[位] and 数字残渣(位)):
            丢掉.append(token)
        else:
            留下.append(token)
    # 去重：``1984 1984``（片名 + 年份写成同一个数）留下一个就够，重复的只会浪费一次请求。
    留下 = list(dict.fromkeys(留下))
    if not 留下:
        # 全被摘光了，但"摘它的理由"可能只是"它等于年份"—— 而片名本来就可能跟年份同值
        # （``1984.1984.1080p``）。这时留下一个"非标记、非残渣"的 token 当兜底，
        # 让上层按"纯数字标题降权保留"或"这是集号要丢"去判（``146`` 会在这里被上层毙掉）。
        候补 = [t for 位, t in enumerate(tokens)
               if not 标记位[位] and not (数字位[位] and 数字残渣(位))]
        if 候补:
            留下 = [候补[0]]
    if not 留下:
        return "", 丢掉
    return " ".join(留下), 丢掉


def 中文段(文本: str) -> str:
    """取文本里的中文/日文/韩文片段（丢掉英文与数字），空格连接。

    中英混排的标题（``仙逆 Renegade Immortal``）必须**分段**：TMDB 的标题字段是单一语言的，
    拿整串去搜两边都不匹配；标注集里"中英混排的期望标题 = 两种写法都保留"就是这个意思。
    """
    return " ".join(_中日韩.findall(清洗(文本))).strip()


def 英文段(文本: str, *, 年份: Optional[int] = None, 季: Optional[int] = None,
           集: Optional[int] = None) -> str:
    """取文本里的英文/数字片段（丢掉中日韩），空格连接。

    **数字要留**：``Blade Runner 2049`` 与 ``Blade Runner`` 是两部电影，
    ``2001 A Space Odyssey`` 的 2001 也是片名的一部分。只有等于 年份/季/集 的
    token 才摘（那才是结构信息）。但**整段里必须至少有一个字母**：
    ``沙丘2`` 的 "2" 是片名里的序号，不是"英文名"，把它当英文段送出去只会白搜一次。
    """
    词们 = _英数词.findall(清洗(文本))
    结构数字 = {str(x) for x in (年份, 季, 集) if x is not None}
    留下 = [w for w in 词们 if not 是标签(w) and w not in 结构数字]
    if not 留下 or not any(re.search(r"[A-Za-z]", w) for w in 留下):
        return ""
    return " ".join(留下)


def _语言(文本: str) -> str:
    中 = 含中文(文本)
    英 = bool(re.search(r"[A-Za-z]", 文本 or ""))
    if 中 and 英:
        return "混"
    return "zh" if 中 else ("en" if 英 else "")


