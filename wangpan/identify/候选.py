# ============================ 别名表 ============================


def _拉起别名(值: Any) -> list[str]:
    """别名表的一个值 → 一批别名文本。

    学习层（P4）是唯一写入方，但它写什么形状还没定死（可能是 str、可能是 list、
    也可能是 ``{"标题": …, "tmdb_id": …}`` 这种带元信息的 dict），这里全部接住，
    只取"能当查询词用"的字符串。数字（比如 tmdb id）不当查询词。
    """
    if 值 is None:
        return []
    if isinstance(值, str):
        return [值.strip()] if 值.strip() else []
    if isinstance(值, Mapping):
        出: list[str] = []
        for 键 in ("标题", "别名", "查询", "名字", "名称", "title", "name", "query", "aliases"):
            if 键 in 值:
                出.extend(_拉起别名(值[键]))
        if not 出:                      # 没认出形状就把值里的字符串都当别名
            出 = [str(x).strip() for x in 值.values() if isinstance(x, str) and x.strip()]
        return 出
    if isinstance(值, Iterable):
        出 = []
        for x in 值:
            出.extend(_拉起别名(x))
        return 出
    if isinstance(值, int):             # 纯数字（多半是 tmdb id）不能当查询词
        return []
    return []


def _观察键们(文本们: Sequence[str]) -> set:
    """观察到的名字 → 一批"比中键"，**同一条文本的几种合理写法都要算**。

    两个真机理由：
    * 别名库里存的是**单一语言**的写法（"仙逆" 或 "Renegade Immortal"），
      而文件名常常是中英混排（"仙逆 Renegade Immortal"）—— 拿整串比永远比不中，
      所以每条文本都要拆出中文段/英文段一起比；
    * 别名库是学习层在**它看到的名字**上写下的，那个名字可能带着画质标签
      （``仙逆.4K高码.SDR.60fps``）。所以去标签后的形式也必须一起比，
      否则同一个目录换个清晰度版本就"不认识"了。
    """
    键们: set = set()
    for 文本 in 文本们:
        变体们 = [清洗(文本)]
        去标, _ = 去标签(变体们[0])          # 这里不带结构数字：判断别名时还不知道 季/集
        变体们.append(去标)
        for 变体 in 变体们:
            键们.add(去重键(变体))
            键们.add(去重键(中文段(变体)))
            键们.add(去重键(英文段(变体)))
    return {x for x in 键们 if x}


def 别名命中(观察文本们: Sequence[str], 别名表: Optional[Mapping]) -> list[tuple[str, str]]:
    """别名表里命中哪些 → ``[(别名文本, 命中的原文), …]``。

    **两个方向都认**：学习层将来可能写 ``{"仙逆": "Renegade Immortal"}``（键=看过的名字），
    也可能写 ``{"Renegade Immortal": ["仙逆"]}``（键=标准名）。方向搞错就等于别名库白建，
    而两个方向都试的代价只是建索引时多写一行。命中的原文会记进备注，方便查"这条别名
    是被谁带出来的"。
    """
    if not 别名表:
        return []
    观察键们 = _观察键们(观察文本们)
    if not 观察键们:
        return []
    出: list[tuple[str, str]] = []
    已见: set[str] = set()
    for 键, 值 in 别名表.items():
        规范们 = [x for x in _拉起别名(值) if x and not 是标签(x)]
        键文本 = str(键 or "").strip()
        # 方向一：观察到的文本 == 键 → 输出值
        if 去重键(键文本) in 观察键们:
            for 别名 in 规范们:
                if 去重键(别名) not in 已见:
                    已见.add(去重键(别名))
                    出.append((别名, 键文本))
        # 方向二：观察到的文本 == 某个值 → 输出键
        for 别名 in 规范们:
            if 去重键(别名) in 观察键们 and 键文本 and 去重键(键文本) not in 已见:
                已见.add(去重键(键文本))
                出.append((键文本, 别名))
    return 出


