@dataclass(frozen=True)
class 查询词:
    """一个送去 TMDB 搜的查询词（带"它是从哪儿来的"和"有多大把握"）。"""

    文本: str
    来源: str
    权重: float
    #: ``zh`` / ``en`` / ``混``：⑤ 打分的"中英分开算相似度"要靠它，
    #: 不能到了打分那一步再从字符串猜（那时已经丢了来源信息）。
    语言: str = ""
    #: 备查：为什么给它这个权重/为什么留下它（真网探测脚本会打出来）。
    备注: str = ""
    #: 同一个查询词还从哪些来源出现过（去重时被并掉的）—— 证据越多，⑤ 越敢信。
    其它来源: tuple = ()

    def 可读(self) -> str:
        return f"{self.文本}｜{self.来源}｜权重 {self.权重:.0f}" + \
            (f"｜{self.备注}" if self.备注 else "")


@dataclass
class 查询集合:
    """③ 的产物：有序查询词们 + 一个**独立的**年份过滤条件 + 结构信息。

    年份为什么不拼进查询词：TMDB 的 ``year`` / ``first_air_date_year`` 是**过滤参数**
    （见 ``wangpan/scrape/tmdb.py`` 的 ``搜电影``/``搜剧集``），拼进 ``query`` 里会让
    "沙丘 2021" 这种串匹配不到官方标题"沙丘"；而且年份是"硬过滤还是软过滤"要由 ④ 检索
    按召回情况决定（第一年对不上时应该退回去年），塞进字符串里就没这个余地了。
    """

    查询词们: list[查询词] = field(default_factory=list)
    年份: Optional[int] = None
    类型: str = "unknown"                  # tv / movie / unknown
    季: Optional[int] = None
    集: Optional[int] = None
    标题: str = ""                         # 结构给的主标题（调试用，不参与检索）
    #: 被丢掉的候选文本 → 原因。**故意留着**：真网探测脚本要靠它回答"为什么没搜某个词"，
    #: 调规则时也不用去猜。
    丢弃们: list[tuple[str, str]] = field(default_factory=list)

    def 文本们(self) -> list[str]:
        return [x.文本 for x in self.查询词们]

    def 最高权重(self) -> float:
        return max((x.权重 for x in self.查询词们), default=0.0)

    def 空的(self) -> bool:
        return not self.查询词们

    def 汇总(self) -> str:
        if not self.查询词们:
            return "（没有查询词）"
        return " + ".join(f"{x.文本}({x.来源},{x.权重:.0f})" for x in self.查询词们)


