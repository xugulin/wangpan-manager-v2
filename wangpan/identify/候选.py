"""③ 候选生成：把一个"结构抽取结果"摊成**多个有序查询词**（P2 的左半边）。

为什么不是一个查询词
====================
真机的现状（``docs/识别/00_架构.md`` 第一节）是"只搜一次、只有一个查询词"：
``146.SDR.8bit.2160p.60fps.DDP5.1.WEB-DL.H265.mp4`` 这种被网盘改名规避限制的文件，
清洗出来的标题必然是垃圾（``146 SDR 60fps DDP5 1``），拿它去搜一定搜不到；
而真正能定位作品的"仙逆"两个字**躺在目录名里**，旧实现根本不看目录。
把 文件标题 / 每一层目录 / 别名库 / 中文段 / 英文段 都摊成查询词，召回才不靠运气 ——
这是 P2 验收指标"候选召回 ≥ 99%"的前提，也是 ④ 检索"多查询 × 双接口"的输入。

三条设计原则
============
1. **纯函数**：不联网、不读盘、不打日志。只是字符串 → 字符串的映射，
   所以能拿标注集逐条钉住（``tests/test_识别候选.py``）。
2. **不 import P1 的模块**：入参是鸭子类型（``getattr`` 能取到 ``标题``/``年份``/``类型``/
   ``季``/``集``/``标题候选们`` 就行）。P1 的 ``结构.py`` 与 P2 是并行施工的，
   强耦合会让两边互相撞车；鸭子类型还能让本模块直接吃 dict 与测试替身。
3. **不许为个案写死**：规则必须是"能解释、能泛化"的字符串规则（标签词表 + 正则 +
   通用目录词表）。个案进标注集（``数据/识别标注.jsonl``），不进 ``if``。

一个容易踩的坑：**纯数字不能一律丢掉**
======================================
``data/识别标注.jsonl`` 里有 ``2012.mp4``（片名就叫 2012）、``1984.1984.1080p.mkv``、
``1917.2019.1080p…``、``10.Cloverfield.Lane``、``Blade.Runner.2049`` —— 一把梭"删掉纯数字"
会把这些片子一起删瞎（``Blade Runner`` 与 ``Blade Runner 2049`` 是两部电影！）。
这里的分寸是：
* 数字**等于**结构里的 集 / 季 → 是结构信息，丢（``146``、``05``、``第03集``）；
* 数字**等于**结构里的 年份 → 丢（年
  份是过滤条件，见 :func:`生成查询` 的返回值），但**整条文本只有它一个 token 时要留下**
  （``1984`` / ``2012`` 就是片名本身）；多 token 时把年份 token 摘掉（``1917 2019`` → ``1917``）；
* 与结构无关的数字一律留（``2049``、``10``、``2001``）。
"""

