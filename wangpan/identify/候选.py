def 取属性(对象: Any, 名字: str, 默认: Any = None) -> Any:
    """dataclass / 普通对象 / dict 三种都认（P1 的结果模型还没定死，别逼它迁就我）。"""
    if 对象 is None:
        return 默认
    if isinstance(对象, Mapping):
        值 = 对象.get(名字, 默认)
    else:
        值 = getattr(对象, 名字, 默认)
    return 默认 if 值 is None else 值


def _取数字(对象: Any, 名字: str) -> Optional[int]:
    值 = 取属性(对象, 名字)
    if 值 is None or 值 == "":
        return None
    try:
        return int(值)
    except (TypeError, ValueError):
        try:
            return int(float(值))
        except (TypeError, ValueError):
            return None


def _取文本们(对象: Any, 名字: str) -> list[str]:
    """``标题候选们`` 这种字段：list / tuple / set / 单个字符串 / dict 全都接住。"""
    值 = 取属性(对象, 名字)
    if 值 is None:
        return []
    if isinstance(值, str):
        return [值] if 值.strip() else []
    if isinstance(值, Mapping):
        值 = list(值.values())
    if isinstance(值, Iterable):
        return [str(x).strip() for x in 值 if isinstance(x, (str, int)) and str(x).strip()]
    return []


