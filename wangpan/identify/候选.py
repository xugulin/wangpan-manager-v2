class _收集器:
    """按"来源优先级"收集查询词：同一文本被多个来源命中时保留最高权重那个。"""

    def __init__(self) -> None:
        self._表: dict[str, 查询词] = {}
        self.丢弃们: list[tuple[str, str]] = []

    def 加(self, 文本: str, 来源: str, 权重: float, 备注: str = "") -> None:
        文本 = (文本 or "").strip()
        if not 文本:
            return
        键 = 去重键(文本)
        if not 键:
            return
        新 = 查询词(文本=文本, 来源=来源, 权重=float(权重), 语言=_语言(文本), 备注=备注)
        旧 = self._表.get(键)
        if 旧 is None:
            self._表[键] = 新
            return
        if 新.权重 > 旧.权重:                    # 换更强的来源，但把旧的记成"其它来源"
            self._表[键] = 查询词(文本=新.文本, 来源=新.来源, 权重=新.权重, 语言=新.语言,
                                备注=新.备注,
                                其它来源=tuple(list(旧.其它来源) + [旧.来源]))
        elif 旧.来源 != 新.来源 and 新.来源 not in 旧.其它来源:
            self._表[键] = 查询词(文本=旧.文本, 来源=旧.来源, 权重=旧.权重, 语言=旧.语言,
                                备注=旧.备注,
                                其它来源=tuple(list(旧.其它来源) + [新.来源]))

    def 丢(self, 文本: str, 原因: str) -> None:
        记录 = ((文本 or "").strip(), 原因)
        if 记录 not in self.丢弃们:            # 同一个标记（2160p）会被丢很多次，去重让记录可读
            self.丢弃们.append(记录)

    def 产物(self, 最多: int) -> list[查询词]:
        # 稳定排序：权重高的在前，同权重的保持"先加进来的在前"（文件标题优先于目录）。
        词们 = sorted(self._表.values(), key=lambda x: -x.权重)[:最多]
        return 词们


def _按来源摊开(收集: _收集器, 文本: str, 来源: str, 基准权重: float,
               结构数字: dict, *, 备注前缀: str = "") -> None:
    """一条"可能含标题的文本" → 最多 3 个查询词（整串 / 中文段 / 英文段）。

    为什么一条文本要摊三段：``仙逆 Renegade Immortal`` 这种中英混排的名字，
    整串搜不到、中文段能搜到、英文段也能搜到（真网实测：两条都命中同一部剧 id 223911）。
    三段都出，⑤ 打分拿"证据条数"去加权，比在这层赌哪段对要稳得多。
    """
    文本 = (文本 or "").strip()
    if not 文本:
        return
    年份, 季, 集 = 结构数字["年份"], 结构数字["季"], 结构数字["集"]
    干净, 丢掉 = 去标签(文本, 年份=年份, 季=季, 集=集)
    for 片段 in 丢掉:
        if 是标签(片段):
            收集.丢(片段, "画质/编码/字幕等标记")
    if not 干净:
        收集.丢(文本, "整条都是标记/结构数字，没有标题信息")
        return

    中 = 中文段(干净)
    英 = 英文段(干净, 年份=年份, 季=季, 集=集)
    是混排 = bool(中) and bool(英)
    if 是混排:
        收集.加(干净, 来源, 基准权重 * 混排系数,
                备注前缀 + "中英混排整串（TMDB 标题是单一语言，降权）")
    else:
        收集.加(干净, 来源, 基准权重, 备注前缀)

    if 中 and 去重键(中) != 去重键(干净):
        if 是标签(中):
            收集.丢(中, "整段都是标记")
        else:
            收集.加(中, 来源_中文段, 基准权重 * 段衰减[来源_中文段],
                    备注前缀 + f"从「{来源}」里切出的中文段")
    if 英 and 去重键(英) != 去重键(干净):
        if 是标签(英):
            收集.丢(英, "整段都是标记")
        else:
            收集.加(英, 来源_英文段, 基准权重 * 段衰减[来源_英文段],
                    备注前缀 + f"从「{来源}」里切出的英文段")


def 生成查询(结构: Any, 目录链: Optional[Sequence[str]] = None,
             别名表: Optional[Mapping] = None, *, 最多: int = 最多查询词) -> 查询集合:
    """③ 的主函数：结构抽取结果 → 有序查询词们 + 年份过滤条件。

    参数
    ----
    结构
        鸭子类型：``标题`` / ``年份`` / ``类型`` / ``季`` / ``集`` 必有（可以为 None），
        ``标题候选们``（``list[str]``）可选。dataclass、dict、测试替身都行。
    目录链
        **从最近到最远**的目录名（``("Season 01", "葬送的芙莉莲")``）。
        为什么需要它：被网盘改名规避限制的文件（``146.SDR.8bit…mp4``）标题里根本没有作品名，
        名字在上层目录里；只吃文件名的旧实现必然瞎。
    别名表
        学习库（P4 ``数据/识别学习.json``）：看过的名字 → 标准名。命中就出**最高权重**的
        查询词 —— 这是"越用越准"在 P2 的落点。

    返回
    ----
    :class:`查询集合`：``查询词们``（权重从高到低）与独立的 ``年份`` 过滤条件。
    """
    结构数字 = {
        "年份": _取数字(结构, "年份"),
        "季": _取数字(结构, "季"),
        "集": _取数字(结构, "集"),
    }
    收集 = _收集器()
    主标题 = 清洗(取属性(结构, "标题", ""))
    候选标题们 = [清洗(x) for x in _取文本们(结构, "标题候选们")]
    # 目录链：调用方显式给的优先；没给就用结构自带的（P1 的 ``结构结果.目录链``）。
    # 两条路都给，是为了让"只有结构对象、没有额外上下文"的调用方能直接用上目录信息 ——
    # 而被改名规避限制的文件，作品名恰恰只在目录里。
    目录链 = tuple(目录链) if 目录链 else tuple(_取文本们(结构, "目录链"))
    # 有些结构实现会额外给出"从文件名切出来的标题"与"从目录链切出来的标题"两路结果，
    # 它们的信息价值分别等于 文件标题 / 目录标题，所以按各自的来源收进来（去重会自动合并）。
    文件标题属性 = 清洗(取属性(结构, "文件标题", ""))
    目录标题属性 = 清洗(取属性(结构, "目录标题", ""))

    # ---- 来源一：文件标题（离内容最近，最可信；但也可能被改名改坏）----
    for 文本 in [主标题] + [x for x in 候选标题们 if x] + [文件标题属性]:
        if not 文本:
            continue
        是主 = 去重键(文本) == 去重键(主标题)
        系数 = 1.0 if 是主 else 标题候选系数
        _按来源摊开(收集, 文本, 来源_文件标题, 权重表[来源_文件标题] * 系数, 结构数字,
                 备注前缀="" if 是主 else "标题候选：")

    # ---- 来源二：目录链每一层（改名文件的作品名往往只在这里）----
    if 目录标题属性:
        _按来源摊开(收集, 目录标题属性, 来源_目录标题, 权重表[来源_目录标题], 结构数字,
                 备注前缀="结构给的目录标题：")
    for 层号, 目录 in enumerate(目录链):
        目录文本 = 清洗(目录)
        if not 目录文本:
            continue
        if 是通用目录(目录文本):
            # 分类目录（电影/动漫/下载）不是作品名：搜它只会拿回一堆同名垃圾。
            收集.丢(目录文本, "通用分类目录名，不是作品名")
            continue
        if 是标签(目录文本):
            收集.丢(目录文本, "整个目录名都是画质/字幕标记")
            continue
        基准 = max(目录最低权重, 权重表[来源_目录标题] - 目录每层衰减 * 层号)
        _按来源摊开(收集, 目录文本, 来源_目录标题, 基准, 结构数字)

    # ---- 来源三：别名表（人工确认过的知识，权重最高）----
    观察文本们 = ([主标题, 文件标题属性, 目录标题属性] + 候选标题们
                + [清洗(x) for x in 目录链])
    for 别名, 原文 in 别名命中(观察文本们, 别名表):
        if 是标签(别名):
            continue
        _按来源摊开(收集, 别名, 来源_别名, 权重表[来源_别名], 结构数字,
                 备注前缀=f"别名库命中（原文：{原文}）：")

    # ---- 过滤：纯数字 / 整条是标记 ----
    留下: list[查询词] = []
    for 词 in 收集.产物(最多=10 ** 6):
        if 是纯数字(词.文本):
            数字 = int(词.文本)
            if 数字 in (结构数字["集"], 结构数字["季"]):
                收集.丢(词.文本, "是集号/季号，不是片名")
                continue
            备注 = "纯数字标题（2012/1917 这类片名），降权保留"
            if 数字 == 结构数字["年份"]:
                备注 = "纯数字标题且与年份同值（1984/2012 这类片名），降权保留"
            词 = 查询词(文本=词.文本, 来源=词.来源, 权重=词.权重 * 纯数字标题系数,
                       语言=词.语言, 备注=备注, 其它来源=词.其它来源)
        if 是标签(词.文本):
            收集.丢(词.文本, "整条都是标记")
            continue
        留下.append(词)

    # ---- 兜底：一条查询词都没有时，把最像标题的丢弃项捡回来 ----
    # 为什么要有兜底：零查询词 = 零召回，而 P2 的验收就是召回。宁可搜一个可疑的词
    # （哪怕它其实是个集号），也不能什么都不搜 —— ⑤ 打分会用分数把它压下去。
    if not 留下:
        for 文本, 原因 in 收集.丢弃们:
            if not 文本 or 是通用目录(文本):
                continue
            # 资格判定用**不带结构数字**的去标签：这样"146"（被丢是因为它是集号）
            # 还有资格当兜底，而"2160p HDR DDP5 1 中字"（整条都是标记与残渣）没有资格。
            兜底文本, _ = 去标签(文本)
            if not 兜底文本:
                continue
            留下 = [查询词(文本=兜底文本, 来源=来源_文件标题, 权重=兜底权重,
                          语言=_语言(兜底文本),
                          备注=f"兜底：没有更好的查询词（原本被丢：{原因}）")]
            break

    # ---- 去重后排序 + 重新裁剪（分段展开后条目可能超过上限）----
    结果: dict[str, 查询词] = {}
    for 词 in sorted(留下, key=lambda x: -x.权重):
        键 = 去重键(词.文本)
        if 键 and 键 not in 结果:
            结果[键] = 词
    词们 = list(结果.values())[:max(1, int(最多))]

    return 查询集合(查询词们=词们, 年份=结构数字["年份"], 类型=归一类型(取属性(结构, "类型")),
                季=结构数字["季"], 集=结构数字["集"], 标题=主标题,
                丢弃们=收集.丢弃们)
