"""识别管线（对外唯一壳）：``识别(样本, 父目录名=…, 目录链=…) → 识别结果``。

P1 只做到"结构层可用"
====================
``docs/识别/00_架构.md`` 第四节把管线写成 ``识别(路径们, 客户端, 库)``，但第五节把施工
拆开了：P1 的验收只有两条 —— **结构准确率 ≥ 99%、标题清洗 ≥ 98%**，而这两条全靠
① 归一化 + ② 结构抽取，**不需要 TMDB**。所以这里的 ``客户端`` 与 ``库`` 只留在签名里
占位、**故意不用**：真接上之前，任何"顺手接一下 TMDB"都会让评测测到一个假接口
（``工具/识别评测.py`` 的 TODO 里点名警告过这件事）。

P5 补上"整条链"
==============
:func:`识别` 仍然是**纯结构层**（P1 的评测脚本按这个契约调它，不许变）。
P5 要接进服务层的是 ②→③→④→⑤→⑥ 一整条，所以另开 :func:`全链`：

    结构(P1) → 候选(P2) → 检索(P2) → 打分(P3) → 决策(P3)

为什么把这条链放在**包里**而不是写在 ``服务.py`` 或评测脚本里：它是
"生产跑的链"与"评测量的链"必须**逐字相同**的那条东西 —— 一旦让两边各写一份，
评测报告里的数字就不再是生产链的数字（P3 那会儿两份并存只是临时状态）。

为什么这些 import 放在 :func:`全链` **函数里**：P1 的评测脚本用
``importlib.import_module("wangpan.identify.管线")`` 找 :func:`识别`，import 期多一个
会失败的顶层 import 就会把 P1 的评测一起炸掉（``__init__.py`` 的注释里记过这个坑）。
结构层是纯规则、无依赖，放顶层；候选/检索/打分/决策放函数里，按需载入。

调用方怎么拿到目录链（评测报告第 3 条那个已确认缺口）
==================================================
``葬送的芙莉莲/Season 01/05.mkv`` 的标题在**祖父目录**里，只给一层父目录永远抽不到。
两种给法都支持，也可以同时给（会去重保序）：

* ``识别("葬送的芙莉莲/Season 01/05.mkv")`` —— 整条路径，管线自己往上找；
* ``识别("05.mkv", 目录链=("Season 01", "葬送的芙莉莲"))`` —— 只有名字时手给。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable, Sequence

from . import 结构

__all__ = ["识别结果", "识别", "批量识别", "链结果", "全链"]


@dataclass
class 识别结果:
    """对外结果：P1 就是结构层那几项 + 一句人话摘要。"""

    结构: 结构结果
    路径: str = ""

    #: 下面几个是给调用方直接取字段用的（评测脚本按 标题/年份/类型/季/集 取值）
    @property
    def 标题(self) -> str:
        return self.结构.标题

    @property
    def 年份(self) -> int | None:
        return self.结构.年份

    @property
    def 类型(self) -> str:
        return self.结构.类型

    @property
    def 季(self) -> int | None:
        return self.结构.季

    @property
    def 集(self) -> int | None:
        return self.结构.集

    @property
    def 集到(self) -> int | None:
        return self.结构.集到

    def 查询词们(self) -> list[str]:
        """③ 候选生成要用的查询词（P2 直接用，不用再猜一遍标题）。"""
        return self.结构.查询词们()

    def 一句话(self) -> str:
        return self.结构.一句话()


def _取路径文本(样本) -> str:
    return str(样本)


def 识别(样本: str | Path, 父目录名: str = "",
       目录链: Iterable[str] = (), 客户端=None, 库=None) -> 识别结果:
    """一条样本 → :class:`识别结果`（**只管结构层**，不联网）。

    参数（``客户端`` / ``库`` 是 P2/P3 的占位，现在传了也不看）：
    * ``样本``：文件名或整条路径（``剧名/Season 01/05.mkv`` 这种最好整条给）；
    * ``父目录名``：文件所在目录名（给了就优先用它，路径里同名的那段会被去重）；
    * ``目录链``：更上层目录名，**由近到远**。
    """
    路径文本 = _取路径文本(样本)
    return 识别结果(结构=结构.抽取(路径文本, 父目录名=父目录名, 目录链=目录链),
                路径=路径文本)


def 批量识别(路径们: Sequence[str | Path], 客户端=None, 库=None) -> list[识别结果]:
    """多条样本依次识别。

    为什么不做成"同目录只搜一次"的批处理：那是 ④ 检索层的缓存，见 :func:`全链`
    的 ``缓存`` 参数（进程内共享 + 可落盘）。结构层是纯规则，先保持"一条进一条出"。
    """
    return [识别(路径, 客户端=客户端, 库=库) for 路径 in 路径们]


# ============================ 整条链（P5：服务层与评测共用）============================


@dataclass
class 链结果:
    """②→⑥ 一整条链的产物（每一层的结果都留着，排查时不用重跑）。

    为什么把中间层全带出来：报告要打印"为什么是这条"（逐信号明细）、服务层要
    把候选落进待确认队列、真机脚本要逐集说明档位 —— 它们要的是**不同层**的东西，
    只回一个"最终选了谁"就得让每个调用方各自再跑一遍链。
    """

    结构: 结构.结构结果
    查询集: Any
    检索结果: Any
    打分结果: Any
    决策结果: Any
    范围表: dict = field(default_factory=dict)

    @property
    def 档位(self) -> str:
        return self.决策结果.档位

    def 首选(self):
        return self.打分结果.首选()

    def 一句话(self) -> str:
        return f"{self.结构.一句话()}｜{self.决策结果.可读()}"


def 全链(样本: str | Path, 客户端, *, 父目录名: str = "",
        目录链: Iterable[str] = (), 学习库=None, 别名表=None,
        缓存=None, 落盘=None, 详情=None, 富化: bool = True,
        门槛=None) -> 链结果:
    """``结构 → 候选 → 检索 → 打分 → 决策`` 一条龙（**生产与评测共用这一份**）。

    参数
    ----
    样本 / 父目录名 / 目录链
        同 :func:`识别`。
    客户端
        TMDB 客户端（或任何有 ``搜电影``/``搜剧集``/``可用`` 的对象）。
    学习库 / 别名表
        P4 的学习库对象（:class:`~wangpan.identify.打分.学习库`）与它的别名节点。
        ``别名表=None`` 时自动从学习库的 ``别名`` 节点取 —— 这样调用方只传一个库，
        不会出现"查询词用了库、打分忘了用库"这种半截状态。
    缓存 / 落盘
        ④ 检索的缓存。``缓存=None`` 用进程内共享的 :func:`~wangpan.identify.检索.默认缓存`
        （同一目录的多个文件天然只搜一遍）；``落盘=True`` 打开跨次启动的缓存。
    详情 / 富化
        ⑤ 打分要的"季集范围 + 别名"取数器（:class:`~wangpan.identify.详情.候选详情`）。
        **``详情=None`` 就不做富化**（等价于没有季集范围信号）—— 故意不做"自动帮你 new 一个"，
        因为那会把"每集都重新取一次详情"的坑藏起来，而真机是几十集连着跑的。
    门槛
        覆盖 ⑥ 的默认门槛（只给评测做敏感性分析用）。
    """
    from .打分 import 打分
    from .决策 import 决策
    from .检索 import 检索
    from .候选 import 生成查询

    路径文本 = _取路径文本(样本)
    结构结果 = 结构.抽取(路径文本, 父目录名=父目录名, 目录链=目录链)

    别名 = 别名表
    if 别名 is None and 学习库 is not None:
        别名 = dict(getattr(学习库, "别名", {}) or {}) or None
    查询集 = 生成查询(结构结果, 目录链=目录链 or 结构结果.目录链, 别名表=别名)
    检索结果 = 检索(客户端, 查询集, 查询集.类型, 过滤年份=查询集.年份,
                 缓存=缓存, 落盘=落盘)

    # 两趟打分（第一版评测里就是两趟）：季集范围会改变排序，所以只能"先排一遍，
    # 再拿头部候选的详情重排"。取多少条由 详情.上限 控制（成本决策在调用方）。
    预分 = 打分(结构结果, 检索结果.候选们, 目录链=结构结果.目录链, 学习库=学习库)
    范围表 = 详情.富化表(预分) if (富化 and 详情 is not None) else {}
    最终 = 打分(结构结果, 检索结果.候选们, 目录链=结构结果.目录链, 学习库=学习库,
              季集范围表=范围表)
    判定 = 决策(结构结果, 最终, 门槛=门槛)
    return 链结果(结构=结构结果, 查询集=查询集, 检索结果=检索结果,
                打分结果=最终, 决策结果=判定, 范围表=范围表)

