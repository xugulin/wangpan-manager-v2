"""① 归一化：把"网盘里什么样的名字"拉平成一种形态，让结构抽取只面对一种写法。

为什么要有这一层（``docs/识别/00_架构.md`` 第三节把"归一化"单列成第 ① 步）
======================================================================
真机上的名字来自十几家发布组、十几个网盘客户端。同一部片能写成
``Spider-Man.No.Way.Home.2021.2160p.WEB-DL.H265.DDP5.1.Atmos-HHWEB.mkv``，
也能写成 ``【更多资源关注公众号：影视大全】奥本海默.2023.2160p.HDR.mkv``。
如果让结构抽取直接啃这些原始字符串，每条规则都要自己处理全角括号、中文标点、广告尾巴、
扩展名 —— 规则互相污染，改一处错一片，而且**错在哪一步没人知道**。

所以这一层只做"把写法拉平"这一件事，**绝不判断"这是第几集"**（那是 ② 结构抽取的事）：

* **全角 → 半角**：``（）`` 与 ``()``、``１２３`` 与 ``123``、各种横线（``–``/``—``/``−``）
  必须当同一个字符，否则"集号"的正则要写两遍，两遍就会不一致；
* **括号统一**：``【】〔〕「」《》`` → ``[]`` —— 后面按方括号切段时只认一种形态；
* **分隔符统一**：``. _ · |`` → 空格，但 ``-`` **保留**：``E01-E12``/``01-12`` 里的连字符
  是"打包区间"的信号，一体化成空格就把集号区间丢了（老实现丢过，见评测报告第 29/30 条）；
* **去扩展名**：只认"像扩展名"的尾巴，``DDP5.1`` 的 ``.1`` 绝不能被当成扩展名切掉；
* **去广告尾巴**：网址、公众号、QQ 群、压制组方括号 —— 网盘分享名里高频存在，
  它们既不是标题也不是标签，留着就会污染标题（评测报告第 41/42 条）；
* **大小写不在这一层下沉**：标题要按原样留给 ③ 候选生成去搜 TMDB
  （``The Bear`` 比 ``the bear`` 更容易命中），只有 :func:`标题比对键` 为"比对"下沉。

每一步都解释"为什么"而不只是"做了什么"：这层是后面所有规则的公共前提，写错一步，
后面所有指标一起掉，而报告里只会看到"标题不对"这种表象。
"""

from __future__ import annotations

import re

__all__ = [
    "转半角", "切路径", "切扩展名", "去网址", "是广告内容", "去广告",
    "去发布标签", "是发布标签", "是数据源ID", "有组名迹象", "是通用目录",
    "清标题", "标题比对键", "去发布组尾巴", "分隔符转空格",
    "有实词", "标签段们", "分辨率段们",
    "视频扩展名", "字幕扩展名", "音频扩展名", "图片扩展名",
]


# ============================ 全角 / 标点归一 ============================

#: 全角 → 半角。为什么手写映射表而不用 ``unicodedata.normalize("NFKC")``：
#: ① 内核依赖白名单里虽然放行 unicodedata，但 NFKC 会把 ``①`` ``Ⅳ`` 这类字符也改掉，
#:    那些字符真的会出现在片名里（``Ⅳ`` 是罗马数字第四部），改了就是另一个片名；
#: ② 我们要的规则是**明确列出来**的，别人读一遍就知道"哪些会被改"。
_全角表 = {码: 码 - 0xFEE0 for 码 in range(0xFF01, 0xFF5F)}
_全角表[0x3000] = 0x20                                   # 全角空格
_全角表.update({
    0x2018: 0x27, 0x2019: 0x27, 0x201C: 0x22, 0x201D: 0x22,      # 弯引号 → 直引号
    0x2010: 0x2D, 0x2011: 0x2D, 0x2012: 0x2D,                    # 各种横线 → '-'
    0x2013: 0x2D, 0x2014: 0x2D, 0x2212: 0x2D,
    0x300A: 0x5B, 0x300B: 0x5D,                                  # 《》
    0x300C: 0x5B, 0x300D: 0x5D,                                  # 「」
    0x300E: 0x5B, 0x300F: 0x5D,                                  # 『』
    0x3010: 0x5B, 0x3011: 0x5D,                                  # 【】
    0x3014: 0x5B, 0x3015: 0x5D,                                  # 〔〕
    0x3016: 0x5B, 0x3017: 0x5D,                                  # 〖〗
})


def 转半角(文本: str) -> str:
    """全角 → 半角（含全角空格与中日韩标点，见 :data:`_全角表`）。"""
    return (文本 or "").translate(_全角表)


# ============================ 扩展名 ============================

#: 视频扩展名（只有这些扩展名的文件才走"影片/剧集"）
视频扩展名 = frozenset({
    "mkv", "mp4", "avi", "mov", "wmv", "flv", "ts", "m2ts", "mts", "webm", "mpg",
    "mpeg", "mpe", "m4v", "3gp", "ogm", "ogv", "asf", "f4v", "m2v", "vob", "iso",
    "rmvb", "rm", "divx", "tp", "trp", "strm", "mxf",
})
字幕扩展名 = frozenset({"srt", "ass", "ssa", "sub", "idx", "sup", "vtt", "smi",
                   "sami", "ttml", "dfxp", "pgs", "mks"})
音频扩展名 = frozenset({"mka", "flac", "mp3", "aac", "ac3", "eac3", "dts", "m4a",
                   "wav", "ogg", "opus", "thd", "ape", "wv", "truehd", "dtshd"})
图片扩展名 = frozenset({"jpg", "jpeg", "png", "webp", "bmp", "gif", "tif", "tiff",
                   "avif", "heic", "jfif", "ico"})
_其它扩展名 = frozenset({"nfo", "txt", "md5", "sfv", "url", "torrent", "xml", "json",
                    "yml", "yaml", "log", "cue", "m3u", "m3u8", "playlist", "db"})

_已知扩展名 = 视频扩展名 | 字幕扩展名 | 音频扩展名 | 图片扩展名 | _其它扩展名
#: 没列进表里的"像扩展名"的尾巴：2~4 个纯字母（``webm`` 之外还有一堆冷门容器格式）。
#: 要求**纯字母**是关键 —— ``DDP5.1`` 的 ``1``、``某剧.1080p`` 的 ``1080p`` 都不是纯字母，
#: 于是不会被误当扩展名切掉。
_像扩展名 = re.compile(r"^[A-Za-z]{2,4}$")


def 切路径(路径: str) -> list[str]:
    """``a/b/c.mkv`` → ``["a", "b", "c.mkv"]``（``\\`` 也当分隔符，Windows 路径一样吃）。"""
    return [段 for 段 in re.split(r"[\\/]+", (路径 or "").strip()) if 段]


def 切扩展名(名字: str) -> tuple[str, str]:
    """切出 ``(主名, 扩展名)``，认不出扩展名就原样返回。

    为什么不用 ``Path(x).suffix`` / 直接取最后一个点：``HDR10+`` 后面没有点没问题，
    但 ``DDP5.1`` 的尾巴是 ``1``、``某剧.S03.1080p`` 的尾巴是 ``1080p`` —— 拿它们当扩展名
    会把名字切残（标题和集号一起没了）。所以只认 ① 已知媒体扩展名 ② 2~4 个纯字母的尾巴。
    """
    名 = (名字 or "").strip().replace("\\", "/").rsplit("/", 1)[-1]
    if "." not in 名:
        return 名, ""
    主, _, 尾 = 名.rpartition(".")
    if 尾.lower() in _已知扩展名 or _像扩展名.match(尾):
        return 主, 尾.lower()
    return 名, ""


# ============================ 广告 / 组名 ============================

#: 网址：``www.dygod.net`` / ``http://…``。**字符类里有两条纪律** ——
#: ① 不能放中日韩字符：分享名是 ``[电影天堂www.dygod.net]流浪地球``，一用 ``\S+``
#:    就会把"流浪地球"也吃掉；② 不能放方括号：``www.dygod.net]`` 连右括号一起吃掉的话，
#:    那个方括号就不闭合了，后面"整块方括号是不是广告"的判断全部失效（踩过）。
_网址 = re.compile(
    r"(?:https?://|www\.)[A-Za-z0-9\-._~:/?#@!$&'()*+,;=%]+"
    r"|(?<![A-Za-z0-9])(?:[A-Za-z0-9][A-Za-z0-9-]{0,30})\."
    r"(?:com|net|cn|org|cc|me|tv|xyz|top|info|biz|vip|site|club|io|la)(?![A-Za-z0-9])",
    re.I)

#: 广告词：只在"整块方括号/圆括号内容"和"去网址后的残留"上生效。
#: 为什么不敢在标题上无脑删"关注/资源"这种词：真片名里有"关注""资源"完全可能；
#: 而方括号里出现这些词，几乎百分之百是分享者塞的广告。
_广告词 = re.compile(
    r"电影天堂|最新电影|免费下载|迅雷下载|迅雷|加群|QQ群|微信公众号|公众号|微信号|扫一扫|"
    r"更多资源|资源分享|资源站|关注我|关注公众号|首发|广告", re.I)


def 去网址(文本: str) -> str:
    """去掉网址（避免它跟着标题一起进 TMDB 查询词）。"""
    return _网址.sub(" ", 文本 or "")


def 是广告内容(文本: str) -> bool:
    """这块内容（通常是方括号里的一整块）是不是广告/分享站的水印。"""
    文本 = 文本 or ""
    return bool(_网址.search(文本) or _广告词.search(文本))


def 去广告(文本: str) -> str:
    """去掉网址和广告词（广告词只在"整块就是广告"时调用；见 :func:`是广告内容`）。"""
    return _广告词.sub(" ", 去网址(文本 or ""))


#: 字幕组/压制组的名字迹象。``[Sakurato]`` 这种光看名字认不出来，所以结构层还会用
#: "后面还有标题内容"来兜底（见 结构._是组名）；这里只管**一眼就是组名**的。
#: ASCII 词必须带字母边界：否则 ``Submarine`` 里的 ``sub`` 会把真标题判成组名。
_组名迹象 = re.compile(
    r"字幕|压制|发布|汉化|翻译|工作室|资源|组|社|屋|"
    r"(?<![A-Za-z])(?:raws?|fansubs?|subs?|rips?|encode)(?![A-Za-z])", re.I)


def 有组名迹象(文本: str) -> bool:
    """这块内容像不像字幕组/压制组的名字。"""
    return bool(_组名迹象.search(文本 or ""))


#: 数据源 ID 标签：``[imdbid-tt0816692]`` / ``[tmdbid=123]``（Jellyfin 官方写法）。
_数据源ID = re.compile(r"^\s*(?:imdb|tmdb|tvdb)\s*(?:id)?\s*[-=:]\s*[^\]\s]+\s*$", re.I)


def 是数据源ID(文本: str) -> bool:
    """Jellyfin 的 ``[imdbid-…]`` 标签：是元数据，不是标题。"""
    return bool(_数据源ID.match(文本 or ""))


#: 通用分类目录名：这类目录**不提供标题**（"电影/下载/未分类"是分类，不是片名）。
#: 判据用"归一后完全相同"，不敢用包含 —— ``电影天堂`` 是分享站，``电影人生`` 是真片名。
_通用目录 = frozenset({
    "电影", "影片", "电视剧", "剧集", "美剧", "英剧", "日剧", "韩剧", "国剧", "国产剧",
    "动漫", "动画", "番剧", "番", "综艺", "纪录片", "视频", "媒体", "媒体库", "下载",
    "未分类", "新建文件夹", "其它", "其他", "补档", "待整理",
    "movies", "movie", "film", "films", "tv", "tvshows", "shows", "series", "anime",
    "video", "videos", "media", "other", "others", "unsorted", "download", "downloads",
})
_通用目录噪点 = re.compile(r"[\s._\-\[\]()（）【】]+")


def 是通用目录(名字: str) -> bool:
    """这个名字是不是"分类目录"（电影/下载/未分类…），是的话不能当标题来源。"""
    键 = _通用目录噪点.sub("", 转半角(名字 or "").lower())
    return 键 in _通用目录


# ============================ 发布标签 ============================

#: 发布标签：清晰度 / 来源 / 编码 / 音轨 / 位深 / 动态范围 / 帧率 / 版本 / 多段。
#: 为什么写得这么全：标题清洗 98% 的门槛就是靠"把标签摘干净"撑起来的
#: （评测报告第 38~43 条全是标签污染）。每条标签两侧都要求"不是字母数字"，
#: 这样 ``x264`` 不会命中 ``x2640``、``aac`` 也不会命中片名里的 ``Aachen``。
_标签 = re.compile(
    r"(?<![A-Za-z0-9])(?:"
    r"4320p|2160p|1080[pi]|720p|576p|540p|480[pi]|360p|4k|8k|uhd|fhd|hd[\s._-]?1080[pi]?|hd|sd"
    r"|web[\s._-]?dl|webrip|webdl|blu[\s._-]?ray|bdrip|brrip|bdremux|remux|hdtv|hdrip"
    r"|dvdrip|dvd|tvrip|vhs|cam|r5"
    r"|x264|x265|h[\s._-]?264|h[\s._-]?265|hevc|avc|av1|xvid|divx|vp9|vvc|h266|mpeg[\s._-]?2"
    r"|dts[\s._-]?hd(?:[\s._-]?ma)?|dts[\s._-]?x|dts|truehd|atmos|eac3|ac3"
    r"|aac[\s._-]?\d(?:[\s._-]\d)?|aac|dd[p+]?[\s._-]?\d[\s._-]\d|dd[p+]?|flac|mp3|opus|lpcm|pcm"
    r"|\d{1,2}[\s._-]?bit|hdr10\+|hdr10|hdr|dolby[\s._-]?vision|dovi|dv|sdr|imax|\d{2,3}fps"
    r"|repack|proper|extended[\s._-]?cut|extended|uncut|unrated|remastered|theatrical|criterion"
    r"|directors[\s._-]?cut|3d|hsbs|fsbs|htab|ftab|mvc"
    r"|(?:cd|dvd|part|pt|disc|disk)[\s._-]?\d{1,2}"
    r")(?![A-Za-z0-9])", re.I)

#: 平台/语言字幕简称：``[Baha]`` / ``[Bilibili]`` / ``[CHS]`` / ``[简繁内嵌]`` 这一层。
#: 为什么单独一张表：它们是"番剧命名"特有的方括号，出现在标题块里会污染标题
#: （老实现把 ``[CHS]`` 留成了标题尾巴）；而它们又都是**独立 token**，
#: 带字母边界之后不会误伤 ``Baha`` 之外的正常英文词。
_平台语言标签 = re.compile(
    r"(?<![A-Za-z0-9])(?:chs|cht|gb|big5|jpsc|jptc|sc|tc|vostfr|baha|bilibili|b-global|"
    r"cr|netflix|nf|amzn|dsnp|atvp|hmax|itunes|v2)(?![A-Za-z0-9])", re.I)

#: 中文画质/语言/字幕噪声词。这些词在日韩剧/国产剧的目录名与文件名里满地都是
#: （``仙逆.4K高码.SDR.60fps``、``沙丘.2021.4K.HDR.国语.中英双字``），
#: 它们不是片名的一部分，但也不是"发布标签"格式，所以要单独一张表。
#: 单字 ``简``/``繁`` 故意不收：``简爱`` 是真片名，收了它标题就残了。
_中文噪声 = re.compile(
    r"(?:高码率?|高帧率?|高画质|高动态|超高[清画]|高清|超清|蓝光|原盘|无损|"
    r"国语|粤语|日语|英语|韩语|中英双字|中英字幕|中文字幕|中字|英字|双语|"
    r"简繁|简体|繁体|简中|繁中|内嵌|外挂|内封|硬字幕|软字幕|字幕组|压制组|"
    r"收藏版|典藏版|修复版|重制版|重置版|加长版|未删减|导演剪辑版|完整版|清晰版|无水印|去水印)")

#: 更新状态（``更新至146集``/``全24集``/``已完结``/``合集``……）。
#: 为什么单独一条：**网盘的目录名**最爱这么写（``某剧 更新至146集``），而目录名不参与
#: 结构标记扫描（标记只扫文件名），所以不在清洗阶段摘掉它，标题兜底就成了
#: ``某剧 更新至146集`` —— 拿去搜 TMDB 一条都搜不到。
#: 为什么要单独一条而不是并进 :data:`_标签`：它跟"发布标签"不是一类东西
#: （``全24集`` 里没有画质/来源信息），但清洗时一样要摘掉；放进 `_标签` 会让
#: "标签段"这个概念的语义变浑。
_更新状态 = re.compile(
    r"(?:更新至|更新到|已更新|连载至|连载|全|共|总共|一共)\s*\d{1,4}\s*[集话話回]"
    r"|已完结|完结|合集|全集")

_分隔符 = re.compile(r"[._·•‧・|｜]+")
_首尾噪点 = " -_·|~:：,，、;；!！?？*+"


def 分隔符转空格(文本: str) -> str:
    """``.``/``_``/间隔号 → 空格；``-`` 保留（它是打包区间与集号区间的信号）。"""
    return _分隔符.sub(" ", 文本 or "")


def 是发布标签(文本: str) -> bool:
    """这块内容（通常是方括号里的一整块）**全是**发布标签吗。

    判据：把标签和中文噪声都摘掉之后不剩任何实词。这样 ``[1080p]``、``[AVC-8bit 1080p AAC]``、
    ``[简繁内嵌]`` 都会被认成标签块整块丢掉，而 ``[葬送的芙莉莲]`` 会留下来当标题。
    """
    剩 = _更新状态.sub(" ", _中文噪声.sub(" ", _平台语言标签.sub(" ", _标签.sub(" ", 文本 or ""))))
    return not _有实词(剩)


def 去发布标签(文本: str) -> str:
    """摘掉发布标签、平台/语言简称、中文画质噪声与更新状态（四张表互不重叠，顺序无关）。"""
    return _更新状态.sub(" ", _中文噪声.sub(
        " ", _平台语言标签.sub(" ", _标签.sub(" ", 文本 or ""))))


#: 发布组尾巴：``…x264-GROUP`` / ``…DDP5.1-OurTV`` / ``…Atmos-HHWEB``。
#: 只认"连字符 + 单个不含点的词"，而且**要求连字符前面紧挨着一个发布标签**。
#: 这两条限制都是防误伤：``Spider-Man.No.Way.Home`` 与 ``Three-Body`` 里的连字符在片名中间，
#: 不是组名分隔符 —— 判错的代价是标题少一截，比"留着组名"严重得多。
_组尾巴 = re.compile(r"-\s*([A-Za-z][A-Za-z0-9]{1,19})\s*$")


def 去发布组尾巴(文本: str) -> str:
    """去掉结尾的发布组名（见 :data:`_组尾巴`）。"""
    文本 = 文本 or ""
    m = _组尾巴.search(文本)
    if not m:
        return 文本
    前 = 文本[:m.start()].rstrip(_首尾噪点 + " ")
    if not 前:
        return 文本
    尾部 = 前[-24:]
    命中 = list(_标签.finditer(尾部))
    # 标签恰好"贴"在连字符前面才算组名；否则（片名里的连字符）原样返回
    if 命中 and 命中[-1].end() == len(尾部):
        return 前
    return 文本


# ============================ 标题清洗 ============================

_有实词迹象 = re.compile(r"[0-9A-Za-z\u4e00-\u9fff\u3040-\u30ff\uac00-\ud7af]")


def _有实词(文本: str) -> bool:
    """还剩不剩"看得出是字"的字符（数字/拉丁/中日韩）。只剩标点等于没清出标题。"""
    return bool(_有实词迹象.search(文本 or ""))


def 有实词(文本: str) -> bool:
    """还剩不剩"看得出是字"的字符（数字/拉丁/中日韩）。只剩标点等于没清出标题。

    公开出来是给结构层用的：判断"这个方括号是不是空的""切点后面还剩不剩东西"。
    """
    return bool(_有实词迹象.search(文本 or ""))


def 标签段们(文本: str) -> list[tuple[int, int]]:
    """所有发布标签/平台语言标签/更新状态的位置区间。

    结构层要用它判断"这个数字是不是标签里的"：``H.265``/``x264``/``DDP5.1``/``8bit``/``60fps``
    里的数字**绝不能被当成集号** —— 这是"集号在最前"的写法最容易翻车的地方。
    ``更新至146集`` 里的 146 同理（它是打包上界，由 ① 打包标记单独处理）。
    """
    文本 = 文本 or ""
    return ([(m.start(), m.end()) for m in _标签.finditer(文本)]
            + [(m.start(), m.end()) for m in _平台语言标签.finditer(文本)]
            + [(m.start(), m.end()) for m in _更新状态.finditer(文本)])


#: 分辨率对 ``1920x1080``：这类数字既不是年份也不是集号，单独挡掉。
_分辨率对 = re.compile(r"(?<![0-9])\d{3,4}\s*[xX×]\s*\d{3,4}(?![0-9])")


def 分辨率段们(文本: str) -> list[tuple[int, int]]:
    """所有"分辨率对"的位置区间（见 :data:`_分辨率对`）。"""
    return [(m.start(), m.end()) for m in _分辨率对.finditer(文本 or "")]


def 清标题(文本: str) -> str:
    """把一段"剩下的文本"清成标题；清不干净就返回空串。

    为什么"清不干净宁可返回空串"：返回一串标签（``1080p WEB-DL``）会被下游当成片名去搜，
    搜出来的结果比"没有标题"更糟（老实现踩过：同一集的两个版本被搜成两部片子）。
    """
    净 = 去网址(文本 or "")
    净 = 去发布标签(净)
    净 = 分隔符转空格(净)
    净 = re.sub(r"[\s]+", " ", 净)
    净 = re.sub(r"[\[\]()]", " ", 净)          # 括号壳：内容已经处理过，壳留着会污染
    净 = re.sub(r"[\s]+", " ", 净).strip(_首尾噪点 + " ")
    if not _有实词(净):
        return ""
    return 净.strip()


#: 比对用噪点：标题比对（评测/打分）时"大小写、空格、标点"都不该影响"是不是同一个标题"。
_比对噪点 = re.compile(r"[\s._\-·|:：,，、/\\'\"!！?？\[\](){}<>]+")


def 标题比对键(文本: str) -> str:
    """标题比对键：转半角 + 小写 + 去噪点（``Spider-Man`` ≡ ``Spider Man``）。"""
    return _比对噪点.sub("", 转半角(文本 or "").lower())
