# ============================ 库文件形状 ============================

#: 库文件的**结构版本号**（以后迁移用：读到不认识的版本要能分辨"这是新库"而不是"这是坏库"）。
#: 为什么现在就要：学习库是用户长期积累的数据，将来加"人物映射""分季映射"时，
#: 必须先能回答"手上这份是哪一版"，否则迁移只能靠猜字段。
结构版本 = 1

#: 打分认的三个节点（顺序就是文件里的书写顺序；``作品`` 只作档案，打分不读它）。
节点们 = ("别名", "目录", "作品")


#: 学习库路径的环境变量覆盖（**测试专用**）：设了就写到那里，不设就是 ``数据/识别学习.json``。
#: 为什么需要它：单测会真的走"人工确认 → 写学习库"这条闭环（``服务.py`` 的接线），
#: 而**测试绝不许往用户的数据目录里写东西**（架构文档第六节第 5 条：真机复验要留下干净的用户数据）。
#: 生产路径上这个变量是空的，所以两者仍然是同一个文件。
_路径变量 = "V2_识别学习库"


def 默认学习库路径() -> Path:
    """``数据/识别学习.json``。**定义只有一处**（在 ``打分.py`` 里），这里只做转发。

    为什么转发而不是各写一份：打分读的路径与学习写/读的路径必须是同一个文件，
    两份 ``Path(__file__).parents[2] / "数据" / …`` 迟早会有一处被改
    （第一版就在这里写成了自己调自己，单测当场炸成递归）。
    """
    覆盖 = (os.environ.get(_路径变量) or "").strip()
    if 覆盖:
        return Path(覆盖)
    return _打分默认学习库路径()


def 空库字典() -> dict:
    """空库（**带版本号与三个空节点**，而不是空文件/半截文件）。

    为什么空库也要"有小节"：``打分.学习库.从字典`` 靠"有没有节点键"判断
    "这是带节点的库"还是"整个文件就是一张别名表"。如果空库写成 ``{"版本": 1}``，
    它会被当成"别名表里有一条叫 版本 的别名"——不致命但很难看；写成
    ``{"别名": {}, "目录": {}, "作品": {}}`` 就是干净的"空且可扩展"。
    """
    return {"版本": 结构版本, "更新时间": "", "别名": {}, "目录": {}, "作品": {}}


def _取版本(值: Any) -> int:
    try:
        return int(值)
    except (TypeError, ValueError):
        return 结构版本


def 库路径可用(路径: Any = None) -> bool:
    """给定路径能不能当学习库用（父目录存在或能建、不是目录）。软检查，不创建任何东西。"""
    落点 = Path(路径) if 路径 is not None else 默认学习库路径()
    try:
        if 落点.is_dir():
            return False
        落点.parent.mkdir(parents=True, exist_ok=True)
    except OSError:
        return False
    return True


def 读原始(路径: Any = None) -> dict:
    """读学习库的**原始字典**（写库要用它，避免把别人写的字段悄悄丢掉）。

    容错三条，全部按"当空库"处理，绝不抛：
    * 文件不存在 / 读不动 / 不是合法 JSON / 顶层不是对象；
    * 顶层是**老形状**（整个文件就是一张别名表，P2 的探测脚本吃过这种）：整份当 ``别名``；
    * 缺 ``版本``：补上当前版本（迁移的起点），但**不改动**未知字段。
    """
    落点 = Path(路径) if 路径 is not None else 默认学习库路径()
    try:
        原文 = json.loads(落点.read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError):
        return 空库字典()
    if not isinstance(原文, Mapping):
        return 空库字典()

    出 = 空库字典()
    有节点 = any(键 in 原文 for 键 in 节点们)
    if 有节点:
        for 名 in 节点们:
            值 = 原文.get(名)
            出[名] = dict(值) if isinstance(值, Mapping) else {}
    else:
        出["别名"] = {k: v for k, v in 原文.items() if isinstance(k, str)}
    出["版本"] = _取版本(原文.get("版本"))
    出["更新时间"] = str(原文.get("更新时间") or "")
    return 出


def 读库(路径: Any = None) -> 学习库:
    """读成 ⑤ 打分要的 :class:`打分.学习库`（文件不存在/坏了 = 空库）。"""
    return 学习库.从字典(读原始(路径))


#: 读-改-写要串行（刮削是后台线程，万一将来多线程同时确认，两次并发写会丢更新）。
#: 原子写只保证"文件不半截"，保证不了"两次读改写不互相覆盖"，所以两者都要。
_写锁 = threading.Lock()


def _原子写(落点: Path, 文本: str) -> None:
    """同目录临时文件 + ``fsync`` + ``os.replace``：要么旧库，要么新库，**没有半截库**。

    为什么临时文件必须**同目录**：``os.replace`` 只在同一个文件系统内是原子的；
    ``/tmp`` 与用户数据目录常常不是同一个挂载点，跨设备替换会退化成"复制+删除"。
    """
    落点.parent.mkdir(parents=True, exist_ok=True)
    句柄, 临时 = tempfile.mkstemp(prefix=落点.name + ".tmp", dir=str(落点.parent))
    try:
        with os.fdopen(句柄, "w", encoding="utf-8") as 文件:
            文件.write(文本)
            文件.flush()
            os.fsync(文件.fileno())      # 先落盘再替换：断电时"新库"至少是完整的
        os.replace(临时, 落点)
    except BaseException:
        # 任何一步失败都只留下"旧库"，临时文件清掉（否则数据目录里会攒一堆 .tmp）
        try:
            os.unlink(临时)
        except OSError:
            pass
        raise


def 写库(数据: Mapping, 路径: Any = None) -> Path:
    """把（可能是半成品的）字典写回学习库：补版本号/三个节点/更新时间，然后原子替换。"""
    落点 = Path(路径) if 路径 is not None else 默认学习库路径()
    出 = dict(数据 or {})
    出["版本"] = _取版本(出.get("版本"))
    for 名 in 节点们:
        if not isinstance(出.get(名), Mapping):
            出[名] = {}
    出["更新时间"] = time.strftime("%Y-%m-%d %H:%M:%S")
    # 先序列化（可能抛：不可序列化的对象）→ 再碰磁盘：这样"报文坏"不会留下临时文件
    文本 = json.dumps(出, ensure_ascii=False, indent=1)
    with _写锁:
        _原子写(落点, 文本)
    return 落点


def 清空(路径: Any = None) -> Path:
    """清空学习库（保留版本号与三个空节点，文件还在、还能被下次确认接着写）。

    为什么不删文件：把文件删掉之后"学习库不存在"与"学习库是空的"这两种状态
    在排查时不好分（一种是"从没用过"，一种是"刚被清过"）。
    """
    return 写库(空库字典(), 路径)


def 统计(路径: Any = None) -> dict:
    """库里现在有什么（报告/界面/排查用）：各节点条数 + 版本号。"""
    原始 = 读原始(路径)
    return {"版本": 原始["版本"], "更新时间": 原始["更新时间"],
            "别名数": len(原始["别名"]), "目录数": len(原始["目录"]),
            "作品数": len(原始["作品"])}


# ============================ 入参读取（鸭子类型） ============================


def _取结构(结构: Any) -> Any:
    """``识别结果``（有 ``.结构``）与 ``结构结果``/dict/替身都能吃。"""
    if 结构 is None:
        return None
    内层 = getattr(结构, "结构", None)
    if 内层 is not None and not isinstance(结构, Mapping):
        return 内层
    if isinstance(结构, Mapping) and isinstance(结构.get("结构"), Mapping):
        return 结构.get("结构")
    return 结构


def _字段(对象: Any, 名字: str, 默认: Any = None) -> Any:
    if 对象 is None:
        return 默认
    if isinstance(对象, Mapping):
        值 = 对象.get(名字, 默认)
    else:
        值 = getattr(对象, 名字, 默认)
    return 默认 if 值 is None else 值


def _文本(值: Any) -> str:
    return str(值 or "").strip()


def _可选整数(值: Any) -> Optional[int]:
    try:
        return int(值)
    except (TypeError, ValueError):
        return None


def _归一类型(值: Any) -> str:
    """类型归一成 ``tv`` / ``movie`` / ``unknown``（吃 str、枚举、``媒体类型``）。"""
    from .候选 import 归一类型
    return 归一类型(值)


def _取标识与信息(选中: Any, 类型: Any) -> tuple[str, str, str, Optional[int]]:
    """从"用户选中的那条候选"里捞出 ``(tmdb id, 类型, 标题, 年份)``。

    三种入参都认（真机里三种都会出现）：
    * ``检索候选``（``标识``/``类型``/``标题``/``年份``）——评测脚本与管线；
    * ``匹配候选``（``来源标识``/``类型``/``标题``/``年份``）——待确认队列里那条；
    * 纯字符串/整数 id（调用方已经知道类型，或者只有 id）。
    """
    if 选中 is None:
        return "", _归一类型(类型), "", None
    标识 = _文本(_字段(选中, "标识", "") or _字段(选中, "来源标识", "")
               or _字段(选中, "tmdb_id", "") or _字段(选中, "id", ""))
    if not 标识 and isinstance(选中, (str, int)) and not isinstance(选中, bool):
        标识 = _文本(选中)
    猜类型 = _字段(选中, "类型", "")
    return 标识, _归一类型(类型 or 猜类型), _文本(_字段(选中, "标题", "")), \
        _可选整数(_字段(选中, "年份", None))


# ============================ 键的取舍（"哪些名字值得记"） ============================

#: 盘标识前缀（``guangya:`` / ``quark:`` / ``local:``）：远端单元的路径是
#: ``标识:远端路径``（见 ``扫描.造远端单元``），它会被 ``结构`` 当成一层目录名。
#: 这不是"某个盘的名字"，而是"``xxx:`` 这种形状"一律不当作品名。
_盘前缀 = re.compile(r"^[A-Za-z][A-Za-z0-9+.\-]*:$")


def _是视频名(名字: str) -> bool:
    后缀 = Path(_文本(名字)).suffix.lower().lstrip(".")
    return bool(后缀) and 后缀 in 归一化.视频扩展名


def _干净标题(文本: Any) -> str:
    """证据文本过一遍清洗 + 去标签（``仙逆.4K高码.SDR.60fps`` → ``仙逆``）。

    为什么要去标签：目录名里常带清晰度/帧率（真机 ``仙逆.4K高码.SDR.60fps``），
    不去掉的话"同一个作品换个清晰度版本"就变成了另一个名字，学习库立刻失效。
    """
    干净 = 清洗(文本)
    if not 干净:
        return ""
    去标, _ = 去标签(干净)
    return 去标 or 干净


def _合格名字(文本: Any) -> str:
    """"能当作品名"的文本 → 干净形式；不行就返回空串（**所有键都要过这道闸**）。

    闸门：清洗 + 去标签 + 不能整条都是标记、不能是分类目录、不能是季/特别篇目录。
    ``第03集`` / ``Season 01`` / ``媒体`` / ``1080p`` 都在这里被挡掉 ——
    它们是"结构和位置"，不是"作品的名字"，记进库只会造成误命中。
    """
    干净 = _干净标题(文本)
    if not 干净 or 是标签(干净) or 是通用目录(干净):
        return ""
    if 是季目录(干净) or 是特别篇目录(干净):
        return ""
    return 干净


def _证据候选们(结构: Any) -> list[str]:
    """② 结构里所有"可能是作品名"的文本（``标题``/``文件标题``/``目录标题``），过滤后去重。

    **不**把整条目录链倒进来：``/媒体/剧集/葬送的芙莉莲/…`` 里的 ``媒体``/``剧集``
    是分类目录，记成别名会让"以后某部片子的候选里出现同一个 id"时被误命中
    （命中即免 margin 直接入库，代价太大，所以记录侧宁可保守）。
    """
    原们 = [_字段(结构, "标题", ""), _字段(结构, "文件标题", ""),
           _字段(结构, "目录标题", "")]
    出: list[str] = []
    已见: set[str] = set()
    for 文本 in 原们:
        干净 = _合格名字(文本)
        if not 干净:
            continue
        键 = 去重键(干净)
        if 键 and 键 not in 已见:
            已见.add(键)
            出.append(干净)
    return 出


def _筛选证据(候选们: Sequence[str], 基准们: Sequence[str],
            锚定目录: str) -> tuple[list[str], list[str]]:
    """把"可能是作品名"的文本筛成"**就是这部作品的名字**"，返回 ``(收录, 丢掉)``。

    两条收录理由（都要"与这次确认的作品挂得上钩"）：
    * 它与**主证据**（结构的主标题 / 用户选中候选的标题）像同一个作品；
    * 它与**锚定目录**像同一个作品 —— 锚定目录 = 路径上离文件最近的、不像分类/季目录的
      那一层，覆盖"文件名是英文、目录名是中文"这种真机常见写法
      （``Renegade.Immortal.S01E138…`` 在 ``仙逆.4K高码.SDR.60fps`` 里）。

    为什么要这道筛：真机路径 ``/来自：分享/仙逆.4K高码.SDR.60fps`` 里，
    结构会把上层目录 ``来自：分享`` 也报成"目录标题"；它和 ``仙逆`` 毫无关系，
    记进库就意味着**整个分享目录**以后都会命中——精确率会被这一条毁掉。
    """
    收录: list[str] = []
    丢掉: list[str] = []
    for 文本 in 候选们:
        相关 = _像同一个作品(文本, 基准们)
        贴目录 = bool(锚定目录) and _像同一个作品(文本, [锚定目录])
        if 相关 or 贴目录:
            收录.append(文本)
        else:
            丢掉.append(f"「{文本}」与这次确认的作品名证据对不上，没记（免得污染学习库）")
    return 收录, 丢掉


def _合格目录们(路径文本: str, 结构: Any) -> list[str]:
    """路径上"可以当作品名"的目录名（由近到远），只按**通用**词表过滤。

    四类一律不要：视频文件本身、盘标识前缀、季/特别篇目录、分类目录
    （``媒体``/``电影``/``剧集``…，词表在 ① 归一化里，与 P1 用的是同一张）。
    """
    出: list[str] = []
    已见: set[str] = set()
    for 文本 in _目录候选们(路径文本, 结构):
        if _是视频名(文本) or _盘前缀.match(文本):
            continue
        if 是季目录(文本) or 是特别篇目录(文本) or 是通用目录(文本) or 是标签(文本):
            continue
        键 = 去重键(文本)
        if 键 and 键 not in 已见:
            已见.add(键)
            出.append(文本)
    return 出


def _英词集(文本: str) -> set[str]:
    段 = 英文段(去标签(清洗(文本))[0])
    return {x.lower() for x in re.findall(r"[A-Za-z0-9]+", 段) if re.search(r"[A-Za-z]", x)}


def _像同一个作品(候选名: str, 证据们: Sequence[str]) -> bool:
    """这个目录名"像不像"是这次确认的那部作品的名字？

    这是**记录侧最重要的闸门**：宁可不记，也不要把 ``媒体`` / ``电影`` / ``来自：分享``
    这种容器名记成"作品"。判定只用结构自身的信息（不引入任何个案）：
    去重键互相包含，或中文段互相包含，或英文词集一方包含另一方。
    """
    键 = 去重键(候选名)
    if not 键:
        return False
    for 证据 in 证据们:
        证键 = 去重键(证据)
        if not 证键:
            continue
        if 键 == 证键:
            return True
        if len(键) >= 2 and len(证键) >= 2 and (键 in 证键 or 证键 in 键):
            return True
        甲中 = 中文段(去标签(_文本(候选名))[0])
        乙中 = 中文段(去标签(_文本(证据))[0])
        if 甲中 and 乙中 and (甲中 in 乙中 or 乙中 in 甲中):
            return True
        甲英, 乙英 = _英词集(候选名), _英词集(证据)
        if 甲英 and 乙英 and (甲英 <= 乙英 or 乙英 <= 甲英):
            return True
    return False


def _目录候选们(路径文本: str, 结构: Any) -> list[str]:
    """从"样本路径"往上列出候选目录名（**由近到远**）。

    * 路径最后一段是视频文件 → 从它的父目录开始数（``/剧/仙逆.4K高码/146.mp4`` → ``仙逆.4K高码``）；
    * 最后一段本身就是目录（真机 ``刮路径()`` 拿到的就是剧集目录）→ 从它自己开始数；
    * 没有路径（只有结构）→ 退回结构自带的目录链。
    """
    出: list[str] = []
    if 路径文本:
        路径 = Path(路径文本.replace("\\", "/"))
        起点 = 路径.parent if _是视频名(路径.name) else 路径
        for 段 in reversed(起点.parts):
            文本 = _文本(段)
            if 文本 and 文本 not in (".", "..", "/"):
                出.append(文本)
        return 出
    for 段 in _字段(结构, "目录链", ()) or ():
        文本 = _文本(段)
        if 文本:
            出.append(文本)
    return 出


def 目录键们(路径文本: str, 结构: Any, 证据们: Sequence[str]) -> list[str]:
    """该记的**目录键**：路径上那些"像这部作品的名字"的目录。

    :func:`_合格目录们` 先挡掉形状不对的（文件/盘前缀/季目录/分类目录/纯标签），
    这里再挡一层**内容**：与结构抽出来的作品名证据"像同一个作品"。
    第二层挡住的是 ``/媒体/某电影.2020.mkv`` 这种把 ``媒体`` 记成作品的情况
    （真机里 ``/来自：分享/…`` 也一样，见 :func:`_筛选证据` 的说明）。
    """
    出: list[str] = []
    for 文本 in _合格目录们(路径文本, 结构):
        if not _像同一个作品(文本, 证据们):
            continue
        出.append(文本)
    return 出


# ============================ 记确认 ============================


def _值(标识: str, 类型: str, 标题: str, 年份: Optional[int]) -> dict:
    """一个学习项的值（**标题一定非空**，理由见模块文档字符串）。"""
    出: dict = {"tmdb_id": str(标识), "类型": 类型 or "unknown", "标题": 标题}
    if 年份:
        出["年份"] = int(年份)
    return 出


def _并入(节点: dict, 键: str, 值: dict, 时刻: str) -> tuple[bool, str]:
    """把一个键并入节点（同一个 id 重复确认 → ``次数`` +1；换成别的 id → 留审计痕迹）。

    返回 ``(是不是新键, 人话说明)``。为什么保留 ``旧id们``：学习库最怕的是"脏"，
    而"同一个目录/名字被确认到了两个不同的 tmdb id"是唯一能自动看出来的脏信号，
    留着它，报告里就能把这行点出来给人复核。
    """
    旧 = 节点.get(键)
    if isinstance(旧, Mapping) and str(旧.get("tmdb_id") or "") == str(值["tmdb_id"]):
        新值 = dict(旧)
        新值.update(值)
        新值["次数"] = int(旧.get("次数") or 1) + 1
        新值["最后确认"] = 时刻
        节点[键] = 新值
        return False, f"「{键}」已记过（第 {新值['次数']} 次确认）"
    新值 = dict(值)
    新值["次数"] = 1
    新值["最后确认"] = 时刻
    if isinstance(旧, Mapping) and 旧.get("tmdb_id"):
        新值["旧id们"] = list(旧.get("旧id们") or []) + [str(旧.get("tmdb_id"))]
        节点[键] = 新值
        return False, f"「{键}」改指 {值['tmdb_id']}（原来指向 {旧.get('tmdb_id')}，已记进旧id们）"
    节点[键] = 新值
    return True, f"「{键}」→ {值['tmdb_id']}"


def 记确认(样本: Any = None, 结构: Any = None, 选中: Any = None, 类型: Any = "",
          *, 路径: Any = None, 库路径: Any = None, 时刻: Optional[str] = None) -> dict:
    """**记一次人工确认**：落"目录 → 作品"与"别名/看过的名字 → 作品"两类映射。

    参数
    ----
    样本 / 路径
        这次确认针对的文件或目录（真机是 ``guangya:/来自：分享/仙逆.4K高码.SDR.60fps``
        这样的远端单元路径，也可以是本地路径）。给 ``样本`` 或 ``路径`` 都行。
    结构
        ② 的结果（``结构结果`` / ``识别结果`` / dict）。不给就用 :func:`管线.识别` 现抽一次。
    选中
        用户选中的候选（``检索候选`` / ``匹配候选`` / dict / 纯 tmdb id 字符串）。
        它提供 **tmdb_id**（唯一身份）、类型、标题、年份。
    类型
        类型覆盖（``tv`` / ``movie`` / ``媒体类型``）；不给就用 选中 自带的。

    返回
    ----
    一个**人话摘要字典**（``标识``/``目录``/``别名``/``作品``/``跳过``/``摘要``），
    调用方直接把它拼进日志即可。

    什么时候**什么都不写**：结构里连一个像样的作品名证据都没有（例如只有一个
    ``第03集.mp4`` 又没有目录）——这时记下来的键只会污染库，宁可不记（但仍会更新
    ``作品`` 档案，那是纯 id 级的、无风险）。
    """
    时刻 = 时刻 or time.strftime("%Y-%m-%d %H:%M:%S")
    路径文本 = _文本(样本) or _文本(路径)
    结构对象 = _取结构(结构)
    if 结构对象 is None:
        if not 路径文本:
            raise ValueError("记确认需要 样本(路径) 或 结构 至少给一个")
        from .管线 import 识别
        结构对象 = 识别(路径文本).结构

    标识, 归一类型, 选中标题, 年份 = _取标识与信息(选中, 类型)
    if not 标识:
        raise ValueError("记确认需要能定位到作品：选中 里没有 tmdb id（或直接传 id 字符串）")

    候选证据们 = _证据候选们(结构对象)
    # 关联基准 = 结构的主标题 + 用户选中候选的标题。选中标题既能当关联基准
    # （让 `沙丘 (2021)` 这样的目录与文件名 `Dune.2021.mkv` 挂上钩），
    # 自己也会作为一条别名键写进去（TMDB 的规范名同样是"这部作品的名字"）。
    基准们: list[str] = []
    for 文本 in [_合格名字(_字段(结构对象, "标题", "")), _合格名字(选中标题)]:
        if 文本 and 去重键(文本) not in {去重键(x) for x in 基准们}:
            基准们.append(文本)

    # 锚定目录 = 路径上离文件最近的合格目录（"这一部"的所在目录）。
    # 它专门用来认下"文件名英文 / 目录名中文"这一路（真机 Renegade Immortal ↔ 仙逆）。
    合格目录们 = _合格目录们(路径文本, 结构对象)
    锚定目录 = 合格目录们[0] if 合格目录们 else ""

    别名键们, 丢掉 = _筛选证据(候选证据们, 基准们, 锚定目录)
    for 文本 in 基准们:                       # 选中标题/主标题也要能当查询词用
        if 去重键(文本) not in {去重键(x) for x in 别名键们}:
            别名键们.append(文本)
    目录键 = 目录键们(路径文本, 结构对象, 别名键们)
    # 值里的标题：选中的（最权威）→ 结构证据 → 键自己。**一定要非空**（见模块文档）。
    值标题 = 选中标题 or (别名键们[0] if 别名键们 else "")

    跳过: list[str] = list(丢掉)
    原始 = 读原始(库路径)
    写目录: list[str] = []
    写别名: list[str] = []
    说明们: list[str] = []

    for 键 in 目录键:
        # 目录键的"标题"用目录自己的干净形式（它是用户实际看到的容器名，
        # 也是"同一目录第二集"最可能出现的查询词）。
        子值 = _值(标识, 归一类型, 值标题 or _干净标题(键) or 键, 年份)
        新键, 说明 = _并入(原始["目录"], 键, 子值, 时刻)
        写目录.append(键)
        if not 新键:
            说明们.append(说明)

    for 键 in 别名键们:
        子值 = _值(标识, 归一类型, 选中标题 or 键, 年份)
        新键, 说明 = _并入(原始["别名"], 键, 子值, 时刻)
        写别名.append(键)
        if not 新键:
            说明们.append(说明)

    # 作品档案：键 = "类型:id"（纯身份，任何语言/写法都指向同一条），供将来迁移与统计用。
    作品键 = f"{归一类型}:{标识}"
    _并入(原始["作品"], 作品键, _值(标识, 归一类型, 值标题 or 作品键, 年份), 时刻)

    if not 目录键 and not 别名键们:
        跳过.append("结构里没有可当作品名的证据（没有目录名也没抽出标题），只更新了作品档案")
    写库(原始, 库路径)

    落点 = Path(库路径) if 库路径 is not None else 默认学习库路径()
    结果 = {"标识": 标识, "类型": 归一类型, "标题": 值标题, "年份": 年份,
           "目录": 写目录, "别名": 写别名, "作品": 作品键, "跳过": 跳过 + 说明们,
           "库": str(落点)}
    结果["摘要"] = 摘要(结果)
    return 结果


def 摘要(结果: Mapping) -> str:
    """把 :func:`记确认` 的结果拼成一行日志（服务层直接往日志里塞）。"""
    标识 = f"[{结果.get('类型') or '?'}#{结果.get('标识') or '?'}]"
    目录 = 结果.get("目录") or []
    别名 = 结果.get("别名") or []
    段: list[str] = []
    if 目录:
        段.append("目录 " + "、".join(f"「{x}」" for x in 目录))
    if 别名:
        段.append("别名 " + "、".join(f"「{x}」" for x in 别名))
    if not 段:
        return f"{标识} 只更新了作品档案（结构里没有可记忆的名字）"
    return f"{标识} 记住 " + "；".join(段)


# ============================ 查询（给打分与报告用） ============================


@dataclass
class 命中项:
    """一个候选命中的一条学习项（谁命中、命中在哪个键上、值多少分）。"""

    候选标识: str = ""
    候选标题: str = ""
    来源: str = ""            # 目录 / 别名
    键: str = ""
    加权: float = 0.0         # 系数 × 打分.权重表["学习库"]（强命中 = 45.0）
    说明: str = ""

    def 可读(self) -> str:
        return (f"[{self.候选标题 or self.候选标识}] 学习库{self.来源}命中"
                f"「{self.键}」 {self.加权:+.1f} 分｜{self.说明}")


def _归库(库: Any, 库路径: Any) -> Optional[学习库]:
    if isinstance(库, 学习库):
        return 库
    if isinstance(库, Mapping):
        return 学习库.从字典(库)
    if 库 is not None and not 库路径:
        库路径 = 库
    return 读库(库路径)


def _定位命中(库对象: 学习库, 结构: Any, 候选: Any, 目录链: Sequence[str],
            观察们: Sequence[str]) -> tuple[str, str]:
    """回出"是哪个节点、哪个键"命中（判定顺序与 ``打分.学习命中`` 一致：先目录后别名）。

    只用于**解释**（报告里那一行"命中的是哪个键"）；能不能命中由 ``打分.学习命中``
    说了算，所以这里即使没定位到键，也只降级成空键，不会改变命中与否。
    """
    for 目录 in 目录链:
        键 = 去重键(目录)
        if not 键:
            continue
        for 库键, 值 in 库对象.目录.items():
            if 去重键(库键) == 键 and _命中一个值(值, 候选):
                return "目录", 库键
    观察键们 = {去重键(x) for x in 观察们 if 去重键(x)}
    for 库键, 值 in 库对象.别名.items():
        键 = 去重键(库键)
        if not 键 or 键 not in 观察键们:
            continue
        if _命中一个值(值, 候选):
            return "别名", 库键
    return "", ""


def 查询(结构: Any = None, 候选们: Iterable[Any] = (), *, 库: Any = None,
        库路径: Any = None, 路径: Any = None, 目录链: Sequence[str] = ()) -> list[命中项]:
    """给定"结构 + 候选"，回出命中的学习项与加权值（⑤ 打分就是用同一套判定算的）。

    这是本模块对外的**查询口**：报告/真机脚本靠它回答"这一条为什么直接定了"，
    而 ⑤ 打分那边由调用方把 :func:`读库` 的结果当 ``学习库=`` 传进去（打分内部
    会走 :func:`打分.学习命中`，两者结论由联动测试保证一致）。

    参数
    ----
    结构
        ② 的结果；``None`` 时用 ``路径`` 现抽（真机只有路径的场景）。
    候选们
        ``检索结果.候选们``（或其他形状的候选对象）。
    库 / 库路径
        ``学习库`` 对象 / 库字典 / 库文件路径。
    目录链
        覆盖结构自带的目录链（与打分的同名参数同义）。
    """
    from .打分 import 学习命中
    路径文本 = _文本(路径)
    结构对象 = _取结构(结构)
    if 结构对象 is None and 路径文本:
        from .管线 import 识别
        结构对象 = 识别(路径文本).结构
    库对象 = _归库(库, 库路径)
    if 库对象 is None or 库对象.空的() or 结构对象 is None:
        return []
    链 = tuple(目录链) if 目录链 else tuple(_字段(结构对象, "目录链", ()) or ())
    观察们 = 观察标题们(结构对象, 链)
    出: list[命中项] = []
    for 候选 in 候选们 or []:
        系数, 说明, 中性 = 学习命中(结构对象, 候选, 库对象, 链)
        if 中性 or float(系数) <= 0:
            continue
        来源, 键 = _定位命中(库对象, 结构对象, 候选, 链, 观察们)
        出.append(命中项(候选标识=_文本(_字段(候选, "标识", "")),
                      候选标题=_文本(_字段(候选, "标题", "")),
                      来源=来源, 键=键,
                      加权=float(系数) * float(权重表["学习库"]), 说明=说明))
    return 出


def 命中表(结构: Any, 候选们: Iterable[Any], **关键字) -> dict[str, float]:
    """``{候选标识: 学习库加权}``（只含命中的候选；给调用方快速查分）。"""
    return {x.候选标识: x.加权 for x in 查询(结构, 候选们, **关键字)}
