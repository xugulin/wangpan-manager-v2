"""⑦ 学习层（P4）：把"人工确认"落成"下次直接命中"——**越用越准**的闭环。

为什么要有这一层
================
⑤ 打分里"学习库命中 +45 分"这条信号（``打分.权重表["学习库"]``）是**唯一**会随使用
变强的信号：规则是死的，人工确认是活的。架构文档第三节 ⑦ 把它写成
"每次人工确认都写成学习样本（别名映射、目录→作品映射），下次直接命中"。
所以本模块只干三件事：

1. **记**：用户在待确认队列里点了"采纳"（或手动匹配选了一部）之后，把这次确认落成
   两条映射 —— ① **目录 → tmdb_id**、② **别名/看过的名字 → tmdb_id**；
2. **查**：给定"结构 + 候选"，回出命中的学习项与加权值（给 ⑤ 打分当输入，也给报告/日志
   当"这一条为什么直接定了"的解释）；
3. **存**：``数据/识别学习.json`` 的**原子写**、**坏文件当空库**、**结构版本号**。

形状必须与 ``打分.学习库`` 完全一致（这是 P3 留给 P4 的接口）
==========================================================
``打分.py`` 认三个节点：``别名`` / ``目录`` / ``作品``（见 :class:`打分.学习库`），
节点下的值形状**故意宽松**（str / list / dict / int 都认，见 ``打分._捞作品``）。
本模块写出去的文件长这样::

    {
      "版本": 1,
      "更新时间": "2026-09-25 11:22:33",
      "别名": {"仙逆": {"tmdb_id": "223911", "类型": "tv", "标题": "仙逆", ...}},
      "目录": {"仙逆.4K高码.SDR.60fps": {"tmdb_id": "223911", ...}},
      "作品": {"tv:223911": {"tmdb_id": "223911", "类型": "tv", "标题": "仙逆", ...}}
    }

**每个值里一定带一个非空的 ``标题``**，这不是装饰：``候选._拉起别名`` 在值里
找不到已知的标题键时会退化成"把值里所有字符串都当别名"，那样 ``tmdb_id`` 与 ``tv``
会被当成查询词送进 TMDB（白花请求、还添一堆垃圾候选）。所以写库时哪怕只能拿结构里的
标题兜底，也要填上。

命中判定**复用打分自己的函数**（而不是重写一套）
==============================================
改库的形状、改命中的方向（键→值 / 值→键）、改"值怎么指向候选"，任何一处不一致都会
变成"评测说有命中、线上没命中"这种最难查的 bug。所以 :func:`查询` 直接调
``打分.学习命中`` 与 ``打分._命中一个值`` —— ``tests/test_识别学习.py`` 里有一条
联动测试钉着"本模块说命中 ⟺ 打分说命中"。

写入安全（三条，每条都有真机理由）
================================
* **原子写**：先写同目录临时文件 → ``fsync`` → ``os.replace``。学习库是用户长期积累的
  资产，写到一半断电/被杀进程不能让它变成半截 JSON（半截文件在 P3 那边等于**空库**，
  等于用户白点了几十次确认）；
* **坏文件当空库**：读不动就当空库（识别不能因为学习库坏了而停摆，架构纪律同 P3）；
* **写失败不抛给调用方之外**：本模块的 :func:`记确认` 会抛异常（调用方要能知道），
  而服务层的接线用 **软失败** 包住 —— 记不住只是"下次还得点一次"，绝不能让"入库"失败。

为什么记的是"目录名/看过的名字"而不是"文件名"
==========================================
① 一个剧集目录里几十集的文件名各不相同（``146.SDR…`` / ``Renegade.Immortal.S01E138…``），
按文件名记等于每集都要重新学；② 网盘目录名往往才是干净的作品名（真机
``仙逆.4K高码.SDR.60fps`` 里的文件只剩集号）。所以键取"**离文件最近的那个像作品名的
目录**"与"**结构抽出来的作品名证据**"，而不是整条文件名。

不许为个案写死
=============
本模块没有一处 ``if 标题 == "仙逆"``：键的取舍靠"与结构抽出来的作品名证据是否相关"
（:func:`_像同一个作品`）加两张**通用**的词表（分类目录 / 标签，来自 ① 归一化与 ③ 候选），
任何作品、任何语言都走同一条路。

依赖方向：只依赖 ``wangpan/identify`` 内的 ① ② ③ ⑤（``归一化``/``结构``/``候选``/
``打分``）与标准库，**绝不 import v8_3**。
"""

