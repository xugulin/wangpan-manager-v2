"""⑥ 决策：三档 **自动入库 / 待确认 / 丢弃**（P3 的右半边）。

为什么要有"待确认"这一档
======================
架构文档第六节第 2 条：**自动化要保守** —— "宁可进待确认，也绝不把错的写进库"。
自动入库的精确率门槛是 **≥ 99%**（第二节表格），这个数字不是"尽量"而是硬线：
一旦写错一部作品，媒体库里就会长期挂着错的标题/海报/季集，而用户未必会发现。

所以自动档要**同时**满足两类条件，缺一不可：

1. **硬条件**（单项否决）：标题足够像、类型不矛盾、年份不是反证、集号不越界。
   这四条是"这条候选本身站得住"的证据，与"领先多少"无关 —— 一个高分错项最典型的
   长相就是"标题不太像但热度/证据很高"，光看分数拦不住它；
2. **高绝对分 + 够大的 margin**（第一名 − 第二名）：高绝对分保证"候选整体像样"，
   margin 保证"没有第二个同样像的候选"。真机上《仙逆》与《仙逆合集篇》、
   《沙丘》2021 与《沙丘》1984、《三体》与《三体·周年纪念版》这些**同名前传/重拍**
   就是靠 margin 掉进待确认的（用户点一下，同时变成 P4 的学习样本）。

只看分数不看 margin 会怎样：两个 105 分的候选（一个对、一个错）永远只能靠运气；
只看 margin 不看硬条件会怎样：一条"标题完全不像但热度 500"的候选只要对手更弱就能自动入库。
两者都要，正是"高分 **且** 领先第二名足够多"（架构文档第三节 ⑥）。

丢弃只留给"连人工都不值得看"的
============================
丢弃 ≠ "分数低"：分数低但标题像的候选应该待确认（差一点点就能入库，值得人工花 3 秒）。
只有**明显没救**的才丢：零候选，或者首选分数低于 :attr:`门槛.丢弃分`
（意味着标题几乎完全不像、连类型/证据/热度都撑不起来）。
"拿不准一律待确认"这条规矩在这里同样有效 —— 本模块的默认倾向是待确认，不是丢弃。

门槛是怎么定的（可复现）
====================
:data:`默认门槛` 是拿**标注集实测校准**出来的（``工具/识别打分评测.py``，
报告见 ``数据/识别打分评测.md``）：先让所有样本按原样跑一遍，看正确候选的分与
margin 分布，再把门槛卡在"错项全部掉出自动档"的位置上。**只许往保守调**：
提高门槛会让精确率升、覆盖率降；反过来必须先跑评测拿到"精确率仍 ≥99%"的证据。

实测数字（``工具/识别打分评测.py``，91 条标注样本里 63 条带 ``tmdb_id``）
--------------------------------------------------------------------
* 默认门槛（自动分 95 / 间距 25 / 标题 0.80 / 丢弃分 30）：
  **Top-1 63/63、自动入库 43/43 全对（精确率 100%）、覆盖率 68.3%、丢弃 0 条**；
* 门槛敏感性（报告第六节，重跑 ⑥ 决策即可复现）：
  ``自动分=92`` → 47/47 全对（覆盖率 74.6%）；``90 + 间距 15`` → 51/51（81.0%）。
  放宽确实还能保持 100% 精确率，但**默认仍然取 95/25**：标注集只有 63 条，
  多进 4~8 条换来的是"看不见的数据上少错一次"的余量 —— 精确率是硬线
  （≥99% = 100 条里最多错 1 条），覆盖率只是取舍，不是门槛。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Mapping, Optional

from .打分 import 打分结果, 候选分

__all__ = [
    "档_自动", "档_待确认", "档_丢弃", "门槛", "默认门槛", "决策结果", "决策",
]

#: 三档的中文名（对外/报告直接用，避免调用方到处拼字符串）
档_自动 = "自动入库"
档_待确认 = "待确认"
档_丢弃 = "丢弃"


@dataclass
class 门槛:
    """决策门槛。**所有"多高算高"的数字都在这里**，方便调参与解释。"""

    #: 自动档要求的第一名总分（原始分，满分不含学习库 = 126，见 ``打分.满分不含学习库``）。
    #: 为什么卡在 95：一条"标题完全一致 + 类型一致 + 季集在范围内"的候选能拿到
    #: 55+18+20 分，再加证据/热度就到 100+；而"标题只有 0.6 像"的候选就算其它信号
    #: 全满也只有 ~85 —— 这条线基本等价于"标题至少 0.85 像"。
    自动分: float = 95.0
    #: 自动档要求的第一名 − 第二名。为什么是 25：它大约等于"标题信号差半档"
    #: （0.45 × 55），也就是"第二名明显不如第一名像"的最小差距。真机上
    #: 《仙逆》vs《仙逆合集篇》的差距有 70+，而"两个候选标题都像"的情况通常 < 15。
    自动间距: float = 25.0
    #: 低于它就丢弃。为什么是 30：类型一致本身就有 18 分，所以 30 分以下意味着
    #: "标题完全不像、证据与热度也没有" —— 这种候选连人工看都浪费时间。
    #: 宁可贵一点：把 30 抬到 40 会开始丢弃"标题部分像"的候选（那该待确认）。
    丢弃分: float = 30.0
    #: 自动档的标题相似度下限（系数，不是分）。**这是精确率的最后一道闸**：
    #: 分数可以被类型/证据/热度堆起来，标题像不像骗不了人。
    标题下限: float = 0.80
    #: 季集范围系数低于它就算"越界反证"（-0.8 那档），自动档一票否决。
    #: 为什么是 -0.5：-0.8 是"集号远超全剧总集数"（前传/合集），-0.3 只是"没有这一季"，
    #: 后者在 TMDB 的季划分与文件名习惯不一致时很常见，不该一票否决。
    范围重罚线: float = -0.5
    #: 学习库强命中时，绝对分可以降这么多（人工确认过的知识不需要再"够高"）。
    学习库放宽: float = 20.0
    #: 是不是允许"学习库强命中"免掉 margin 要求。默认允许：库里的映射就是人工确认的
    #: 答案，此时第二名像不像已经不重要（这正是"越用越准"）。
    学习库免间距: bool = True

    def 摘要(self) -> str:
        return (f"自动分 ≥{self.自动分:.0f}，间距 ≥{self.自动间距:.0f}，"
                f"标题 ≥{self.标题下限:.2f}，丢弃分 <{self.丢弃分:.0f}")


#: 默认门槛（校准过程见模块文档字符串；报告里会原样打出来，避免"偷偷改门槛"）。
默认门槛 = 门槛()


@dataclass
class 决策结果:
    """⑥ 的输出：一个档位 + 一句人话原因 + 关键信号明细。"""

    档位: str
    首选: Optional[候选分]
    打分结果: 打分结果
    原因: str = ""
    #: 关键信号的**可读文本**（给界面/报告直接展示，不用再拼一次）。
    关键信号: list = field(default_factory=list)
    分数: float = 0.0
    间距: float = 0.0
    门槛: 门槛 = field(default_factory=门槛)

    def 是自动(self) -> bool:
        return self.档位 == 档_自动

    def 可读(self) -> str:
        首选 = self.首选
        谁 = (f"[{首选.类型}#{首选.标识}] {首选.标题}" if 首选 else "（没有候选）")
        return (f"{self.档位}：{谁}｜{self.分数:.1f} 分｜间距 {self.间距:.1f}"
                f"｜{self.原因}")


def _候选名们(候选: Any) -> list[str]:
    """候选身上所有"它的名字"（``标题``/``原名``/``别名``）—— dataclass / dict 都认。"""
    def 取(名字):
        if isinstance(候选, Mapping):
            return 候选.get(名字)
        return getattr(候选, 名字, None)
    名们 = [取("标题"), 取("原名")]
    别名 = 取("别名")
    if isinstance(别名, str):
        名们.append(别名)
    elif isinstance(别名, (list, tuple, set)):
        名们.extend(别名)
    return [str(x).strip() for x in 名们 if str(x or "").strip()]


def _名字逐字一致(甲: str, 乙: str) -> bool:
    """两个名字是不是**逐字符一致**（只忽略大小写、空格与标点）。

    与 ⑤ 打分的"标题相似度"是**两套判据**，这里刻意用更严的那套：相似度会剥掉中文段里
    的数字（``沙丘 2021`` → ``沙丘``），拿来判"精确一致"会把"沙丘"与"沙丘 2021"当成
    同一部片子（真机的假 TMDB 正好这么造）。精确一致这条规则的门槛就必须是逐字符级的。
    """
    from .候选 import 去重键
    键甲, 键乙 = 去重键(甲), 去重键(乙)
    return bool(键甲) and 键甲 == 键乙


def _主标题(结构: Any) -> str:
    """从结构里取"这部作品的片名"（dataclass / dict 都认，取不到就是空串）。"""
    if 结构 is None:
        return ""
    if isinstance(结构, Mapping):
        return str(结构.get("标题") or "")
    return str(getattr(结构, "标题", "") or "")


def _硬条件否决(首选: 候选分, 门槛: 门槛) -> str:
    """自动档的四个硬条件，返回**否决原因**（空字符串 = 全部通过）。

    为什么把硬条件写成独立的函数：这四条是"精确率优先"的落点，必须能被单测逐个钉住
    （构造一条"分数很高但标题不像"的候选，断言它进不了自动档）。
    """
    标题 = 首选.系数("标题")
    if 标题 < 门槛.标题下限:
        return f"标题相似度只有 {标题:.2f}（要求 ≥{门槛.标题下限:.2f}），不像"
    年份 = 首选.取("年份")
    if 年份 is not None and not 年份.中性 and 年份.系数 < 0:
        return f"年份是反证（{年份.说明}）"
    类型 = 首选.取("类型")
    if 类型 is not None and not 类型.中性 and 类型.系数 < 0:
        return f"类型不一致（{类型.说明}）"
    范围 = 首选.取("季集范围")
    if 范围 is not None and not 范围.中性 and 范围.系数 <= 门槛.范围重罚线:
        return f"季集越界（{范围.说明}）"
    return ""


def _精确一致(结构: Any, 项: 候选分) -> bool:
    """这条候选是不是"片名一字不差 **且** 年份也对得上"。

    三条都要（这也是"精确率优先"的一部分：宁可判不成立，也别放宽）：

    1. **主标题**（``结构.标题``，P1 抽出来的那个片名）与候选的某个名字
       （``标题``/``原名``/``别名``）**逐字符一致**（只忽略大小写/空格/标点）；
    2. 类型信号是正的（既不是中性也不是反证）—— 电影文件不能配到剧集上；
    3. 年份系数 ≥ 0.999（年份完全一致）。

    为什么第 1 条要**两处收紧**（只认主标题 + 逐字符一致）：
    * ⑤ 打分的"标题相似度"为了照顾"改名文件（作品名只剩在目录里）"，会把**整条目录链**
      也算成观察标题，而且中文段会把数字剥掉（``沙丘 2021`` → ``沙丘``）。于是目录名
      ``沙丘 (2021)`` 与某个候选的 TMDB 标题 ``沙丘 2021`` 会互相判成"完全一致"；
    * 真机 ``沙丘 (2021)`` 的局面（``tests/test_tmdb真HTTP.py`` 的假 TMDB 就是照它造的）
      正是这样：一部片子里冒出**两个**"精确一致"的候选 → 反而进了待确认。
    "片名一模一样"该说的是**这部作品自己的片名**逐字符相同，不是路径上碰巧出现过的
    任何字符串在"剥掉数字后"像。

    为什么第 3 条**不能**像老实现那样放宽成"目标压根没有年份"：光凭"片名一字不差"
    就放行，会把"只有名字像、别的什么都不知道"的候选也推进自动档 ——
    ``tests/test_识别决策.py::分数低但标题像的_仍然待确认而不是丢弃`` 钉的就是这条。
    年份的来源不只有文件名：``结构.抽取`` 也会从目录名括号里取
    （``怪奇物语 (2016)/Season 01/…`` → 2016），所以"最规范的目录写法"照样拿得到它。

    **为什么单独需要它，而不是只看 margin**：真机上 ``沙丘 (2021)`` 的最佳候选是
    《沙丘》(2021)，次佳《沙丘行星》(2021) 靠"片名包含沙丘 + 同年上映"也能咬到很接近的
    分数 —— 光看 margin 会把这种"一眼就能定"的条目永远塞进待确认队列。
    ``tests/test_tmdb真HTTP.py::端到端队列测试`` 里的"片名年份都对得上就直接采纳"
    钉的就是这件事（那是老实现（``匹配打分.自动决策`` 的"精确一致例外"）在真机测真 API
    之后加上的规则，P5 接线时**不许把它丢掉**）。

    **为什么它不等于"降低自动入库的标准"**：判定要求"候选里有**且只有一条**满足它、
    而且它必须就是首选"（见 :func:`决策` 里的调用点）。同一部剧在 TMDB 上有两条重复条目、
    《狂飙》与《狂飙1996》、《繁花》与《繁花2003》这类**同名并列**的场面
    仍然一律待确认 —— 单测 ``test_两个几乎同分的候选必须待确认`` 与 P3 评测报告里
    "自动入库精确率 100%" 一起盯着这件事。
    """
    主标题 = _主标题(结构)
    if not 主标题:
        return False
    if not any(_名字逐字一致(主标题, 名) for 名 in _候选名们(项.候选)):
        return False
    类型 = 项.取("类型")
    if 类型 is None or 类型.中性 or 类型.系数 <= 0:
        return False
    年份 = 项.取("年份")
    return bool(年份 is not None and not 年份.中性 and 年份.系数 >= 0.999)



def 决策(结构: Any, 打分结果: 打分结果, *, 门槛: Optional[门槛] = None) -> 决策结果:
    """⑥ 主函数：打分结果 → 三档之一（**纯函数**，不联网、不读盘）。

    参数
    ----
    结构
        ② 的结果。**三档判定其实用不到它**（只看候选分数与逐信号系数），保留在签名里
        有两个理由：⑥ 在链路（②→③→④→⑤→⑥）里有固定位置，将来"丢弃"要看上下文
        （例如"这根本不是视频"）；而且调用方（管线/评测）按同一个签名走，不用为
        "这一版用不到"而改两处。
    打分结果
        :class:`~wangpan.identify.打分.打分结果`（⑤ 的产物，已按总分排序）。
    门槛
        覆盖默认门槛（评测脚本用它做敏感性分析；**生产路径不要乱传**）。

    返回
    ----
    :class:`决策结果`：``档位`` / ``原因`` / ``关键信号`` / ``分数`` / ``间距``。
    """
    门槛 = 门槛 or 默认门槛
    首选 = 打分结果.首选()
    间距 = 打分结果.间距()

    if 首选 is None:
        return 决策结果(档位=档_丢弃, 首选=None, 打分结果=打分结果,
                    原因="一个候选都没有（查询词没搜到任何结果？）", 门槛=门槛)

    关键 = [f"{项.名字}：{项.说明}" for 项 in 首选.关键信号们(3)]

    def 待确认(原因: str) -> 决策结果:
        return 决策结果(档位=档_待确认, 首选=首选, 打分结果=打分结果, 原因=原因,
                    关键信号=关键, 分数=首选.总分, 间距=间距, 门槛=门槛)

    def 自动(原因: str) -> 决策结果:
        return 决策结果(档位=档_自动, 首选=首选, 打分结果=打分结果, 原因=原因,
                    关键信号=关键, 分数=首选.总分, 间距=间距, 门槛=门槛)

    # ---- 学习库强命中：人工确认过的答案，直接自动（"越用越准"的落点）----
    库项 = 首选.取("学习库")
    库强命中 = 库项 is not None and not 库项.中性 and 库项.系数 >= 1.0
    if 库强命中:
        否决 = _硬条件否决(首选, 门槛)
        # 学习库能免掉"标题下限"，但**免不掉年份/类型/季集的反证** ——
        # 库可能是脏的（人工点错过、或同一目录换过内容），而反证比记忆更硬。
        反证 = ""
        for 名字 in ("年份", "类型", "季集范围"):
            项 = 首选.取(名字)
            if 项 is not None and not 项.中性 and 项.系数 < 0:
                反证 = f"{名字}是反证（{项.说明}）"
        if 反证:
            return 待确认(f"学习库命中，但{反证} —— 库可能脏了，交人工复核")
        if 首选.总分 >= 门槛.自动分 - 门槛.学习库放宽 and (门槛.学习库免间距 or 间距 >= 门槛.自动间距):
            放宽 = f"；放宽掉的硬条件：{否决}" if 否决 else ""
            return 自动(f"学习库命中（{库项.说明}），总分 {首选.总分:.1f}、"
                       f"间距 {间距:.1f}{放宽}")
        return 待确认(f"学习库命中，但总分只有 {首选.总分:.1f}（<{门槛.自动分 - 门槛.学习库放宽:.0f}）")

    # ---- 丢弃：明显没救的（零候选已在上面处理）----
    if 首选.总分 < 门槛.丢弃分:
        return 决策结果(档位=档_丢弃, 首选=首选, 打分结果=打分结果,
                    原因=(f"最高分只有 {首选.总分:.1f}（<{门槛.丢弃分:.0f}），"
                           f"标题、年份、证据都撑不起来，连人工都不值得看"),
                    关键信号=关键, 分数=首选.总分, 间距=间距, 门槛=门槛)

    # ---- 自动档：先过硬条件，再看"精确一致唯一"，最后才是"够高 + 够领先" ----
    # 顺序不能反：硬条件是**单项否决**（标题不像 / 类型不对 / 年份反证 / 集号越界，
    # 分数再高也不许自动）；"精确一致唯一"是"片名与年份都一字不差、而且候选里再也
    # 找不出第二个" —— 这种局面没什么可犹豫的，不该被绝对分或 margin 卡住
    # （老实现 ``匹配打分.自动决策`` 就是把它放在分数判断**之前**的：真机上
    #  文件名 ``沙丘 (2021)`` 在低热度数据下分数可能不到 95，但那确实是它）。
    否决 = _硬条件否决(首选, 门槛)
    if 否决:
        return 待确认(f"{否决} —— 拿不准一律待确认（宁可少入库，也不写错）")

    精确们 = [项 for 项 in 打分结果.分数们 if _精确一致(结构, 项)]
    if len(精确们) == 1 and 精确们[0] is 首选:
        标题项 = 首选.取("标题")
        return 自动(f"标题与年份都精确一致、且候选里有且仅有它一个对得上"
                   f"（{标题项.说明 if 标题项 else ''}）；总分 {首选.总分:.1f}、"
                   f"领先第二名 {间距:.1f} 分 —— 有且仅有一个一字不差，不必再看门槛")

    if 首选.总分 < 门槛.自动分:
        return 待确认(f"总分 {首选.总分:.1f} 没到自动门槛 {门槛.自动分:.0f}"
                     f"（差 {门槛.自动分 - 首选.总分:.1f} 分）")
    if 间距 < 门槛.自动间距:
        亚军 = 打分结果.亚军()
        谁 = f"「{亚军.标题}」（{亚军.总分:.1f} 分）" if 亚军 else "第二名"
        return 待确认(f"领先幅度只有 {间距:.1f} 分（要求 ≥{门槛.自动间距:.0f}）："
                     f"{谁}同样像，交人工点一下最稳")

    标题 = 首选.取("标题")
    原因 = (f"标题{标题.说明 if 标题 else ''}；总分 {首选.总分:.1f}（≥{门槛.自动分:.0f}）、"
            f"领先第二名 {间距:.1f} 分（≥{门槛.自动间距:.0f}）")
    return 自动(原因)
