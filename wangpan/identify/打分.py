def _一条候选分(结构: Any, 候选: Any, 观察们: Sequence[str],
              范围表: Optional[Mapping], 学习库对象: Optional[学习库],
              目录链: Sequence[str]) -> 候选分:
    范围 = None
    if isinstance(范围表, Mapping):
        范围 = 范围表.get(str(_取(候选, "标识", "") or ""))
        if 范围 is None:
            范围 = 范围表.get(_取(候选, "标识", ""))
    if 范围 is None:
        范围 = 从候选取范围(候选)
    if 范围 is not None and not isinstance(范围, 季集范围):
        范围 = None

    明细: list[信号分] = []

    def 加(名字: str, 结果: tuple) -> None:
        系数, 说明, 中性 = 结果
        权重 = 权重表[名字]
        明细.append(信号分(名字=名字, 权重=权重, 系数=float(系数),
                         得分=0.0 if 中性 else float(系数) * 权重,
                         说明=说明, 中性=bool(中性)))

    标题分, 标题说 = 标题相似度(观察们, 候选)
    加("标题", (标题分, 标题说, False))
    加("年份", 年度系数(_可选整数(_取(结构, "年份")), _可选整数(_取(候选, "年份"))))
    加("类型", 类型系数(结构, 候选))
    加("季集范围", 季集范围系数(结构, 候选, 范围))
    加("证据", 证据系数(候选))
    加("热度", 热度系数(候选))
    加("学习库", 学习命中(结构, 候选, 学习库对象, 目录链))

    总分 = sum(项.得分 for 项 in 明细)
    return 候选分(候选=候选, 总分=总分, 信号们=明细)


def _归学习库(入参学习库: Optional[Any], 别名表: Optional[Mapping]) -> Optional[学习库]:
    """把"库对象 / 库字典 / 库路径 / 只有一张别名表"四种入参统一成一个 :class:`学习库`。

    两者都给时**库里的条目优先**（P4 是人工确认写进去的，比手工别名表更权威），
    但手工别名表里独有的条目会一并留下 —— 谁都不该被无声丢弃。

    注意形参名不叫 ``学习库``：那会把同名的**类**遮住，``isinstance(x, 学习库)`` 就炸了
    （第一版就踩了这个坑，单测当场抓住）。
    """
    if 入参学习库 is None:
        库: Optional[学习库] = None
    elif isinstance(入参学习库, 学习库):
        库 = 入参学习库
    elif isinstance(入参学习库, Mapping):
        库 = 学习库.从字典(入参学习库)
    elif isinstance(入参学习库, (str, Path)):
        库 = 学习库.读(入参学习库)
    else:
        库 = None
    if 别名表:
        合并 = dict(别名表)
        if 库 is not None:
            合并.update(库.别名)
        库 = 学习库(别名=合并) if 库 is None else 学习库(
            别名=合并, 目录=库.目录, 作品=库.作品)
    return 库


def _证据权重和(候选: Any) -> float:
    来源 = _取(候选, "来源", None)
    if not isinstance(来源, Mapping):
        return 0.0
    合计 = 0.0
    for 值 in 来源.values():
        try:
            合计 += float(值)
        except (TypeError, ValueError):
            continue
    return 合计


def 打分(结构: Any, 候选们: Sequence[Any], *,
        目录链: Sequence[str] = (), 别名表: Optional[Mapping] = None,
        学习库: Optional[Any] = None, 季集范围表: Optional[Mapping] = None) -> 打分结果:
    """⑤ 主函数：结构 + 候选表 → 排好序的 :class:`打分结果`（纯函数，不联网）。

    参数
    ----
    结构
        ② 的结果（鸭子类型：``标题/年份/类型/季/集/集到``，P1 的结构结果直接能用）。
    候选们
        ④ 的 ``检索结果.候选们``（:class:`~wangpan.identify.检索.检索候选`，或任何有
        ``标识/类型/标题/原名/年份/来源`` 的对象/dict）。
    目录链
        ④ 拿到的目录链（近→远）。学习库的"目录命中"要用它；不传就从结构里取。
    别名表
        P2 形状的别名表（``{看过的名字: 标准名}``）。传了就当学习库的 ``别名`` 节点用 ——
        这样"P4 还没落地、但已经手工维护了一份别名表"的场景能直接受益。
    学习库
        :class:`学习库` / dict / P4 的库文件所在路径。``None`` 或空库 = 全部中性。
    季集范围表
        ``{tmdb id: 季集范围}``。**为什么不内置联网取详情**：打分必须是纯函数、
        必须能被单测钉住，而且"取多少条详情"是成本决策，属于调用方（见评测脚本）。

    返回
    ----
    :class:`打分结果`：``分数们``（总分降序，同分按"证据权重和 → 热度 → 标识"稳定排序）
    与``观察标题们``（本次是拿什么比出来的，排查第一现场）。
    """
    观察们 = 观察标题们(结构, 目录链)
    库 = _归学习库(学习库, 别名表)

    分数们 = [_一条候选分(结构, 候选, 观察们, 季集范围表, 库, 目录链)
             for 候选 in (候选们 or [])]

    # 稳定排序：总分 → 证据权重和 → 热度 → 标识。
    # 为什么要后三级：同分时**不许**由输入顺序决定名次（那会让"多搜了一个查询词"
    # 这种无关变化改变 Top-1，指标就没法复现了）。
    分数们.sort(key=lambda x: (-x.总分, -_证据权重和(x.候选), -_浮点(_取(x.候选, "热度", 0)),
                              str(_取(x.候选, "标识", ""))))
    for 序号, 项 in enumerate(分数们, start=1):
        项.排名 = 序号
    return 打分结果(分数们=分数们, 观察标题们=观察们)
