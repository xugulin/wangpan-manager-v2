@dataclass
class 信号分:
    """**一个**信号的得分：``得分 = 权重 × 系数``。

    ``系数`` 才是信号的"事实判断"（1.0 = 完全支持，0 = 中性/无信息，负数 = 反证），
    它比 ``得分`` 更适合被 ⑥ 决策当硬条件用（例如"标题系数 < 0.8 不许自动入库"），
    因为换权重不该改掉"这条候选的标题到底像不像"。
    """

    名字: str
    权重: float
    系数: float
    得分: float
    说明: str = ""
    #: 中性 = "这条信号没有信息"（年份一边为空、候选没有季集信息…）。
    #: 中性必须与"负面"严格区分：拿不到信息就罚分，等于在惩罚数据缺失。
    中性: bool = False

    def 可读(self) -> str:
        if self.中性:
            return f"{self.名字} ±0.0（中性：{self.说明}）"
        return f"{self.名字} {self.得分:+.1f}（{self.说明}）"


@dataclass
class 候选分:
    """一条候选的打分结果（含逐信号明细）。"""

    候选: Any
    总分: float = 0.0
    信号们: list = field(default_factory=list)
    排名: int = 0

    def 取(self, 名字: str) -> Optional[信号分]:
        for 项 in self.信号们:
            if 项.名字 == 名字:
                return 项
        return None

    def 系数(self, 名字: str) -> float:
        项 = self.取(名字)
        return 0.0 if 项 is None or 项.中性 else float(项.系数)

    # ---- 透传候选自身的字段，方便调用方不必两处取 ----

    @property
    def 标识(self) -> str:
        return str(_取(self.候选, "标识", "") or "")

    @property
    def 标题(self) -> str:
        return str(_取(self.候选, "标题", "") or "")

    @property
    def 类型(self) -> str:
        return str(_取(self.候选, "类型", "") or "")

    def 可读(self) -> str:
        年 = f"（{self.候选.年份}）" if _取(self.候选, "年份") else ""
        return (f"{self.排名}. {self.总分:7.1f} 分｜[{self.类型}#{self.标识}] "
                f"{self.标题}{年}")

    def 明细(self) -> str:
        """一行行摊开：报告与真机排查都靠它回答"为什么是这条"。"""
        return "\n".join(f"      {项.可读()}" for 项 in self.信号们)

    def 关键信号们(self, 条数: int = 3) -> list:
        """贡献最大的几个**非中性**信号（按 |得分| 从大到小）。"""
        非中性 = [x for x in self.信号们 if not x.中性]
        return sorted(非中性, key=lambda x: -abs(x.得分))[:条数]


@dataclass
class 打分结果:
    """一次识别的全部候选分数（按总分从高到低）。"""

    分数们: list = field(default_factory=list)
    #: 本次打分吃到的观察标题（"我们是拿什么去比的"）—— 排查标题信号偏低的第一现场。
    观察标题们: list = field(default_factory=list)

    def 首选(self) -> Optional[候选分]:
        return self.分数们[0] if self.分数们 else None

    def 亚军(self) -> Optional[候选分]:
        return self.分数们[1] if len(self.分数们) > 1 else None

    def 间距(self) -> float:
        """margin = 第一名 − 第二名；只有一个候选时按"无穷大"处理。

        为什么用无穷大而不是 0：只有一条候选时"领先"这件事没有对手可比，
        它的可靠性由**绝对分**和硬条件（标题/类型/年份）把关，不该被 margin 卡住。
        """
        第一 = self.首选()
        if 第一 is None:
            return 0.0
        第二 = self.亚军()
        return float(第一.总分) if 第二 is None else float(第一.总分 - 第二.总分)

    def 空(self) -> bool:
        return not self.分数们


# ============================ 入参读取（鸭子类型） ============================


def _取(对象: Any, 名字: str, 默认: Any = None) -> Any:
    """dataclass / dict / 测试替身都认（P2 的候选模型已经定死，但测试替身不该被迫复刻它）。"""
    if 对象 is None:
        return 默认
    if isinstance(对象, Mapping):
        值 = 对象.get(名字, 默认)
    else:
        值 = getattr(对象, 名字, 默认)
    return 默认 if 值 is None else 值


def _可选整数(值) -> Optional[int]:
    if 值 in (None, ""):
        return None
    try:
        return int(值)
    except (TypeError, ValueError):
        try:
            return int(float(值))
        except (TypeError, ValueError):
            return None


def _文本们(值) -> list[str]:
    if 值 is None:
        return []
    if isinstance(值, str):
        return [值] if 值.strip() else []
    if isinstance(值, Mapping):
        值 = list(值.values())
    if isinstance(值, Iterable):
        return [str(x).strip() for x in 值 if str(x).strip()]
    return []


# ============================ 信号一：标题相似度 ============================

_空白 = re.compile(r"\s+")
_英数词 = re.compile(r"[A-Za-z0-9]+")
#: 纯数字（允许小数点与分隔符）：``2012`` / ``1917`` / ``2049`` 这类**片名本身就是数字**。
_纯数字串 = re.compile(r"[\d\s.\-–—]+")


def _二元组(文本: str) -> set:
    """字符二元组；长度 1 的串退化成它自己（否则"仙"这种单字串交集永远为空）。"""
    return {文本[i:i + 2] for i in range(len(文本) - 1)} or {文本}


def _编辑距离(甲: str, 乙: str) -> int:
    """标准 Levenshtein（滚动数组）。标题都很短，够用，不引第三方库。"""
    if 甲 == 乙:
        return 0
    if not 甲:
        return len(乙)
    if not 乙:
        return len(甲)
    上 = list(range(len(乙) + 1))
    for i, 字甲 in enumerate(甲, start=1):
        现 = [i]
        for j, 字乙 in enumerate(乙, start=1):
            现.append(min(上[j] + 1, 现[j - 1] + 1, 上[j - 1] + (字甲 != 字乙)))
        上 = 现
    return 上[-1]


def 中文相似度(甲: str, 乙: str) -> float:
    """中文标题相似度 = ``max(字符二元组 Dice, 编辑距离相似度)``。

    为什么两个都算再取大：两种度量各有盲区，而它们的**上限**才是我们想要的信号。
    * 二元组 Dice 对词序不敏感、对长标题稳（``葬送的芙莉莲`` vs ``葬送のフリーレン``
      只共享一个二元组 → 0.17，说明"日文原名"本来就不该跟中文名算得像）；
    * 编辑距离相似度对**短标题**更准（``仙逆`` vs ``逆仙``：二元组无交集 = 0，
      编辑距离 2/2 → 0；``仙逆`` vs ``仙逆合集篇``：两者都给 0.4）。
    * 只取大不取平均：宁可给"某一种度量认为很像"的候选一个高分，也不要让两种度量
      互相拉低 —— 打分还有类型/年份/季集在后面兜底，标题宁可略宽松。
    """
    甲 = _空白.sub("", 甲 or "")
    乙 = _空白.sub("", 乙 or "")
    if not 甲 or not 乙:
        return 0.0
    if 甲 == 乙:
        return 1.0
    组甲, 组乙 = _二元组(甲), _二元组(乙)
    dice = 2.0 * len(组甲 & 组乙) / (len(组甲) + len(组乙))
    编辑相似 = 1.0 - _编辑距离(甲, 乙) / max(len(甲), len(乙))
    return max(dice, 编辑相似)


def 英文相似度(甲: str, 乙: str) -> float:
    """英文标题相似度 = 词集合的 F1（词序无关）。

    为什么按**词**而不是字符：``Spider-Man: No Way Home`` 与 ``Spider Man No Way Home``
    标点不同、字符编辑距离不小，但词集完全一样 → 必须判 1.0（标注集口径就是"去标点后相同"）。
    为什么用 F1 而不是交集大小：``The Office`` 命中 ``The Office US`` 时 F1 = 0.8，
    而``The`` 这种词单独命中只给很小的分 —— 短查询词不会靠常用词刷分。
    """
    甲词 = {x.lower() for x in _英数词.findall(甲 or "")}
    乙词 = {x.lower() for x in _英数词.findall(乙 or "")}
    if not 甲词 or not 乙词:
        return 0.0
    交 = len(甲词 & 乙词)
    return 2.0 * 交 / (len(甲词) + len(乙词))


def 文本相似度(甲: str, 乙: str) -> float:
    """一条观察标题 × 一条候选标题：中文比中文、英文比英文，取较优。

    **不跨语言瞎比**：中文串与纯英文串之间没有可比的字符，硬比只会得到 0；
    跨语言的情况由调用方拿候选的 ``原名`` 再比一遍（:func:`标题相似度` 的"各算一次取较优"）。

    **纯数字片名要单独兜一手**：``2012`` / ``1917`` / ``2049`` 这类片名既没有汉字也没有
    字母，而 :func:`~wangpan.identify.候选.英文段` 故意要求"至少一个字母"
    （那是 ③ 生成查询词时的规矩：拿纯数字去搜会白花一次请求）。于是两个"空段"比出 0 分 ——
    真机上 ``2012.mp4`` 因此被打了 23 分、判成**丢弃**（正确的候选反而被丢掉）。
    所以这里补一条：两边都是数字串时，直接按字符/编辑距离比。
    """
    甲中, 乙中 = 中文段(甲), 中文段(乙)
    甲英, 乙英 = 英文段(甲), 英文段(乙)
    分们 = []
    if 甲中 and 乙中:
        分们.append(中文相似度(甲中, 乙中))
    if 甲英 and 乙英:
        分们.append(英文相似度(甲英, 乙英))
    if not 分们 and 甲 and 乙 and _纯数字串.fullmatch(甲) and _纯数字串.fullmatch(乙):
        分们.append(中文相似度(甲, 乙))
    return max(分们) if 分们 else 0.0


def 观察标题们(结构: Any, 目录链: Sequence[str] = ()) -> list[str]:
    """从结构结果里收出"我们观察到的、可能指向作品名"的标题们（去重保序）。

    为什么要把文件标题/目录标题/标题候选们全收进来：P1 一次会给好几个候选
    （``[喵萌奶茶屋][葬送的芙莉莲][05]`` → 组名 + 标题），谁是对的由相似度说话。
    为什么允许纯数字标题（``2012``）：像 ``2012.mp4`` 这种片名本身就叫 2012，
    把纯数字一律当噪声会把这类片子判成"没有标题"。只滤掉**画质标记**。
    """
    原们 = [_取(结构, "标题", ""), _取(结构, "文件标题", ""), _取(结构, "目录标题", "")]
    原们 += _文本们(_取(结构, "标题候选们", []))
    原们 += [str(x) for x in (目录链 or _文本们(_取(结构, "目录链", [])))]
    出: list[str] = []
    for 文本 in 原们:
        干净 = 清洗(文本)
        if not 干净 or 是标签(干净):
            continue
        if 去重键(干净) not in {去重键(x) for x in 出}:
            出.append(干净)
    return 出


def 标题相似度(观察们: Sequence[str], 候选: Any) -> tuple[float, str]:
    """标题信号：``(系数, 说明)``。

    候选有三个"名字"可用：``标题``（当前语言，通常中文）、``原名``（original_title /
    original_name）、以及 ``别名``（有些客户端会带）。**每个名字都与每个观察标题比一遍，
    取全局最优** —— 因为"文件名用中文、TMDB 当前语言是中文但原名是日文"
    （``葬送的芙莉莲`` vs ``葬送のフリーレン``）这种情况，只有各算一次才拿得到真信号。
    """
    候选名们 = [_取(候选, "标题", ""), _取(候选, "原名", "")]
    候选名们 += _文本们(_取(候选, "别名", []))
    候选名们 = [清洗(x) for x in 候选名们 if 清洗(x)]
    if not 观察们 or not 候选名们:
        return 0.0, "没有可比的标题"
    最优, 最优对 = 0.0, ("", "")
    for 观察 in 观察们:
        for 名字 in 候选名们:
            分 = 文本相似度(观察, 名字)
            if 分 > 最优:
                最优, 最优对 = 分, (观察, 名字)
    if not 最优对[0]:
        # 一条都没比出相似（典型：观察是中文、候选两边都是英文名）——
        # 说明里要把"拿什么比的"写出来，否则报告里只会看到一句没头没脑的 0.00。
        return 0.0, (f"标题完全不像（观察「{观察们[0]}」与候选名"
                     f"「{'／'.join(候选名们[:2])}」没有共同语言与字词）")
    甲, 乙 = 最优对
    怎么算 = "中文" if 含中文(甲) and 含中文(乙) else "英文"
    if 最优 >= 0.999:
        说明 = f"{怎么算}完全一致（「{甲}」＝「{乙}」）"
    else:
        说明 = f"{怎么算}最相似「{甲}」×「{乙}」= {最优:.2f}"
    return 最优, 说明


# ============================ 信号二：年份 ============================


def 年度系数(结构年份: Optional[int], 候选年份: Optional[int]) -> tuple[float, str, bool]:
    """年份信号：``(系数, 说明, 是否中性)``。

    分档理由（每一档都来自真机的"年份会骗人"）：
    * 一致 → 1.0；
    * 差 1 年 → 0.55（首播年 vs 上映年、不同地区首播年差一年是常态，不能当反证）；
    * 差 2 年 → 0.2（可能是不同版本的发行年，弱惩罚但不推翻标题）；
    * 差 ≥3 年 → **-0.85 反证**（《沙丘》2021 与《沙丘》1984、《2012》与《2012 世界末日》
      就靠这一条分开）。
    * 任一边年份未知 → **中性**：年份未知不是"对不上"，拿不到信息就罚分等于惩罚缺失。
    """
    if 结构年份 is None or 候选年份 is None:
        return 0.0, f"年份信息不全（结构 {结构年份}／候选 {候选年份}），不奖不罚", True
    差 = abs(int(结构年份) - int(候选年份))
    if 差 == 0:
        return 1.0, f"年份完全一致（{结构年份}）", False
    if 差 == 1:
        return 0.55, f"年份差 1 年（{结构年份} vs {候选年份}，首播/上映年常差一年）", False
    if 差 == 2:
        return 0.2, f"年份差 2 年（{结构年份} vs {候选年份}）", False
    return -0.85, f"年份差 {差} 年（{结构年份} vs {候选年份}）—— 反证，不是同一部作品", False


# ============================ 信号三：类型 / 上下文 ============================


def 上下文类型(结构: Any) -> str:
    """从结构里推"这条样本应该是电影还是剧集"。

    优先用 P1 的类型（实测 91/91）；它给 ``unknown`` 时退回**上下文**：
    有集号就一定是剧集（电影没有"第 146 集"）。这就是架构里"剧集目录 vs 单片"那一条。
    """
    类型 = str(getattr(结构, "类型", "") or "").strip().lower()
    if 类型 in ("tv", "movie"):
        return 类型
    if 类型 in ("剧集", "集", "电视剧", "series"):
        return "tv"
    if 类型 in ("电影", "影片", "film"):
        return "movie"
    return "tv" if _可选整数(_取(结构, "集")) is not None else "unknown"


def 类型系数(结构: Any, 候选: Any) -> tuple[float, str, bool]:
    """类型信号：``(系数, 说明, 是否中性)``。

    一致 → +1.0；不一致 → **-1.0**（重罚，等于 18 分级别）；任一未知 → 中性。
    "电影候选混进剧集接口结果"是 ④ 检索的必然产物（类型未知时两个接口都搜），
    所以这条信号在真机里几乎每次都在起作用，权重给到 18。
    """
    该是 = 上下文类型(结构)
    实际 = str(_取(候选, "类型", "") or "").strip().lower()
    if 实际 in ("剧集", "集"):
        实际 = "tv"
    if 实际 in ("电影", "影片"):
        实际 = "movie"
    if 该是 not in ("tv", "movie") or 实际 not in ("tv", "movie"):
        return 0.0, f"类型信息不全（结构 {该是 or '未知'}／候选 {实际 or '未知'}），不奖不罚", True
    if 该是 == 实际:
        return 1.0, f"类型一致（{'剧集' if 该是 == 'tv' else '电影'}）", False
    return -1.0, (f"类型不一致（结构判 {'剧集' if 该是 == 'tv' else '电影'}，"
                  f"候选是 {'剧集' if 实际 == 'tv' else '电影'}）"), False


# ============================ 信号四：季集范围 ============================


@dataclass
class 季集范围:
    """候选作品的季/集结构：``每季集数`` + 派生出的 ``总集数``。

    为什么要单独一个类而不是直接读候选：⑤ 打分不该自己去联网取详情（那会让打分
    不可测、也不可能纯函数）。季集信息由调用方注入（``打分(..., 季集范围表=…)``），
    真机由管线按需取 TMDB 详情，评测脚本自己控制取多少条（见 ``工具/识别打分评测.py``）。
    """

    每季集数: dict = field(default_factory=dict)      # {季号: 集数}
    季数: int = 0

    def __post_init__(self) -> None:
        归一 = {}
        for 键, 值 in (self.每季集数 or {}).items():
            号, 数 = _可选整数(键), _可选整数(值)
            if 号 is not None and 数:
                归一[int(号)] = int(数)
        self.每季集数 = 归一
        self.季数 = self.季数 or len(归一)

    @property
    def 总集数(self) -> int:
        """**所有季**的集数之和（含第 0 季特别篇）。

        为什么含第 0 季：连续编号的长播番（真机《仙逆》146 集）在 TMDB 上常常是
        "第 0 季特别篇 + 第 1 季正片"并存，只算正片会把合法集号误判成越界。
        """
        return sum(self.每季集数.values())

    def 说明(self) -> str:
        if not self.每季集数:
            return "（没有季集信息）"
        段 = "、".join(f"S{号}:{数}集" for 号, 数 in sorted(self.每季集数.items()))
        return f"{段}（共 {self.总集数} 集）"


def 从候选取范围(候选: Any) -> Optional[季集范围]:
    """尽力从候选对象上读季集信息；读不到就返回 ``None``（**不许猜**）。

    认的形状（按优先级）：
    * 候选本身带 ``季集范围``（:class:`季集范围` 或 dict）；
    * ``每季集数``（dict）或 ``季们``（TMDB 的 ``季`` 对象列表，有 ``季号``/``集数``）；
    * 单独给 ``季数``/``集数`` 时只能得到"总集数"，按单季处理 —— 这种情况下
      :func:`季集范围系数` 会走"只有总集数"的分支（判定更宽松，见那里的注释）。
    """
    范围 = _取(候选, "季集范围", None)
    if isinstance(范围, 季集范围):
        return 范围
    if isinstance(范围, Mapping):
        return 季集范围(每季集数=dict(范围))
    每季 = _取(候选, "每季集数", None)
    if isinstance(每季, Mapping):
        return 季集范围(每季集数=dict(每季))
    季们 = _取(候选, "季们", None)
    if isinstance(季们, Iterable) and not isinstance(季们, (str, bytes, Mapping)):
        对 = {}
        for 季 in 季们:
            号, 数 = _可选整数(_取(季, "季号")), _可选整数(_取(季, "集数"))
            if 号 is not None and 数:
                对[int(号)] = int(数)
        if 对:
            return 季集范围(每季集数=对)
    总 = _可选整数(_取(候选, "集数", None))
    if 总:
        # 只有总集数：当成"第 1 季 = 总集数"。为什么会走到这里：有些客户端只给总集数。
        return 季集范围(每季集数={1: int(总)})
    return None


#: 集号超出"全剧总集数"多少比例才算**反证**。
#: 为什么要容差：TMDB 的集数常滞后于正在更新的剧（今天第 147 集播了、TMDB 还写着 146 集），
#: 卡死"一个都不能超"会把正确的长播剧误杀。15% + 2 集是宽严之间的折中。
范围容差 = 1.15
范围容差基数 = 2


def 季集范围系数(结构: Any, 候选: Any, 范围: Optional[季集范围]
                ) -> tuple[float, str, bool]:
    """(季,集) 范围校验：``(系数, 说明, 是否中性)``。

    这一条是**专治同名前传/合集/特别篇**的（真机：TMDB 里《仙逆》223911 是 200 集正片，
    而《仙逆合集篇》292307 是只有 22 集的独立条目 —— 文件名写着"第 146 集"时，
    合集篇必然越界）。判定分档：

    ========================  ======  ==================================
    情况                      系数    理由
    ========================  ======  ==================================
    集号在该季集数内          1.0     最强证据
    超出该季、但在全剧总集数内 0.35    连续编号写法（黑镜 S1E07 其实是 S1E3+S2E4）
    超出总集数（容差内）       0.0     可能 TMDB 滞后，不奖不罚
    超出总集数（容差外）      -0.8    反证：这是"前传/合集/短篇"，不是正片
    没有集号（整季包/特别篇）  0.5/-0.3 季号在候选里存在 / 不存在
    电影候选却有集号          -0.6    电影不可能有"第 146 集"
    拿不到季集信息            0.0     中性：**拿不到信息不许罚分**
    ========================  ======  ==================================
    """
    该是 = 上下文类型(结构)
    实际 = str(_取(候选, "类型", "") or "").strip().lower()
    集号们 = [x for x in (_可选整数(_取(结构, "集")), _可选整数(_取(结构, "集到")))
             if x is not None]
    季号 = _可选整数(_取(结构, "季"))

    if 实际 == "movie" or (实际 == "" and 该是 == "movie"):
        if 集号们:
            return -0.6, f"候选是电影，文件名却有第 {max(集号们)} 集 —— 结构对不上", False
        return 0.0, "候选是电影且文件名没有集号，没有可校验的范围", True

    if 范围 is None or not 范围.每季集数:
        return 0.0, "没有候选的季集信息，不奖不罚（宁可少判，不许瞎判）", True

    if not 集号们:
        if 季号 is None:
            return 0.0, "文件名没有季号也没有集号，无需校验范围", True
        if 季号 in 范围.每季集数:
            return 0.5, f"第 {季号} 季在候选里存在（{范围.说明()}）", False
        return -0.3, f"候选里没有第 {季号} 季（{范围.说明()}）", False

    上界 = max(集号们)
    该季集数 = 范围.每季集数.get(季号) if 季号 is not None else None
    if 该季集数 and 上界 <= 该季集数:
        return 1.0, f"第 {上界} 集落在第 {季号} 季的 {该季集数} 集内", False
    if 范围.总集数 and 上界 <= 范围.总集数:
        return 0.35, (f"第 {上界} 集超出该季（{该季集数} 集）但在全剧 {范围.总集数} 集内"
                     " —— 连续编号写法（如《黑镜》S1E07 跨季连编），只轻扣"), False
    上限 = int(范围.总集数 * 范围容差) + 范围容差基数 if 范围.总集数 else 0
    if 范围.总集数 and 上界 <= 上限:
        return 0.0, (f"第 {上界} 集超出全剧 {范围.总集数} 集但还在容差内"
                     f"（TMDB 集数常滞后于更新中的剧），不奖不罚"), False
    if 范围.总集数:
        return -0.8, (f"第 {上界} 集远超候选全剧 {范围.总集数} 集"
                     f"（{范围.说明()}）—— 这是前传/合集/短篇，不是正片"), False
    return 0.0, "候选没有总集数，范围无法判定", True


# ============================ 信号五：证据条数 ============================

#: 证据权重的"软上限"：权重和到这个数就算满（别名 100 + 文件标题 80 = 180 是常见上限）。
证据权重软上限 = 180.0


def 证据系数(候选: Any) -> tuple[float, str, bool]:
    """证据信号：``(系数, 说明, 是否中性)`` —— 这条候选是被**几个**查询词搜出来的。

    为什么这算证据：③ 会摊出"中文段 / 英文段 / 目录名 / 别名"等多个查询词，
    它们是**互相独立**的索引路径。一部剧同时被"仙逆"和"Renegade Immortal"搜到，
    说明 TMDB 上这两个名字都指向它 —— 比只被一个模糊长串搜到可信得多
    （架构文档第五节把这条写成"中英两条索引互为独立证据"）。

    系数构成：``0.5×条数分 + 0.5×权重和分``，再加 0.15 的"中英双证"加分（封顶 1.0）。
    为什么权重和也要压缩：权重是 ③ 给的先验（别名 100、目录 65），不压缩的话
    一条从别名库出来的低质候选会靠权重把标题信号压过去。
    """
    来源 = _取(候选, "来源", None)
    if not isinstance(来源, Mapping) or not 来源:
        return 0.0, "没有来源证据（单查询词检索或证据被丢掉）", True
    条数 = len(来源)
    权重和 = 0.0
    for 值 in 来源.values():
        try:
            权重和 += float(值)
        except (TypeError, ValueError):
            continue
    条数分 = min(1.0, max(0, 条数 - 1) / 2.0)
    权重分 = min(1.0, 权重和 / 证据权重软上限)
    有中 = 有英 = False
    for 词 in 来源:
        if 含中文(词):
            有中 = True
        elif re.search(r"[A-Za-z]", str(词)):
            有英 = True
    双证 = 0.15 if (有中 and 有英) else 0.0
    系数 = min(1.0, 0.5 * 条数分 + 0.5 * 权重分 + 双证)
    语言说明 = "中英双证" if 双证 else ("仅中文查询词" if 有中 else
                                  ("仅英文查询词" if 有英 else "无语言线索"))
    说明 = f"被 {条数} 个查询词命中（权重和 {权重和:.0f}，{语言说明}）"
    return 系数, 说明, False


# ============================ 信号六：热度 / 票数 ============================

#: 对数压缩的参考点：热度到 300 就算满、票数到 5000 就算满。
#: 为什么票数参考点取这么低（5000 而不是 10 万）：中文长播剧在 TMDB 的票数普遍很低
#: （真机《仙逆》第一名票数只有 44），参考点取太高会让所有中文剧的票数分都趋近 0，
#: 那还不如不给这个信号。取 5000 是为了让"几十票 vs 几千票"能分出层次。
热度参考 = 300.0
票数参考 = 5000.0


def 热度系数(候选: Any) -> tuple[float, str, bool]:
    """热度/票数：**弱先验**，且必须对数压缩。

    为什么必须压缩：TMDB 的 ``popularity`` 从 0.5 到 200+，``vote_count`` 从 0 到几万，
    线性用会让"热门烂片"压死"冷门正确项"。取 ``log1p`` 之后，44 票与 4400 票的差距
    只有约 2 倍分，而这 5 分权重也不足以推翻任何标题证据 —— 它只在**同分候选**之间
    起作用，这正是架构里"弱先验，只用于同分打破"的意思。
    """
    热度 = _浮点(_取(候选, "热度", 0.0))
    票数 = _浮点(_取(候选, "票数", 0.0))
    if 热度 <= 0 and 票数 <= 0:
        return 0.0, "没有热度/票数信息", True
    热分 = min(1.0, math.log1p(max(0.0, 热度)) / math.log1p(热度参考))
    票分 = min(1.0, math.log1p(max(0.0, 票数)) / math.log1p(票数参考))
    系数 = 0.5 * 热分 + 0.5 * 票分
    return 系数, f"热度 {热度:.1f}／票数 {票数:.0f}（已对数压缩，只做弱先验）", False


def _浮点(值) -> float:
    try:
        return float(值)
    except (TypeError, ValueError):
        return 0.0


# ============================ 信号七：学习库（P4 接口） ============================


@dataclass
class 学习库:
    """P4（``数据/识别学习.json``）的内存形状 —— **现在按空库处理**，接口先留好。

    三个节点，对应三类"人工确认过的知识"：
    * ``别名``：看过的名字 → 标准名/id（用户在待确认界面上点选后写入）；
    * ``目录``：目录名 → 作品（同一个网盘目录第二次就不用再猜了，**最强的一类**）；
    * ``作品``：规范名 → 作品信息（``{"tmdb_id": "223911", "类型": "tv"}``）。

    值的形状**故意宽松**（str / list / dict 都认）：P4 的 ``学习.py`` 还没落地，
    现在把形状焊死，等于逼 P4 迁就 P3。判命中只看"能不能捞出一个 tmdb id 或标题"。
    """

    别名: dict = field(default_factory=dict)
    目录: dict = field(default_factory=dict)
    作品: dict = field(default_factory=dict)

    def 空的(self) -> bool:
        return not (self.别名 or self.目录 or self.作品)

    @classmethod
    def 从字典(cls, 数据: Any) -> "学习库":
        """认两种形状：``{"别名": {...}, "目录": {...}}`` 与"整个文件就是别名表"。

        后者是为了兼容 P2 的 ``工具/识别真网探测.py``：它把整个文件当别名表用，
        P4 真写库时应该用带节点的那种（好扩展）。
        """
        if not isinstance(数据, Mapping):
            return cls()
        有节点 = any(k in 数据 for k in ("别名", "目录", "作品"))
        if not 有节点:
            return cls(别名=dict(数据))
        return cls(
            别名=dict(数据.get("别名") or {}) if isinstance(数据.get("别名"), Mapping) else {},
            目录=dict(数据.get("目录") or {}) if isinstance(数据.get("目录"), Mapping) else {},
            作品=dict(数据.get("作品") or {}) if isinstance(数据.get("作品"), Mapping) else {},
        )

    @classmethod
    def 读(cls, 路径: Any) -> "学习库":
        """读学习库。**文件不存在/坏了 = 空库**（识别不能因为学习库打不开而停摆）。"""
        try:
            原文 = json.loads(Path(路径).read_text(encoding="utf-8"))
        except (OSError, ValueError, TypeError):
            return cls()
        return cls.从字典(原文)


def 读学习库(路径: Any = None) -> 学习库:
    """读 P4 的学习库；``路径=None`` 用 :func:`默认学习库路径`。空库是合法状态。"""
    return 学习库.读(默认学习库路径() if 路径 is None else 路径)


def _捞作品(值: Any) -> tuple[str, list[str]]:
    """从学习库的一个值里捞出 ``(tmdb id, 标题们)``（认 str / list / dict / int）。"""
    if 值 is None:
        return "", []
    if isinstance(值, (int, float)) and not isinstance(值, bool):
        return str(int(值)), []
    if isinstance(值, str):
        文本 = 值.strip()
        return (文本, []) if 文本.isdigit() else ("", [文本] if 文本 else [])
    if isinstance(值, Mapping):
        标识 = ""
        for 键 in ("tmdb_id", "tmdb", "标识", "id", "来源标识"):
            数字 = _可选整数(值.get(键))
            if 数字:
                标识 = str(数字)
                break
        标题们: list[str] = []
        for 键 in ("标题", "标准名", "名字", "名称", "title", "name", "别名", "aliases"):
            if 键 in 值:
                标题们.extend(_文本们(值[键]))
        return 标识, 标题们
    if isinstance(值, Iterable):
        标识, 标题们 = "", []
        for 项 in 值:
            子标识, 子标题 = _捞作品(项)
            标识 = 标识 or 子标识
            标题们.extend(子标题)
        return 标识, 标题们
    return "", []


def _命中一个值(值: Any, 候选: Any) -> Optional[str]:
    """学习库的某个值是否指向这条候选？指向就返回"是怎么指过来的"（给说明用）。"""
    标识, 标题们 = _捞作品(值)
    候选标识 = str(_取(候选, "标识", "") or "").strip()
    if 标识 and 候选标识 and 标识 == 候选标识:
        return f"tmdb id {标识} 完全一致"
    候选名们 = {去重键(_取(候选, "标题", "")), 去重键(_取(候选, "原名", ""))}
    for 标题 in 标题们:
        键 = 去重键(标题)
        if 键 and 键 in 候选名们:
            return f"标题「{标题}」完全一致"
    return None


def 学习命中(结构: Any, 候选: Any, 学习库对象: Optional[学习库],
            目录链: Sequence[str] = ()) -> tuple[float, str, bool]:
    """学习库信号：``(系数, 说明, 是否中性)`` —— 空库时中性（不是罚分）。

    两类命中，都是"人工确认过"的强证据：
    * **目录命中**（最强，"同一目录第二次直接命中"就是它）；
    * **别名命中**（看过的名字 → 作品）。

    判定用**双向 + 去重键**：学习库的键可能是看过的乱名（``仙逆.4K高码.SDR.60fps``），
    也可能是规范名；值指向 tmdb id 或标题。只要"观察到的名字"与键对得上，
    且值指向当前候选，就算命中。
    """
    if 学习库对象 is None or 学习库对象.空的():
        return 0.0, "学习库是空的（P4 还没落地），不奖不罚", True
    观察键们 = {去重键(x) for x in 观察标题们(结构, 目录链) if 去重键(x)}
    目录链 = tuple(目录链 or _文本们(_取(结构, "目录链", [])))
    for 目录 in 目录链:
        键 = 去重键(目录)
        if 键 and 键 in {去重键(k) for k in 学习库对象.目录}:
            for 库键, 值 in 学习库对象.目录.items():
                if 去重键(库键) != 键:
                    continue
                怎么指 = _命中一个值(值, 候选)
                if 怎么指:
                    return 1.0, f"学习库目录命中：目录「{目录}」→ {怎么指}", False
    for 库键, 值 in 学习库对象.别名.items():
        键 = 去重键(库键)
        if not 键 or 键 not in 观察键们:
            continue
        怎么指 = _命中一个值(值, 候选)
        if 怎么指:
            return 1.0, f"学习库别名命中：看过的名字「{库键}」→ {怎么指}", False
    return 0.0, "学习库有内容，但这条候选没被记住过", True


