"""匹配打分：把"解析出来的文件名"与"TMDB 搜出来的候选"对上号，并给出人话理由。

为什么要自己写一套打分而不是直接取搜索结果第一条：

* TMDB 的搜索排序是"词面 + 热度"混合的，同名前作/续集/翻拍经常排在正主前面
  （搜"沙丘"能给你搜出"沙丘 2"）；
* 界面上必须能解释"为什么选它"（理由要能给人看），否则用户不敢用自动刮削；
* 自动采纳要有据可依：分数够高**且**和第二名拉开差距，两个都满足才敢自动。

量纲说明（很容易写错，这里写死）：
* ``匹配候选.热度`` 是 TMDB 的 ``popularity``（几十到几千），**不是评分**，
  只当"最多 +5 分"的破平手段；
* ``匹配候选.额外["评分"]`` 才是 0–10 的 ``vote_average``；
* 本模块返回的分数是 **0–100**（不是 0–1）。
"""

from __future__ import annotations

import re
from pathlib import Path

from .命名解析 import 解析, 猜剧集路径, 转半角
from .模型 import 匹配候选, 媒体类型

__all__ = ["规范化标题", "区分季与剧场版", "是包含关系", "标题相似度", "打分候选",
           "排序候选", "自动决策", "从文件名猜查询词", "权重", "包含相似度"]

#: 打分权重（标题 45 + 别名 15 + 年份 30 + 结构 10 = 100，热度最多再 +5）
权重 = {"标题": 45.0, "别名": 15.0, "年份": 30.0, "结构": 10.0, "热度上限": 5.0}
#: 相似度权重：编辑距离 0.6 + 词集合 Jaccard 0.4（中文靠双字组，英文靠词）
_编辑距离权重 = 0.6
_词集权重 = 0.4
#: "包含关系"的相似度上限：给 0.9 而不是 1.0（防"沙丘"命中"沙丘2"）
包含相似度 = 0.9
#: 年份符合度：差 1 年扣一半，差 ≥2 年扣满，年份未知取半分（不奖也不罚）
年份符合度_差一年 = 0.5
年份符合度_未知 = 0.5

#: 季标识（"第二季"/"第2季"/"Season 2"/"S2"/"2nd Season"）
_季标识们 = (
    r"第\s*([0-9]{1,2}|[一二两三四五六七八九十]{1,3})\s*[季部]",
    r"(?:season|s)\s*([0-9]{1,2})(?![0-9])",
    r"([0-9]{1,2})\s*(?:st|nd|rd|th)\s+season",
)
_季中文数字 = {"一": 1, "二": 2, "两": 2, "三": 3, "四": 4, "五": 5, "六": 6,
           "七": 7, "八": 8, "九": 9, "十": 10}
#: "剧场版"这类标记（保留成标记，别当成噪声丢掉）
_剧场版们 = ("剧场版", "劇場版", "电影版", "電影版", "the movie")
#: 归一化时保留的字符（字母/数字/中日韩/假名/谚文），其余一律当分隔符
_保留 = r"0-9a-z\u4e00-\u9fff\u3040-\u30ff\uac00-\ud7af"


# ============================ 标题归一化 ============================


def 区分季与剧场版(文本: str) -> tuple[str, int | None, bool]:
    """把"核心标题 / 季号 / 是否剧场版"**分别**取出来。

    为什么要"分别"：直接删掉"第2季"会让"沙丘 第二季"和"沙丘"归一成同一个字符串，
    匹配时就会拿第二季的候选去配第一季。所以取出来之后，:func:`规范化标题` 会把它当
    **标记补回结尾** —— 信息不丢，只是位置统一了。
    """
    剩余 = 转半角(文本 or "")
    季号: int | None = None
    剧场版 = False
    for 模式 in _季标识们:
        if (m := re.search(模式, 剩余, re.I)):
            值 = m.group(1)
            数字 = int(值) if 值.isdigit() else _季中文数字.get(值, 0)
            if 数字:
                季号 = 数字
                剩余 = 剩余[:m.start()] + " " + 剩余[m.end():]
                break
    小写 = 剩余.lower()
    for 词 in _剧场版们:
        if (位置 := 小写.find(词)) >= 0:
            剧场版 = True
            剩余 = 剩余[:位置] + " " + 剩余[位置 + len(词):]
            break
    return 剩余, 季号, 剧场版


def _压平(文本: str) -> str:
    """只留"字母/数字/CJK"，其余变空格再合并（标点、括号、emoji 全当分隔符）。"""
    文本 = 转半角(文本 or "").lower()
    文本 = re.sub(f"[^{_保留}]+", " ", 文本)
    return re.sub(r"\s+", " ", 文本).strip()


def 规范化标题(文本: str) -> str:
    """归一化标题：全角转半角、去标点空白、统一大小写；**季号/剧场版信息保留**（搬到结尾）。

    为什么标点当分隔符而不是直接删：``Spider-Man`` 与 ``Spider Man`` 要归一成同一个；
    但 ``dune part two`` 的词间空格不能被吃掉，所以统一成"单个空格"。
    """
    核心, 季号, 剧场版 = 区分季与剧场版(文本)
    规范 = _压平(核心)
    if 季号 is not None:
        规范 = f"{规范} s{季号}".strip()
    if 剧场版:
        规范 = f"{规范} 剧场版".strip()
    return 规范


def _词集合(文本: str) -> set[str]:
    """英文按词、中文按**双字组**切（中文没空格，双字组是最省事的近似）。"""
    规范 = _压平(文本)
    词们: set[str] = set(re.findall(r"[a-z0-9]+", 规范))
    for 段 in re.findall(r"[\u4e00-\u9fff\u3040-\u30ff\uac00-\ud7af]+", 规范):
        if len(段) == 1:
            词们.add(段)
        else:
            词们.update(段[i:i + 2] for i in range(len(段) - 1))
    return 词们


def _编辑距离(甲: str, 乙: str) -> int:
    """Levenshtein（滚动数组）。不引 ``difflib``：V2 的依赖白名单里没有它。"""
    if 甲 == 乙:
        return 0
    if not 甲 or not 乙:
        return len(甲) or len(乙)
    上一行 = list(range(len(乙) + 1))
    for i, 字甲 in enumerate(甲, start=1):
        当前行 = [i] + [0] * len(乙)
        for j, 字乙 in enumerate(乙, start=1):
            当前行[j] = min(上一行[j] + 1, 当前行[j - 1] + 1,
                        上一行[j - 1] + (0 if 字甲 == 字乙 else 1))
        上一行 = 当前行
    return 上一行[-1]


def 是包含关系(甲: str, 乙: str) -> bool:
    """归一化之后一个是另一个的子串（"沙丘" ⊂ "沙丘2"），且不相等。"""
    左, 右 = 规范化标题(甲), 规范化标题(乙)
    return bool(左 and 右 and 左 != 右 and (左 in 右 or 右 in 左))


def 标题相似度(甲: str, 乙: str) -> float:
    """0..1 的标题相似度（编辑距离 0.6 + 词集合 Jaccard 0.4）。

    "包含关系"（一个是另一个的子串）**给 0.9**，不给 1.0 —— 续集/同名前作就靠这一档区分：
    ``沙丘`` vs ``沙丘2`` 拿不到满分，再叠上"年份不符"就落不到自动采纳线以上。
    """
    左, 右 = 规范化标题(甲), 规范化标题(乙)
    if not 左 or not 右:
        return 0.0
    if 左 == 右:
        return 1.0
    if 左 in 右 or 右 in 左:
        return 包含相似度
    最长 = max(len(左), len(右))
    编辑 = 1.0 - _编辑距离(左, 右) / 最长
    集左, 集右 = _词集合(左), _词集合(右)
    并集 = 集左 | 集右
    雅卡尔 = (len(集左 & 集右) / len(并集)) if 并集 else 0.0
    return max(0.0, min(1.0, _编辑距离权重 * 编辑 + _词集权重 * 雅卡尔))


# ============================ 打分 ============================


def _年份符合度(候选年份: int | None, 目标年份: int | None) -> float:
    if not 候选年份 or not 目标年份:
        return 年份符合度_未知          # 不知道就别奖也别罚（0.5）
    差 = abs(int(候选年份) - int(目标年份))
    if 差 == 0:
        return 1.0
    if 差 == 1:
        return 年份符合度_差一年        # 跨年上映/首播很常见：扣一半但可用
    return 0.0


def _结构符合度(候选: 匹配候选, 目标: 解析结果) -> float:
    """"结构" = 电影对电影、剧集对剧集。

    匹配候选里没有季/集字段（官方搜索接口不返回季集），所以这里只能比类型；
    季集对不对要靠详情抓取 + 人工确认，理由里会写明"结构未知"。
    """
    期望 = "movie" if 目标.类型 == "电影" else ("tv" if 目标.类型 in ("集", "剧集") else "")
    if not 期望 or 候选.类型 is 媒体类型.未知:
        return 0.5
    return 1.0 if 候选.类型.value == 期望 else 0.0


def _热度分(热度: float) -> float:
    """热度只用来破平：最多 +5；100 以上给满（popularity 上不封顶，不能线性用）。"""
    return min(权重["热度上限"], 权重["热度上限"] * min(1.0, max(0.0, 热度 or 0.0) / 100.0))


def 打分候选(候选: 匹配候选, 目标: 解析结果,
          别名们: list[str] = ()) -> tuple[float, str]:
    """给一个候选打 0–100 分，返回 ``(分数, 理由)``，并写回 ``候选.分数/理由/额外["匹配细节"]``。

    权重：标题 45 / 别名 15 / 年份 30 / 结构 10，热度最多 +5。
    别名**不额外加分**（它和标题同源）：别名的作用是"让别的写法也能匹配上"，
    再单独加分会让同一部片子被重复计分。
    """
    目标标题 = (目标.标题 or "").strip()
    主相似 = max(标题相似度(候选.标题, 目标标题), 标题相似度(候选.原名, 目标标题))
    别名相似 = 0.0
    命中别名 = ""
    for 别名 in 别名们 or ():
        if not (别名 or "").strip():
            continue
        值 = max(标题相似度(候选.标题, 别名), 标题相似度(候选.原名, 别名))
        if 值 > 别名相似:
            别名相似, 命中别名 = 值, 别名
    名称一致度 = max(主相似, 别名相似)
    年份度 = _年份符合度(候选.年份, 目标.年份)
    结构度 = _结构符合度(候选, 目标)
    热度 = _热度分(候选.热度)
    分数 = round(max(0.0, min(100.0, 权重["标题"] * 名称一致度
                           + 权重["别名"] * 名称一致度
                           + 权重["年份"] * 年份度
                           + 权重["结构"] * 结构度 + 热度)), 1)
    细节 = {"主标题相似度": round(主相似, 3), "别名相似度": round(别名相似, 3),
          "名称一致度": round(名称一致度, 3), "年份符合度": round(年份度, 3),
          "结构符合度": round(结构度, 3), "热度分": round(热度, 2),
          "包含关系": bool(主相似 < 1.0 and (是包含关系(候选.标题, 目标标题)
                                    or 是包含关系(候选.原名, 目标标题))),
          "命中别名": 命中别名}
    候选.分数 = 分数
    候选.理由 = _理由(候选, 目标, 主相似, 别名相似, 年份度, 结构度, 热度, 命中别名)
    候选.额外 = {**(候选.额外 or {}), "匹配细节": 细节}
    return 分数, 候选.理由


def _理由(候选: 匹配候选, 目标: 解析结果, 主相似: float, 别名相似: float,
        年份度: float, 结构度: float, 热度: float, 命中别名: str) -> str:
    部分: list[str] = []
    if 主相似 >= 0.999:
        部分.append("标题完全一致")
    elif 主相似 >= 包含相似度:
        部分.append(f"标题包含关系（{主相似:.2f}，疑似续集/同名前作）")
    elif 主相似 > 0:
        部分.append(f"标题相似 {主相似:.2f}")
    else:
        部分.append("标题对不上")
    if 命中别名 and 别名相似 > 主相似:
        部分.append(f"命中别名「{命中别名}」（{别名相似:.2f}）")
    if not 目标.年份 or not 候选.年份:
        部分.append(f"年份未知（按 {年份度:.2f} 计）")
    elif 年份度 >= 0.999:
        部分.append(f"年份一致（{候选.年份}）")
    elif 年份度 > 0:
        部分.append(f"年份差 1 年（候选 {候选.年份}，解析 {目标.年份}）")
    else:
        部分.append(f"年份不符（候选 {候选.年份}，解析 {目标.年份}）")
    if 结构度 >= 0.999:
        部分.append("结构一致")
    elif 结构度 <= 0:
        部分.append(f"结构不符（候选 {候选.类型.value}，解析为{目标.类型}）")
    else:
        部分.append("结构未知")
    if 热度 > 0:
        部分.append(f"热度 {候选.热度:.1f}（+{热度:.1f}）")
    return "；".join(部分)


def 排序候选(候选们, 目标: 解析结果, 别名们: list[str] = ()) -> list[匹配候选]:
    """按分数从高到低排序（顺手把 分数/理由/匹配细节 写回候选对象，界面直接拿来显示）。

    同分破平：热度高者先 → 年份更接近者先 → 来源标识（保证结果可复现）。
    """
    列表 = list(候选们 or [])
    for 候选 in 列表:
        打分候选(候选, 目标, 别名们)
    return sorted(列表, key=lambda c: (-c.分数, -c.热度,
                                   abs((c.年份 or 0) - (目标.年份 or c.年份 or 0)),
                                   str(c.来源标识)))


def 自动决策(候选们, 目标: 解析结果, 自动阈值: float = 78.0,
         差距阈值: float = 12.0) -> tuple[匹配候选 | None, bool, str]:
    """能不能自动采纳：返回 ``(采纳的候选或 None, 是否需要人工确认, 说明)``。

    三种情况要人工确认（宁可不刮，也别刮错）：

    1. 最高分低于 ``自动阈值``；
    2. 与次佳的差距小于 ``差距阈值``（两个都挺像 = 让用户点一下）；
    3. "硬伤"任何一条都直接交人工：标题是**包含关系**且年份对不上（``沙丘`` vs ``沙丘2``）、
       或者**类型不符**（电影文件配到剧集上、反过来也是）。为什么用硬规则而不是加重权重：
       官方给的权重里"结构"只占 10 分，标题年份全对时类型错了也还有 90 分 —— 光靠分数
       拦不住这种错，必须显式拦。
    """
    排序后 = 排序候选(候选们, 目标)
    if not 排序后:
        return None, True, "没有候选，需要人工搜索或手动填 ID"
    最佳 = 排序后[0]
    次佳 = 排序后[1] if len(排序后) > 1 else None
    原因: list[str] = []
    if 最佳.分数 < 自动阈值:
        原因.append(f"最佳候选只有 {最佳.分数:.1f} 分，低于自动阈值 {自动阈值:.0f}")
    if 次佳 is not None and (最佳.分数 - 次佳.分数) < 差距阈值:
        原因.append(f"与次佳「{次佳.标题}」（{次佳.分数:.1f} 分）只差 "
                 f"{最佳.分数 - 次佳.分数:.1f} 分，太接近")
    细节 = (最佳.额外 or {}).get("匹配细节") or {}
    if 细节.get("包含关系") and 细节.get("年份符合度", 0) < 1:
        原因.append("标题是包含关系且年份不一致（可能是续集或同名前作）")
    if 细节.get("结构符合度") == 0:
        原因.append(f"类型不符（候选是{最佳.类型.value}，解析结果是{目标.类型}）")
    if 原因:
        return None, True, "需要人工确认：" + "；".join(原因)
    return 最佳, False, (f"自动采纳「{最佳.标题}」（{最佳.分数:.1f} 分）：{最佳.理由}")


# ============================ 查询词 ============================


def 从文件名猜查询词(路径: Path) -> list[str]:
    """给 TMDB 搜索用的查询词，按"从具体到宽松"排：

    1. ``标题 年份``（最准，能避开翻拍）；
    2. ``标题``；
    3. 去掉季/剧场版标识的标题（"剧名 第二季" → "剧名"）；
    4. 去掉字幕组前缀的标题（番剧 ``[字幕组][剧名][1080p][BDRip]`` → "剧名"）。

    返回去重后的词表（最多 4 个）；调用方按顺序试，命中即停。
    """
    结果 = 猜剧集路径(Path(路径))
    基础 = (结果.标题 or "").strip()
    词们: list[str] = []
    if 基础 and 结果.年份:
        词们.append(f"{基础} {结果.年份}")
    if 基础:
        词们.append(基础)
    核心, _季, _剧场版 = 区分季与剧场版(基础)
    核心 = 核心.strip(" -–—_.·")
    if 核心 and 核心 != 基础:
        词们.append(核心)
    衍生 = _去组前缀(Path(路径).name)
    if 衍生 and 衍生 != Path(路径).name:
        # 再走一遍解析：把衍生名里的发布标签（1080p/BDRip）也清掉
        组标题 = (解析(衍生).标题 or "").strip()
        if 组标题:
            词们.append(组标题)
    去重: list[str] = []
    for 词 in 词们:
        词 = " ".join(词.split())
        if 词 and 词 not in 去重:
            去重.append(词)
    return 去重[:4]


def _是标签组(内容: str) -> bool:
    """方括号里装的是发布标签吗（1080p / BDRip / x265 / 10bit …）。"""
    return bool(re.fullmatch(
        r"\s*(?:\d{3,4}[pi]|4k|8k|uhd|hd|sd|bluray|blu-ray|bdrip|brrip|web-?dl|webrip|"
        r"web|hdtv|dvdrip|dvd|remux|hdrip|x264|x265|h264|h265|hevc|avc|av1|xvid|divx|"
        r"aac|ac3|eac3|dts(?:-hd)?|flac|mp3|truehd|atmos|\d+bit|hdr\d*|10bit|8bit|"
        r"repack|proper|chs|cht|gb|big5|简|繁|简繁|中字|双语|內封|内封|外挂)\s*",
        (内容 or "").strip(), re.I))


def _去组前缀(文件名: str) -> str:
    """番剧命名 ``[字幕组][剧名][1080p][BDRip].mkv`` → ``剧名.mkv``（去掉组前缀的新文件名）。

    不这么做的后果：查询词会变成 "Nekomoe kissaten Movie Title"，TMDB 一条都搜不到。
    没有方括号前缀时返回空串（表示"没有这个变体"），调用方会跳过它。
    """
    名字 = (文件名 or "").strip()
    if not 名字:
        return ""
    主名 = Path(名字).stem if "." in 名字 else 名字
    组们 = list(re.finditer(r"[\[【]([^\]】]{1,40})[\]】]", 主名))
    if not 组们 or 组们[0].start() != 0:
        return ""
    后面 = 主名[组们[0].end():]
    头 = re.split(r"[\[【]", 后面)[0].strip(" ._-")
    if 头 and not _是标签组(头):
        return f"{头}.mkv"
    for m in 组们[1:]:
        内容 = m.group(1).strip()
        if 内容 and not _是标签组(内容):
            return f"{内容}.mkv"
    return ""
