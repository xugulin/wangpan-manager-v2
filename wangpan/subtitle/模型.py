"""字幕数据模型：一条字幕（:class:`字幕条目`）与一条轨道（:class:`字幕轨道`）。

为什么单独一层
==============
"解析各种格式"、"按播放时间取条目"、"画到画面上"这三件事的变化原因完全不同：
格式会越加越多（VTT / 内嵌 / SUP），取法要够快（界面每 16ms 问一次），
画法要跟着界面走。所以模型层只放 **数据 + 查找**：不 import Qt，也不认识任何文件格式，
能脱离界面单测。

为什么"取"必须是二分
====================
一部长片几千条字幕，界面每一帧都要问"现在该显示哪条"。线性扫一遍几千条 × 60 次/秒，
光这一项就能把主线程拖出可见卡顿（这类卡顿还会被误判成"解码慢"）。
⇒ 建轨道时就把条目按起始秒排好，查找走二分，见 :meth:`字幕轨道.取`。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

__all__ = ["字幕条目", "字幕轨道", "空样式", "位置底部", "位置顶部", "位置中间",
           "样式键们"]

#: 垂直位置取值。解析、绘制、界面共用同一套字符串，别各写各的（写错了不报错，只是位置不对）
位置底部 = "底部"
位置顶部 = "顶部"
位置中间 = "中间"

#: 样式里"对外承诺"的键（值是"没设"时的默认）。其余键（如 ASS 换算出来的比例）是补充信息
样式键们 = ("字号", "颜色", "粗体", "斜体", "位置", "对齐")


def 空样式() -> dict:
    """一套"什么都没设"的样式（缺的键补齐成 None/False）。

    为什么要补齐所有键：上层（绘制、界面、后续里程碑）要能无脑 ``样式["位置"]`` 取值，
    不该到处都是 ``if "位置" in 样式``。None/False 的语义就是"按默认来"。
    """
    return {"字号": None, "颜色": None, "粗体": False, "斜体": False,
            "位置": None, "对齐": None}


def 补全样式(样式: Optional[dict]) -> dict:
    """把局部样式并到 :func:`空样式` 上（保留"字号比例"这类补充键）。"""
    结果 = 空样式()
    if 样式:
        结果.update(样式)
    return 结果


@dataclass
class 字幕条目:
    """一条字幕：时间段 + 纯文本 + 可选样式。

    ``文本`` 是**已经去掉样式标签**的纯文本（多行用 ``\\n``）；
    ``原始`` 留着排查用（ASS 的原始 Dialogue 行 / SRT 的原文块）——
    解析出问题时，光看纯文本是看不出"标签有没有被吃掉"的。
    """

    起始秒: float
    结束秒: float
    文本: str
    样式: dict = field(default_factory=dict)
    原始: str = ""

    @property
    def 时长秒(self) -> float:
        return max(0.0, float(self.结束秒) - float(self.起始秒))

    def 覆盖(self, 秒: float) -> bool:
        """两端都算命中：播放头正好停在起始/结束时刻上时，这条也该显示。"""
        return self.起始秒 <= 秒 <= self.结束秒

    def 样式值(self, 键: str, 默认=None):
        """取样式（``样式`` 可能是手工构造的空 dict，别直接下标）。"""
        return (self.样式 or {}).get(键, 默认)


@dataclass
class 字幕轨道:
    """一条字幕轨（一个文件 = 一条轨；以后"内嵌轨"也用这个类型）。

    ``来源``：``"srt"`` / ``"ass"`` / ``"ssa"`` / ``"vtt"`` / ``"内嵌"``。
    """

    名字: str
    条目们: list = field(default_factory=list)
    来源: str = ""

    def __post_init__(self) -> None:
        # 二分依赖有序：在这里排一次，别指望调用方保证 —— 解析器、手工构造、
        # 以后从容器里抽出来的内嵌轨，三条来源都得守这个规矩。
        # 传进来的可能是元组/生成器（手工构造时很常见），先落成 list。
        self.条目们 = list(self.条目们)
        self.条目们.sort(key=lambda 条: 条.起始秒)      # stable：同一时刻的多条保持原顺序
        # 最长条目的时长：取() 往回找重叠字幕时的下界，见 取()
        self._最长秒 = max((条.时长秒 for 条 in self.条目们), default=0.0)

    # ---------------- 查询 ----------------

    def 取(self, 秒: float) -> Optional[字幕条目]:
        """当前该显示哪条（没有就是 ``None``）。**二分查找**，O(log n)。

        为什么不用 ``bisect``：独立性测试的依赖白名单里没有它（多一个 import 就多一条
        要维护的"计划外依赖"），而这里要的语义是"起始秒 <= 秒 里最靠右的一条"，
        手写六行反而更直白。
        """
        条目们 = self.条目们
        左, 右 = 0, len(条目们) - 1
        命中 = -1
        while 左 <= 右:
            中 = (左 + 右) // 2
            if 条目们[中].起始秒 <= 秒:
                命中 = 中
                左 = 中 + 1
            else:
                右 = 中 - 1
        # 正常字幕是"上一条结束、下一条开始"，二分命中的就是它；只有重叠/嵌套字幕
        # 才需要往回看。回看的下界用"最长条目时长"卡住，保证不会退化成线性扫描。
        索引 = 命中
        while 索引 >= 0 and 秒 - 条目们[索引].起始秒 <= self._最长秒:
            if 条目们[索引].覆盖(秒):
                return 条目们[索引]
            索引 -= 1
        return None

    def 在区间(self, 起: float, 止: float) -> list:
        """与 ``[起, 止]`` 有交集的条目（按时间序）。

        "交集"而不是"起点落在区间里"：一条字幕从区间前就开始、一直盖到区间里，
        对这份区间来说它当然算数（字幕列表/导出/剪辑都用这个语义）。
        """
        if 止 < 起:                     # 调用方传反了不至于返回空
            起, 止 = 止, 起
        条目们 = self.条目们
        左, 右 = 0, len(条目们)
        while 左 < 右:                  # 二分：第一条"起始秒 >= 起"的
            中 = (左 + 右) // 2
            if 条目们[中].起始秒 < 起:
                左 = 中 + 1
            else:
                右 = 中
        起点 = 左
        while 起点 > 0 and 条目们[起点 - 1].结束秒 >= 起:   # 往前收下"跨过起点"的
            起点 -= 1
        结果 = []
        索引 = 起点
        while 索引 < len(条目们) and 条目们[索引].起始秒 <= 止:
            if 条目们[索引].结束秒 >= 起:
                结果.append(条目们[索引])
            索引 += 1
        return 结果

    @property
    def 空(self) -> bool:
        return not self.条目们

    def __len__(self) -> int:
        return len(self.条目们)
