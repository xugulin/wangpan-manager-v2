"""字幕模块（M4）：SRT/ASS 解析 + 按时间取条目 + 自绘叠加。

对外契约（界面与后续里程碑只按这些名字调用）::

    from wangpan.subtitle import (字幕条目, 字幕轨道, 解析SRT, 解析ASS,
                                  读字幕文件, 找同名字幕, 画字幕)

为什么拆成三个文件（而不是一个 800 行的 字幕.py）
================================================
* :mod:`~wangpan.subtitle.模型`：纯数据 + 二分查找。不 import Qt，也不认识任何文件格式
  → 解析格式和画法怎么改都不影响它，也能脱离界面单测；
* :mod:`~wangpan.subtitle.解析`：各种格式 → 条目。同样不 import Qt（解析跟界面无关）；
* :mod:`~wangpan.subtitle.绘制`：条目 → 画面。唯一 import QtGui 的地方。

于是"加一种字幕格式"（内嵌轨、SUP 图形字幕）和"改画法"（字体、阴影、样式表）
互不干扰 —— 这正是 M1 分层那套思路在字幕上的延续。
"""

