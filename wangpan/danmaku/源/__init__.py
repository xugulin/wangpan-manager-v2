def 建默认源(配置: Optional[dict] = None) -> list[弹幕源]:
    """建一组默认源：**Animeko（零凭据）+ 弹弹play + 本地**，顺序就是优先级。

    ``配置`` 支持的键（都可不给）：

    * ``"appId"`` / ``"appSecret"`` —— 显式凭证（不传就从环境变量/配置文件读）；
    * ``"传输"`` —— 注入的 HTTP 传输函数（测试用，生产别给）；
    * ``"缓存目录"`` / ``"缓存TTL秒"`` / ``"chConvert"`` / ``"最小请求间隔秒"``；
    * ``"本地"`` —— False 就不要本地源（比如只想要网络弹幕）。

    为什么本地源放在后面：网络弹幕是"主体"（人多、时效新），本地文件是补充/离线兜底；
    合并去重交给 :class:`~wangpan.danmaku.模型.弹幕池` 的 ``合并(去重=True)``。
    """
    配置 = dict(配置 or {})
    允许的键 = {"appId", "appSecret", "传输", "基地址", "缓存目录", "缓存TTL秒",
              "chConvert", "配置路径", "读环境", "时钟", "睡眠",
              "最小请求间隔秒", "超时秒", "读哈希"}
    未认 = sorted(set(配置) - 允许的键 - {"本地"})
    if 未认:
        # 不抛错：多一个键（比如界面把整份配置丢进来）不该让播放起不来
        logging.getLogger(__name__).warning("建默认源：忽略了不认识的配置项 %s", 未认)
    要本地 = bool(配置.get("本地", True))
    网络配置 = {键: 值 for 键, 值 in 配置.items() if 键 in 允许的键}
    # 顺序 = 优先级：Animeko 公益弹幕（**不需要凭据**，实测可用）排最前，
    # 其次是弹弹play（需要 AppId+签名，个人开发者要审核），最后是本地文件兜底。
    # 这样"什么凭据都没配"的用户也能拿到在线弹幕。
    源们: list[弹幕源] = [Animeko源()]
    网络配置.pop("appId", None)      # 这些是弹弹play 专用参数，别透传给 Animeko
    网络配置.pop("appSecret", None)
    网络配置.pop("chConvert", None)
    网络配置.pop("读哈希", None)
    网络配置.pop("配置路径", None)
    网络配置.pop("读环境", None)
    源们.append(弹弹play源(**网络配置))
    if 要本地:
        源们.append(本地源())
    return 源们
