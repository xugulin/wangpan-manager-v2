"""轨道分配与定位（从零实现）。

核心思想：**弹幕的位置是"帧时间的纯函数"**，不是"每帧累加位移"。
这样丢帧、卡顿、暂停、跳转之后位置依然正确，也不会累积浮点误差。

三条硬规则
==========
1. **进入与退出**：滚动弹幕在 `t0` 时刻从右边缘外侧进入，**整条完全飞出左边缘**才算结束；
   顶部/底部固定弹幕不横move，显示 `固定停留毫秒`。
2. **同轨不追尾**（本项目自己的判据，等价于"整段时间里两条弹幕的间隙始终 ≥ 安全间距"）：
   设轨道上最后一条是 L（进入时刻 t_L、宽度 w_L、速度 v_L），新来的是 N（t_N、w_N、v_N）。
   两者间隙 `g(t) = (x_L(t) + w_L) - (x_N(t) + w_N)`，其中 `x(t) = W - (t - t0) * v`，
   于是 `g'(t) = v_N - v_L` 是常数 —— 也就是说间隙在时间上是**单调**的，
   所以**只要在两端都不小于安全间距**，整段时间就都满足：
   * 进入时刻：`g(t_N) ≥ 间距`
   * L 的尾部飞出屏幕的时刻：`g(t_L + (W + w_L) / v_L) ≥ 间距`
   这条判据比"只看进入时刻的间距"严谨（后者在 N 比 L 快时会追尾），
   又比"逐帧检查碰撞"便宜得多（O(1)）。
3. **长弹幕加速**：越长的弹幕在屏幕上待得越久，遮挡越严重 → 按
   `(宽度 / 基准宽度) ** 指数` 提速（有上限）。**同一个 id 的速度是确定的**（用哈希做抖动），
   这样重播时位置一致，不会"这次在左边那次在右边"。
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from typing import Iterable, Optional

from .模型 import 弹幕, 弹幕模式, 弹幕配置

__all__ = ["屏幕布局", "轨道占用", "轨道分配器", "定位结果"]


@dataclass
class 屏幕布局:
    """把控件尺寸 + 配置换算成像素级参数（避免各处重复算）。"""

    宽: int
    高: int
    字号: int
    轨道高: int
    显示区高: int
    基准宽度: int              # 长弹幕加速的"基准文本宽度"
    基准速度: float            # 像素/秒（按控件高度归一后）

    @classmethod
    def 由尺寸与配置(cls, 宽: int, 高: int, 配置: 弹幕配置) -> "屏幕布局":
        宽 = max(1, int(宽))
        高 = max(1, int(高))
        字号 = int(round(高 * 配置.字号比例))
        字号 = max(配置.最小字号像素, min(配置.最大字号像素, 字号))
        轨道高 = max(字号 + 2, int(round(字号 * 配置.轨道间距比例)))
        显示区高 = max(轨道高, int(高 * max(0.05, min(1.0, 配置.显示区比例))))
        # 速度按高度归一：1080p 下调好的手感，换到别的分辨率依然合适
        基准速度 = max(20.0, 配置.速度像素每秒 * (高 / 1080.0))
        基准宽度 = max(40, int(宽 * 0.25))
        return cls(宽=宽, 高=高, 字号=字号, 轨道高=轨道高, 显示区高=显示区高,
                  基准宽度=基准宽度, 基准速度=基准速度)

    @property
    def 滚动轨道数(self) -> int:
        return max(1, self.显示区高 // self.轨道高)

    @property
    def 顶部轨道数(self) -> int:
        return max(1, (self.显示区高 // 2) // self.轨道高)

    @property
    def 底部轨道数(self) -> int:
        return max(1, (self.显示区高 // 2) // self.轨道高)

    def 轨道纵坐标(self, 模式: 弹幕模式, 序号: int) -> int:
        """某条轨道里弹幕的**顶部** y 坐标。"""
        if 模式 is 弹幕模式.顶部:
            return 序号 * self.轨道高
        if 模式 is 弹幕模式.底部:
            # 底部从下往上排（第 0 条贴底）
            return max(0, self.高 - (序号 + 1) * self.轨道高)
        return 序号 * self.轨道高


@dataclass
class 轨道占用:
    """一条轨道上"最后一条弹幕"的信息（用于判据 2）。"""

    进入毫秒: int
    宽度: int
    速度: float            # 像素/秒
    文本: str = ""

    def 位置x(self, 现在毫秒: int, 屏宽: int) -> float:
        """弹幕左边缘的 x 坐标（纯函数）。"""
        return 屏宽 - (现在毫秒 - self.进入毫秒) / 1000.0 * self.速度

    def 尾部飞出时刻(self, 屏宽: int) -> float:
        """整条完全飞出左边缘的时刻（毫秒）。"""
        return self.进入毫秒 + (屏宽 + self.宽度) / max(1.0, self.速度) * 1000.0


@dataclass
class 定位结果:
    """一条弹幕"现在"该画在哪儿。"""

    弹幕: 弹幕
    模式: 弹幕模式
    x: float
    y: int
    速度: float
    宽度: int
    字号: int
    序号: int = 0                 # 轨道序号（调试用）

    @property
    def 可见(self) -> bool:
        return self.x is not None


class 轨道分配器:
    """把弹幕分配到轨道上；**同一帧内先来后到**，分配好就不再变。"""

    def __init__(self, 配置: 弹幕配置) -> None:
        self.配置 = 配置
        #: 模式 → 轨道序号 → 最后一条占用
        self._占用: dict[弹幕模式, dict[int, 轨道占用]] = {
            弹幕模式.滚动: {}, 弹幕模式.顶部: {}, 弹幕模式.底部: {}}
        #: 弹幕标识 → (模式, 轨道号, 进入毫秒, 速度, 宽度, 字号)
        self._已排: dict[int, tuple[弹幕模式, int, int, float, int, int]] = {}
        self.丢弃数 = 0
        self.排入数 = 0

    # ---------------- 清空 ----------------

    def 清空(self) -> None:
        for 表 in self._占用.values():
            表.clear()
        self._已排.clear()
        self.丢弃数 = 0
        self.排入数 = 0

    # ---------------- 速度与宽度 ----------------

    def 计算速度(self, 文本宽度: int, 布局: 屏幕布局, 标识: int = 0) -> float:
        """滚动弹幕速度：按长度提速 +（可选的）确定性抖动。"""
        速度 = 布局.基准速度
        if self.配置.长弹幕加速 and 布局.基准宽度 > 0:
            比例 = max(1.0, 文本宽度 / 布局.基准宽度)
            倍率 = 比例 ** max(0.0, self.配置.加速指数)
            倍率 = min(max(1.0, self.配置.加速上限倍率), 倍率)
            速度 *= 倍率
        if self.配置.抖动比例 > 0:
            # 用 id 做确定性抖动（同一条弹幕每次播放速度一致）
            种子 = int.from_bytes(hashlib.blake2s(str(标识).encode(), digest_size=2).digest(),
                                "big") / 65535.0
            速度 *= 1.0 + (种子 - 0.5) * 2.0 * max(0.0, min(0.5, self.配置.抖动比例))
        return max(10.0, 速度)

    # ---------------- 判据 ----------------

    def _能放下(self, 占用: 轨道占用, 新进入毫秒: int, 新宽度: int, 新速度: float,
              布局: 屏幕布局) -> bool:
        """判据 2：两端间隙都不小于安全间距。"""
        间距 = self.配置.安全间距像素
        # ① 进入时刻：老弹幕尾部必须已经离开"右边缘 - 间距"
        老尾在进入时刻 = 占用.位置x(新进入毫秒, 布局.宽) + 占用.宽度
        if 老尾在进入时刻 > 布局.宽 - 间距:
            return False
        # ② 在老弹幕**整条飞出屏幕**的时刻，新弹幕的头部（左边缘）必须还在老弹幕尾部右侧
        #    （间隙 ≥ 间距）—— 因为间隙随时间单调变化，两端都满足就整段时间都满足。
        飞出时刻 = 占用.尾部飞出时刻(布局.宽)                 # 此刻老弹幕尾部正好在 x=0
        新头 = 布局.宽 - (飞出时刻 - 新进入毫秒) / 1000.0 * 新速度
        return 新头 >= 间距

    def 分配(self, 条: 弹幕, 文本宽度: int, 布局: 屏幕布局,
           文本字号: Optional[int] = None) -> Optional[定位结果]:
        """给一条弹幕找轨道；找不到返回 None（**丢弃**，不排队等 —— 排队会让画面延迟）。"""
        键 = id(条) if not 条.标识 else hash((条.标识, 条.毫秒, 条.文本)) & 0x7FFFFFFF
        if 键 in self._已排:
            模式, 序号, 进入, 速度, 宽, 字号 = self._已排[键]
            return self._定位(条, 模式, 序号, 进入, 速度, 宽, 字号, 布局, 条.毫秒)

        模式 = 条.模式
        if 模式 is 弹幕模式.顶部 and not self.配置.允许顶部:
            return None
        if 模式 is 弹幕模式.底部 and not self.配置.允许底部:
            return None
        字号 = int(文本字号 or 布局.字号)
        if 模式 is 弹幕模式.滚动:
            速度 = self.计算速度(文本宽度, 布局, 键)
            轨道数 = 布局.滚动轨道数
        else:
            速度 = 0.0
            轨道数 = (布局.顶部轨道数 if 模式 is 弹幕模式.顶部
                    else 布局.底部轨道数)
        表 = self._占用[模式]
        for 序号 in range(轨道数):
            占 = 表.get(序号)
            if 占 is None:
                break
            if 模式 is not 弹幕模式.滚动:
                # 固定弹幕：上一条显示完就能再用（同一个位置）
                if 条.毫秒 >= 占.尾部飞出时刻(布局.宽) or (
                        条.毫秒 - 占.进入毫秒 >= self.配置.固定停留毫秒):
                    break
                continue
            if self._能放下(占, 条.毫秒, 文本宽度, 速度, 布局):
                break
        else:
            self.丢弃数 += 1
            return None                 # 所有轨道都放不下 → 丢弃（比延迟显示更不打扰）

        进入 = 条.毫秒
        表[序号] = 轨道占用(进入毫秒=进入, 宽度=文本宽度, 速度=速度, 文本=条.文本)
        self._已排[键] = (模式, 序号, 进入, 速度, 文本宽度, 字号)
        self.排入数 += 1
        return self._定位(条, 模式, 序号, 进入, 速度, 文本宽度, 字号, 布局, 条.毫秒)

    # ---------------- 定位 ----------------

    def _定位(self, 条: 弹幕, 模式: 弹幕模式, 序号: int, 进入毫秒: int,
            速度: float, 宽度: int, 字号: int, 布局: 屏幕布局,
            现在毫秒: Optional[int] = None) -> 定位结果:
        """算"现在该画在哪"。

        ⚠️ 必须传**当前时刻**：位置 = 入场位置 − 经过时间 × 速度。
        这里踩过一次坑：写成用弹幕自己的时间戳，于是 x 恒等于入场位置，弹幕看起来不动。
        """
        现在毫秒 = 条.毫秒 if 现在毫秒 is None else int(现在毫秒)
        y = 布局.轨道纵坐标(模式, 序号)
        if 模式 is 弹幕模式.滚动:
            x = 布局.宽 - (现在毫秒 - 进入毫秒) / 1000.0 * 速度
        else:
            x = (布局.宽 - 宽度) / 2.0
        return 定位结果(弹幕=条, 模式=模式, x=x, y=y, 速度=速度, 宽度=宽度,
                    字号=字号, 序号=序号)

    def 已排定位(self, 条: 弹幕, 现在毫秒: int, 布局: 屏幕布局) -> Optional[定位结果]:
        """对**已经排过**的弹幕取当前定位（不改状态，纯查询）。"""
        键 = id(条) if not 条.标识 else hash((条.标识, 条.毫秒, 条.文本)) & 0x7FFFFFFF
        排 = self._已排.get(键)
        if 排 is None:
            return None
        模式, 序号, 进入, 速度, 宽度, 字号 = 排
        return self._定位(条, 模式, 序号, 进入, 速度, 宽度, 字号, 布局, 现在毫秒)

    def 过期清理(self, 现在毫秒: int, 布局: 屏幕布局) -> int:
        """把已经飞出屏幕的弹幕从表里清掉（否则长时间播放会越积越多）。"""
        去掉 = 0
        for 模式, 表 in self._占用.items():
            死的 = [序号 for 序号, 占 in 表.items()
                   if 现在毫秒 >= 占.尾部飞出时刻(布局.宽) + 500
                   or (模式 is not 弹幕模式.滚动
                       and 现在毫秒 >= 占.进入毫秒 + self.配置.固定停留毫秒 + 500)]
            for 序号 in 死的:
                del 表[序号]
                去掉 += 1
        if self._已排 and 去掉:
            # 同步清理"已排"表：只保留还可能可见的
            保留: dict[int, tuple] = {}
            for 键, 值 in self._已排.items():
                模式, 序号, 进入, 速度, 宽度, 字号 = 值
                if 模式 is 弹幕模式.滚动:
                    寿命 = (布局.宽 + 宽度) / max(1.0, 速度) * 1000.0
                else:
                    寿命 = self.配置.固定停留毫秒
                if 现在毫秒 <= 进入 + 寿命 + 1000:
                    保留[键] = 值
            self._已排 = 保留
        return 去掉

    def 统计(self) -> dict:
        return {"排入": self.排入数, "丢弃": self.丢弃数,
                "轨道占用": {模式.value: len(表) for 模式, 表 in self._占用.items()},
                "在册": len(self._已排)}
