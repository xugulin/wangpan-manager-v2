@dataclass
class 匹配决策:
    """一次匹配的结论：自动采纳了哪个 / 还是得让人点一下。"""

    采纳: Optional[匹配结果] = None
    候选们: list[匹配结果] = field(default_factory=list)
    需要人工确认: bool = False
    说明: str = ""

    def 选中标识(self) -> str:
        return self.采纳.标识 if self.采纳 is not None else ""


def 自动决策(候选们: Sequence[匹配结果], 素材: 素材信息,
           自动阈值: float = 自动阈值, 差距阈值: float = 差距阈值) -> 匹配决策:
    """最高分 ≥ ``自动阈值`` 且领先第二名 ≥ ``差距阈值`` → 自动采纳；否则要人确认。"""
    排好 = 排序候选(候选们, 素材)
    if not 排好:
        return 匹配决策(None, [], True, "没有任何候选：没匹配上，请手动搜索或换个源")
    最高 = 排好[0]
    次高 = 排好[1] if len(排好) > 1 else None
    差距 = (最高.分数 - 次高.分数) if 次高 is not None else None
    if 最高.分数 < 自动阈值:
        return 匹配决策(None, 排好, True,
                      f"最高分只有 {最高.分数:.1f}（低于自动阈值 {自动阈值:.0f}），"
                      f"需要人工确认：{最高.说说()}")
    if 差距 is not None and 差距 < 差距阈值:
        return 匹配决策(None, 排好, True,
                      f"前两名只差 {差距:.1f} 分（不足 {差距阈值:.0f} 分），"
                      f"拿不准，需要人工确认：《{最高.标题}》"
                      f" vs 《{次高.标题}》")
    领先 = f"，领先 {差距:.1f} 分" if 差距 is not None else "，唯一候选"
    return 匹配决策(最高, 排好, False,
                  f"自动采纳《{最高.说说()}》（{最高.分数:.1f} 分{领先}）")


def 找弹幕(素材: 素材信息, 源们: Sequence[弹幕源]) -> 匹配决策:
    """串起"各源匹配 → 合并候选 → 打分 → 决策"。

    * 只问 :meth:`能匹配` 为真的源（本地源不打网络请求）；
    * **一个源抛异常只记日志**：网络抖一下不该让"本地文件明明有弹幕"也一起失败；
    * 候选里塞 ``原始["源"] = 源.标识``：:attr:`标识` 只在**源内**唯一，
      后面要按它回去 :meth:`取弹幕`，得知道找哪个源。
    """
    候选们: list[匹配结果] = []
    试过: list[str] = []
    坏了: list[str] = []
    for 源 in 源们 or []:
        if not 源.能匹配():
            continue
        试过.append(源.名字 or 源.标识)
        try:
            出 = 源.匹配(素材) or []
        except Exception as 错:  # noqa: BLE001  # 源失败不该拖垮整条链路
            坏了.append(f"{源.名字 or 源.标识}：{错}")
            日志.warning("源 %s 匹配失败（跳过它）：%s", 源.名字 or 源.标识, 错)
            continue
        for 候 in 出:
            候.原始 = dict(候.原始 or {})
            候.原始.setdefault("源", 源.标识)
            候选们.append(候)
    决策 = 自动决策(候选们, 素材)
    if 坏了:
        决策.说明 += "｜失败的源：" + "；".join(坏了)
    elif not 试过:
        决策.说明 += "｜没有可用的匹配源"
    return 决策


def 取弹幕(决策: 匹配决策, 源们: Sequence[弹幕源]) -> 弹幕池:
    """按决策取弹幕：用 ``原始["源"]`` 找到对应的源再取（找不到就按顺序问一遍）。

    这是 :func:`找弹幕` 的收尾动作，放在一起是为了让"选了哪个源"这件事只有一处解释。
    """
    if 决策.采纳 is None:
        raise 弹幕源错误("还没有采纳任何候选（需要人工确认或手动指定）")
    候选 = 决策.采纳
    想要的 = str((候选.原始 or {}).get("源") or "")
    顺序 = [源 for 源 in (源们 or []) if 源.标识 == 想要的] if 想要的 else []
    顺序 += [源 for 源 in (源们 or []) if 源.标识 != 想要的]
    if not 顺序:
        raise 弹幕源错误("没有可用的弹幕源")
    最后: Optional[Exception] = None
    for 源 in 顺序:
        try:
            return 源.取弹幕(候选.标识)
        except 弹幕源错误 as 错:
            最后 = 错
            日志.warning("从 %s 取弹幕失败：%s", 源.名字 or 源.标识, 错)
    raise 最后 if 最后 is not None else 弹幕源错误("所有源都取不到弹幕")
