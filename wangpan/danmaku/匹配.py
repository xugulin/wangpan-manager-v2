#: 默认自动采纳阈值（0-100）。低于它就让人来点一下 —— 匹配错了比"多问一句"烦人得多。
自动阈值 = 82.0
#: 默认"领先第二名多少分才算稳"
差距阈值 = 12.0

#: 发布/压制/字幕组标签里常见的噪音词（**按整词丢**，不做子串替换：
#: 子串替换会把 "bd" 从 "bdrip" 里切出来，也会把中文片名里的字误删）
噪音词 = frozenset((
    "1080p", "720p", "2160p", "480p", "4k", "8k", "hd", "fhd", "uhd",
    "x264", "x265", "h264", "h265", "avc", "hevc", "vp9", "av1",
    "aac", "flac", "ac3", "eac3", "dts", "dtshd", "truehd", "opus", "mp3",
    "web", "webdl", "webrip", "web-dl", "bluray", "blu-ray", "bdrip", "brrip",
    "bd", "dvdrip", "hdtv", "remux", "hdrip", "tvrip", "hdr", "sdr", "dovi",
    "10bit", "8bit", "hi10p", "yuv420p", "mkv", "mp4", "avi", "rmvb", "flv",
    "chs", "cht", "jpsc", "gb", "big5", "sc", "tc", "简", "繁", "简体", "繁体",
    "简繁", "简日", "繁日", "双语", "中日双语", "中字", "内嵌", "外挂", "字幕",
    "字幕组", "压制", "招募", "合集", "全集", "完结", "首发", "高清", "修复版",
    "v2", "v3", "repack", "proper", "final", "ver", "sample", "sp", "ova", "oad",
))

#: 中文数字
_中文数表 = {"零": 0, "〇": 0, "一": 1, "两": 2, "二": 2, "三": 3, "四": 4,
           "五": 5, "六": 6, "七": 7, "八": 8, "九": 9}
#: "第一季/第2期/第3部" 里的序号（中文数字要有"季期部章话集篇幕"跟着才算）
_中文序号模式 = re.compile(r"([零〇一二两三四五六七八九十百]+)\s*(?=[季期部章话集篇幕])")
_阿拉伯数字模式 = re.compile(r"\d+")
#: 从标题里抠季号：第2季 / 第二季 / Season 2 / S02
_季号模式 = re.compile(r"第\s*(\d+|[零〇一二两三四五六七八九十百]+)\s*[季期部]"
                    r"|season\s*(\d+)|(?<![a-z0-9])s(\d{1,2})(?![a-z0-9])",
                    re.I)
#: 切词：连续的汉字算一个词，连续的字母数字算一个词
_切词模式 = re.compile(r"[\u3400-\u9fff]+|[a-z0-9]+")
#: 归一化时当分隔符的字符（括号、各种连接符、标点、装饰性符号）
_分隔模式 = re.compile(r"[\[\](){}<>（）【】《》「」『』〈〉]|"
                    r"[._\-–—+~!@#$%^&*=,;:'\"|/\\?！？。，、；：…·★☆※〓●○◎◇◆■□▲△]+")
#: 归一化时直接丢掉的字符（空白留着当分隔）
_空白模式 = re.compile(r"\s+")
#: 归一化时按"形状"丢的噪音词（分辨率、放送月份、版本号…）
#: 它们会被 :func:`数字们` 当成"年份/季数"抽出来，从而错误地触发数字惩罚
噪音形状 = (
    re.compile(r"^\d{3,4}[x*×]\d{3,4}$"),      # 1280x720 / 1920*1080
    re.compile(r"^\d{1,2}月(新番|番|番组)?$"),   # 4月新番
    re.compile(r"^\d{3,4}[pi]$"),              # 1080p / 1080i
    re.compile(r"^v\d+$"),                     # v2 / v3（压制版本号）
)
#: 认这些后缀是"文件扩展名"（归一化时去掉；不用 Path.stem：标题里也可能有点）
_后缀模式 = re.compile(r"\.(mkv|mp4|avi|rmvb|flv|mov|webm|ts|m2ts|wmv|mpg|mpeg|"
                    r"xml|json|ass|ssa|srt|txt)$", re.I)


