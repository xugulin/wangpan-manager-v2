def _打分与理由(候选: 匹配结果, 素材: 素材信息) -> tuple[float, str]:
    名字 = 素材.无扩展名 or 素材.文件名
    按名字 = 文件名相似度(名字, 候选.标题) if (名字 and 候选.标题) else 0.0
    # 素材.标题 是"已知的作品名"（界面/命名解析给的），比原始文件名干净，取两者较大值
    按标题 = 文件名相似度(素材.标题, 候选.标题) if (素材.标题 and 候选.标题) else 0.0
    基准 = max(按名字, 按标题)
    片段 = [f"名字相似 {基准:.1f}"]
    if 按标题 > 按名字 + 0.5:
        片段.append("按已知作品名比对")
    调整 = 0.0

    素材集 = 素材.集号
    候选集 = 取整数(候选.集号)
    if 素材集 is not None and 候选集 is not None:
        if int(素材集) == 候选集:
            调整 += 5.0
            片段.append(f"集号一致（{候选集}）+5")
        else:
            调整 -= 12.0
            片段.append(f"集号不一致（{素材集}≠{候选集}）-12")
    素材季 = 素材.季号
    候选季 = 从标题取季号(候选.标题)
    if 素材季 is not None and 候选季 is not None and int(素材季) != 候选季:
        调整 -= 10.0
        片段.append(f"季号不一致（{素材季}≠{候选季}）-10")
    if 候选.偏移秒:
        片段.append(f"源建议偏移 {候选.偏移秒:+.1f}s")
    return round(min(100.0, max(0.0, 基准 + 调整)), 1), "｜".join(片段)


def 打分(候选: 匹配结果, 素材: 素材信息) -> float:
    """给一个候选打 0-100 分（越高越像）。

    名字相似度（取"文件名 vs 作品名"和"已知作品名 vs 作品名"里大的那个）打底，
    集号一致 +5 / 不一致 -12，季号不一致 -10，最后夹到 [0, 100]。
    """
    return _打分与理由(候选, 素材)[0]


def 排序候选(候选们: Iterable[匹配结果], 素材: 素材信息) -> list[匹配结果]:
    """按分数降序排序，并把 :attr:`分数` / :attr:`理由` 填好（返回**新**对象）。

    同分时保持源给的顺序（稳定排序）—— 源给的顺序本身就有意义（弹弹play 的
    hashAndFileName 命中通常排在第一个）。
    """
    算过 = []
    for 序, 候 in enumerate(候选们 or []):
        分, 理由 = _打分与理由(候, 素材)
        算过.append((分, 序, replace(候, 分数=分, 理由=理由, 原始=dict(候.原始 or {}))))
    算过.sort(key=lambda 项: (-项[0], 项[1]))
    return [项[2] for 项 in 算过]


