def 规范化名字(名字) -> str:
    """把文件名/标题洗成"可比"的形式：小写、去扩展名、括号与连接符换成空格、
    丢掉发布标签噪音词、**把中文序号统一成阿拉伯数字**。

    为什么噪音词按**整词**丢而不是子串替换：``bd`` 是 ``bdrip`` 的子串、``sc`` 是
    ``school`` 的子串，子串替换会把正常片名切出洞来。整词丢最多漏掉几个标签，
    不会误伤。

    为什么要把 ``第二季`` 写成 ``第2季``：同一个东西两种写法到处都是
    （``第2季``/``第二季``/``Season 2``），不统一的话"明明是同一条"却只拿到五十几分。
    只在"数字后面紧跟 季/期/部/章/话/集/篇/幕"时替换 —— ``一人之下`` 的"一"、
    ``十二国记`` 的"十二"不会被碰。
    """
    文本 = str(名字 or "").strip()
    文本 = _后缀模式.sub("", 文本)
    文本 = 文本.lower()
    文本 = _中文序号模式.sub(lambda 匹配: _中文序号替(匹配.group(1)), 文本)
    文本 = _分隔模式.sub(" ", 文本)
    文本 = _空白模式.sub(" ", 文本)
    词 = []
    for 一个 in 文本.split(" "):
        if not 一个 or 一个 in 噪音词:
            continue
        if any(形状.match(一个) for 形状 in 噪音形状):
            continue
        词.append(一个)
    return " ".join(词).strip()


def _中文序号替(段: str) -> str:
    值 = 中文数字(段)
    return str(值) if 值 is not None else 段


def 词元们(文本: str) -> set[str]:
    """切词：连续汉字一个词、连续字母数字一个词（中文没有空格，只能这么切）。"""
    return {一个 for 一个 in _切词模式.findall(规范化名字(文本)) if 一个}


def 中文数字(文本: str) -> Optional[int]:
    """``一``→1、``十``→10、``十二``→12、``二十``→20、``二十三``→23。"""
    文本 = str(文本 or "").strip()
    if not 文本:
        return None
    if 文本 == "十":
        return 10
    if 文本.startswith("十"):
        余 = 文本[1:]
        return 10 + _中文数表.get(余, 0) if (not 余 or 余 in _中文数表) else None
    if "十" in 文本:
        前, _, 后 = 文本.partition("十")
        if 前 not in _中文数表 or (后 and 后 not in _中文数表):
            return None
        return _中文数表[前] * 10 + (_中文数表[后] if 后 else 0)
    if all(字 in _中文数表 for 字 in 文本):
        数 = 0
        for 字 in 文本:
            数 = 数 * 10 + _中文数表[字]
        return 数
    return None


def 数字们(文本: str) -> set[int]:
    """抽出一段文本里的"序号类数字"：阿拉伯数字 + 带季/期/部/话/集的中文数字。

    只认跟着"季期部章话集篇幕"的中文数字（``第一季`` → 1），因为"一"这种字在中文
    片名里到处都是（``一人之下``），无脑抽会把分数搞得一团糟。
    """
    数: set[int] = set()
    for 段 in _阿拉伯数字模式.findall(str(文本 or "")):
        try:
            数.add(int(段))
        except ValueError:
            continue
    for 段 in _中文序号模式.findall(str(文本 or "")):
        值 = 中文数字(段)
        if 值 is not None:
            数.add(值)
    return 数


def 从标题取季号(文本: str) -> Optional[int]:
    """从标题里抠季号：``第2季`` / ``第二季`` / ``Season 2`` / ``S02``；抠不到 None。"""
    for 甲, 乙, 丙 in _季号模式.findall(str(文本 or "")):
        if 甲:
            值 = int(甲) if 甲.isdigit() else 中文数字(甲)
            if 值 is not None:
                return 值
        elif 乙:
            return int(乙)
        elif 丙:
            return int(丙)
    return None


def 最长公共子序列长度(甲: str, 乙: str) -> int:
    """经典 LCS（字符级，DP + 滚动数组）。名字都很短，O(n·m) 足够。"""
    if not 甲 or not 乙:
        return 0
    上一行 = [0] * (len(乙) + 1)
    for 甲字 in 甲:
        本行 = [0] * (len(乙) + 1)
        for 序, 乙字 in enumerate(乙, start=1):
            if 甲字 == 乙字:
                本行[序] = 上一行[序 - 1] + 1
            else:
                本行[序] = max(上一行[序], 本行[序 - 1])
        上一行 = 本行
    return 上一行[-1]


def 最长公共子串长度(甲: str, 乙: str) -> int:
    """最长**连续**公共子串（同样是 DP + 滚动数组）。"""
    if not 甲 or not 乙:
        return 0
    if len(甲) > len(乙):
        甲, 乙 = 乙, 甲
    上一行 = [0] * (len(甲) + 1)
    最长 = 0
    for 乙字 in 乙:
        本行 = [0] * (len(甲) + 1)
        for 序, 甲字 in enumerate(甲, start=1):
            if 甲字 == 乙字:
                本行[序] = 上一行[序 - 1] + 1
                if 本行[序] > 最长:
                    最长 = 本行[序]
        上一行 = 本行
    return 最长


def _二元组们(文本: str) -> set[str]:
    return {文本[i:i + 2] for i in range(len(文本) - 1)} if len(文本) >= 2 else set()


def _dice(甲: set, 乙: set) -> float:
    并 = len(甲) + len(乙)
    return (2.0 * len(甲 & 乙) / 并) if 并 else 0.0


def _数字惩罚(左: str, 右: str) -> float:
    """数字不一致时的惩罚系数。

    * 只有一边有数字（多一个"第01话"之类的信息）→ 0.90，**轻微**；
    * 两边都是四位年份、且相差 ≤ 1 年 → 0.88（同年不同版本/跨年番很常见）；
    * 其它（季数、集号不同）→ 0.70，**要能区分开**。
    """
    甲数, 乙数 = 数字们(左), 数字们(右)
    if 甲数 == 乙数:
        return 1.0
    if not 甲数 or not 乙数:
        return 0.90
    if (len(甲数) == len(乙数)
            and all(1000 <= 数 <= 2999 for 数 in 甲数 | 乙数)
            and all(abs(甲 - 乙) <= 1 for 甲, 乙 in zip(sorted(甲数), sorted(乙数)))):
        return 0.88
    return 0.70


def 文件名相似度(甲, 乙) -> float:
    """两个名字的相似度，0-100（**对称**，自己实现）。

    完全一样（归一化后）100；一方完整出现在另一方里时至少给
    ``68 + 32×长度比``（发布组标签再长也不能把正确的候选压到及格线下）；
    其余按二元组/子序列/子串/词元四路加权，最后乘数字一致性惩罚。
    """
    左, 右 = 规范化名字(甲), 规范化名字(乙)
    if not 左 or not 右:
        return 0.0
    if 左 == 右:
        return 100.0
    串比 = 最长公共子串长度(左, 右) / min(len(左), len(右))
    序比 = 最长公共子序列长度(左, 右) / max(len(左), len(右))
    二元 = _dice(_二元组们(左), _二元组们(右))
    词比 = _dice(词元们(左), 词元们(右))
    分数 = 0.40 * 二元 + 0.30 * 序比 + 0.30 * 词比
    if 串比 >= 0.99:                     # 短的那个完整出现在长的里面
        长度比 = min(len(左), len(右)) / max(len(左), len(右))
        分数 = max(分数, 0.68 + 0.32 * 长度比)
    return round(100.0 * min(1.0, 分数) * _数字惩罚(左, 右), 1)


