"""候选匹配与自动决策：把"这个文件是哪个节目"变成**可解释的分数**。

思路（自己实现，不搬任何项目的代码）
====================================

1. **归一化优先**：真实文件名里塞满了发布组标签（``[VCB-Studio]``、``1080p``、
   ``x265``、``CHS``…）。不先洗掉它们，任何字符串相似度都会被稀释到没意义。
2. **多路信号加权**（纯字符串相似度对中/日文短标题很不稳）：
   * 二元组 Dice —— 对"少一个字"很敏感，且不要求分词正确；
   * 最长公共子序列比 —— 抓住"顺序一致但中间有插入"的情况；
   * 最长公共子串比 —— 抓住"一方完整出现在另一方里"（文件名里带一堆标签时最有用）；
   * 词元 Dice —— 抓住整体词序被打乱的情况。
3. **数字一致性单独惩罚**：年份/季数/集号是"同名不同条目"的唯一区别，光靠字符相似度
   区分不开（``进击的巨人 2013`` vs ``2014`` 字符相似度高达 9 成）。所以把
   **阿拉伯数字**与**中文数字+季/期/部/话/集**都抽出来比：不同就乘一个惩罚系数。
4. **分数要能解释**：每个候选都带 :attr:`~wangpan.danmaku.源.接口.匹配结果.理由`，
   界面直接显示"为什么给它 92 分"，用户才敢点"自动匹配"。

自动决策的语义（**阈值是给"拿不准"留的余地**）
==============================================
最高分 ≥ ``自动阈值``（默认 82）**且** 比第二名高出 ``差距阈值``（默认 12）才自动采纳，
否则 ``需要人工确认=True``。唯一候选时视为"没有竞争"，只看绝对分。
"""

