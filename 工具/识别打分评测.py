#!/usr/bin/env python3
"""P3 打分评测：跑"② 结构 → ③ 候选 → ④ 检索 → ⑤ 打分 → ⑥ 决策"整条链，出真实指标。

为什么要有这个脚本（不是"又一个 demo"）
======================================
``docs/识别/00_架构.md`` 第二节把 P3 的验收写成两个数字：**Top-1 ≥ 95%**、
**自动入库精确率 ≥ 99%**。这两个数字都**只能**用真 TMDB 跑出来：

* 单测（``tests/test_识别打分.py`` / ``test_识别决策.py``）证明的是"规则自洽"，
  用的是构造数据 —— 它没法告诉你真机上《仙逆》的候选表里到底有几条干扰、
  《黑镜》的季集划分和文件名差多少、票数 44 的长播剧会不会被热门错项压死；
* P2 的 ``工具/识别真网探测.py`` 只打到"候选表"为止，不告诉你**选了哪条**、
  选得对不对、敢不敢自动入库。

所以这个脚本是 P3 的尺子：它把标注集的 ``tmdb_id`` 当唯一权威，逐条跑完整条链，
输出 Top-1 准确率 / 自动入库精确率 / 自动入库覆盖率 / 待确认率 + 失败样例清单。

指标口径（读数字前先看）
======================
* **只算已标注样本**：``数据/识别标注.jsonl`` 里 ``tmdb_id`` 为 ``null`` 的样本
  （占位符"某剧"/"某番"、以及"1984"这种三项对不上的）**无法判定** Top-1 与精确率，
  一律排除在分母之外，另在报告里单列"未标注样本的档位分布"。
  把它们混进分母才是真的在骗自己。
* **Top-1 准确率** = 首选候选的 tmdb id == 标注 id（不看标题文本，id 才是身份）。
* **自动入库精确率** = 自动档里**正确**的条数 / 自动档条数。门槛 99%，**这是硬线**：
  分母为 0 时报告写"样本不足"，不写 100%（0/0 不是满分）。
* **自动入库覆盖率** = 自动档条数 / 已标注条数；另给"自动且正确"的口径，
  因为"自动了很多但一半是错的"在只看覆盖率时会很好看。
* **待确认率** = 待确认条数 / 已标注条数。
* **候选召回率**（诊断用）= 标注 id 出现在候选表里的比例。它把"P2 没搜到"与
  "P3 排错了"分开：召回率低是 P2 的病，Top-1 低于召回率才是 P3 的病。

季集范围是怎么来的（成本说明）
============================
⑤ 打分的"(季,集) 范围校验"需要候选作品的**季数与集数**，而 TMDB 的搜索接口不返回它。
本脚本的做法：先做一次**预打分**（不带季集信息），取分数够看的**前 N 条**（``--富化上限``，
默认 3）去调 ``取剧集`` 详情，补上 ``季集范围`` 后再正式打分一次。
* 为什么不给所有候选都取详情：91 条样本 × 每条十几条候选 = 上千次请求，既慢又挨限流，
  而排在后面的候选本来就不可能胜出；
* 为什么两趟而不是一趟：范围信息会改变排序（这正是它的作用），所以只能"先排一遍、
  再拿头部的详情重排"；
* TMDB 客户端自带 7 天磁盘缓存（``wangpan/scrape/tmdb.py``），本脚本再叠一层进程内缓存，
  同一个 id 在 91 条样本里只取一次详情（真机是"同一部剧几十集"，这个收益很大）。
* ``--不富化`` 关掉这一层：用来回答"没有季集信号会掉多少"。

**"TMDB 认识的所有名字"也要取回来**（``alternative_titles`` + ``translations``）
================================================================================
真机的英文/罗马音文件名（``Renegade.Immortal.S01E138``、``Sousou no Frieren``、
``Mushoku Tensei``）与 TMDB 的当前语言标题（``仙逆``、``葬送的芙莉莲``、``无职转生``）
**没有任何共同字符**，光比字符串永远得 0 分 —— 而 TMDB 的搜索之所以能把这些文件名的
查询词匹配到正确的条目，靠的正是它内部记着的那一堆名字。

**两个接口都要**（实测踩过）：
* ``/alternative_titles``：``Xian Ni``、``Immortal Reversal``、``Tiên Nghịch`` …；
* ``/translations``：**``Renegade Immortal`` 只在这里**（en 译名）。

只取 ``alternative_titles`` 时，真机样本 ``Renegade.Immortal.S01E138…`` 只能匹配到
``Immortal Reversal``（0.50 分）→ 卡在待确认；补上 ``translations`` 才拿到 1.00。
把候选的这些名字喂给 ⑤ 打分（``打分.标题相似度`` 本来就认候选的 ``别名`` 字段），
"罗马音/英文写法"这条就通了，而且**不是为个案写死**：任何作品、任何语言的名字都走同一条路。
代价是每个候选多两次请求（同样吃 7 天磁盘缓存）。

P5 起这条路已经补成**公开接口**：``TMDB客户端.取别名们(类型, id)`` 把
``alternative_titles`` 与 ``translations`` 两个接口包在一处（``identify.详情`` 负责调用）。
假客户端没有它就退回带缓存的私有 ``_取一份``，两个都拿不到就当没有别名（软失败）。

连通性自检必须绕开 7 天缓存
========================
``TMDB客户端`` 默认有 7 天磁盘缓存，**断网也会"秒返回成功"**（第一次写真网探测时踩过）。
所以这里用 ``dataclasses.replace(配置, 缓存TTL秒=0)`` 的副本真发一次请求，
连不上就直接说清楚（凭据怎么配、代理怎么设），而不是让人看 30 行报错。

跑法
====
::

    运行环境/venv/bin/python 工具/识别打分评测.py
    运行环境/venv/bin/python 工具/识别打分评测.py --限制 10        # 只跑前 10 条（调试）
    运行环境/venv/bin/python 工具/识别打分评测.py --不富化          # 不吃季集/别名详情
    运行环境/venv/bin/python 工具/识别打分评测.py --json 数据/识别打分评测.json

退出码
======
* ``0``：跑完了（**有失败样例也返回 0**：这是尺子，不是 CI 测试）；
* ``1``：命令行用法错；
* ``2``：TMDB 凭据没配（不猜、不硬编）；
* ``3``：连不上 TMDB（除非 ``--允许离线``，那时只吃落盘缓存）；
* ``4``：标注集读不动 / 字段不合法（尺子本身坏了，这时指标一个都不可信）。
"""

