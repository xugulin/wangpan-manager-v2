def _取参数() -> argparse.Namespace:
    解析 = argparse.ArgumentParser(
        description="P3 打分评测：真 TMDB 跑 ② 结构 → ③ 候选 → ④ 检索 → ⑤ 打分 → ⑥ 决策",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    解析.add_argument("--标注", default=str(默认标注集), help="标注集 JSONL（默认 数据/识别标注.jsonl）")
    解析.add_argument("--报告", default=str(默认报告), help="报告落点（默认 数据/识别打分评测.md）")
    解析.add_argument("--限制", type=int, default=0, help="只跑前 N 条（调试用，0 = 全跑）")
    解析.add_argument("--不落盘", action="store_true", help="不用/不写 数据/识别检索缓存.json")
    解析.add_argument("--不富化", action="store_true",
                    help="不取 TMDB 详情补季集范围（用来回答「没有季集信号会掉多少」）")
    解析.add_argument("--富化上限", type=int, default=3,
                    help="每条样本取前 N 条候选的季集/别名详情（默认 3）")
    解析.add_argument("--json", default="", metavar="路径", help="把逐条原始结果也写一份 JSON")
    解析.add_argument("--不取别名", action="store_true",
                    help="不取 TMDB alternative_titles（英文/罗马音文件名会因此拿不到标题分）")
    解析.add_argument("--允许离线", action="store_true", help="连不上也继续（只吃落盘缓存）")
    解析.add_argument("--安静", action="store_true", help="不打印每条样本的进度")
    解析.add_argument("--自动分", type=float, default=None,
                    help="覆盖自动档的绝对分门槛（默认 95；只做敏感性分析用）")
    解析.add_argument("--自动间距", type=float, default=None,
                    help="覆盖自动档的 margin 门槛（默认 25；只做敏感性分析用）")
    解析.add_argument("--丢弃分", type=float, default=None,
                    help="覆盖丢弃门槛（默认 30；只做敏感性分析用）")
    return 解析.parse_args()


def _取门槛(参数) -> 门槛:
    """把 CLI 的覆盖项套到默认门槛上（只改用户显式给的字段）。"""
    改动 = {}
    for 名字, 值 in (("自动分", 参数.自动分), ("自动间距", 参数.自动间距),
                   ("丢弃分", 参数.丢弃分)):
        if 值 is not None:
            改动[名字] = 值
    return dataclasses.replace(默认门槛, **改动) if 改动 else 默认门槛


def main() -> int:
    参数 = _取参数()
    门槛 = _取门槛(参数)
    标注路径 = Path(参数.标注)
    if not 标注路径.is_absolute():
        标注路径 = 项目根 / 标注路径
    报告路径 = Path(参数.报告)
    if not 报告路径.is_absolute():
        报告路径 = 项目根 / 报告路径

    try:
        样本们 = P1评测.读标注(标注路径)
    except P1评测.评测错误 as 错:
        print(f"❌ 标注集读不动（尺子本身坏了，指标一个都不可信）：\n{错}")
        return 4
    if 参数.限制:
        样本们 = 样本们[:参数.限制]

    # ---- 凭据 ----
    try:
        from wangpan.scrape.tmdb import TMDB客户端, TMDB配置, 请求失败
    except Exception as 异常:                                            # noqa: BLE001
        print(f"❌ 导不进 TMDB 客户端：{type(异常).__name__}: {异常}")
        return 2
    配置 = TMDB配置.从环境与配置()
    if not 配置.可用():
        print("❌ 没配 TMDB 凭据（token / apiKey）：写进 数据/刮削.json 的 tmdb 节点，"
              "或设环境变量 V2_TMDB_TOKEN / V2_TMDB_API_KEY。")
        print("   （这一步只读配置，不会打印密钥本身）")
        return 2
    客户端 = TMDB客户端(配置)
    print("TMDB 配置：" + json.dumps(客户端.配置摘要(), ensure_ascii=False))
    print(f"标注集：{标注路径}（{len(样本们)} 条）")
    print(f"门槛：{门槛.摘要()}"
          f"{'（CLI 覆盖）' if 门槛 != 默认门槛 else ''}"
          f"｜理论满分（不含学习库）{满分不含学习库:.0f} 分")

    # ---- 连通性自检：必须绕开客户端自己的 7 天磁盘缓存（断网也会「秒成功」）----
    离线 = bool(参数.允许离线)
    探针 = TMDB客户端(dataclasses.replace(配置, 缓存TTL秒=0))
    try:
        探针.搜电影("沙丘", 2021)
        print("连通性自检：✅ 真发了一次请求（已绕开 7 天磁盘缓存）")
    except 请求失败 as 错:
        print("❌ 连不上 TMDB（或凭据不对）。原样原因如下：\n   " + str(错))
        print("   本机实测直连到不了 api.themoviedb.org，要走代理："
              "数据/刮削.json 的 tmdb.proxy（例如 socks5://127.0.0.1:10808）"
              "或环境变量 V2_TMDB_PROXY。")
        print("   自检：运行环境/venv/bin/python 工具/检查刮削凭据.py")
        if not 离线:
            探针.关闭()
            客户端.关闭()
            return 3
        print("   （--允许离线：继续跑，但只能吃落盘缓存里的旧结果）")
    finally:
        探针.关闭()

    缓存路径 = None if 参数.不落盘 else 默认落盘缓存路径()
    缓存 = 检索缓存(落盘=缓存路径)
    详情 = 候选详情(客户端, 上限=0 if 参数.不富化 else 参数.富化上限,
                 取别名=not 参数.不取别名)

    起点 = time.time()
    结果们: list[dict] = []
    for 序号, 条 in enumerate(样本们, start=1):
        try:
            项 = 跑一条(条, 客户端, 缓存, 详情, 富化=not 参数.不富化,
                      门槛=门槛)
        except Exception as 异常:                                        # noqa: BLE001
            # 一条样本炸了不许毁掉整轮评测：记成"崩溃"并继续（否则指标不可信）。
            项 = {"样本": 条["样本"], "父目录": 条["父目录"], "期望": 条["期望"],
                "结构": {}, "查询词们": [], "候选数": 0, "检索汇总": "",
                "错误们": [f"评测崩溃：{type(异常).__name__}: {异常}"],
                "观察标题们": [], "已富化": [], "首选标识": "", "首选标题": "",
                "首选类型": "", "首选年份": None, "分数": 0.0, "间距": 0.0,
                "信号们": [], "档位": 档_丢弃, "原因": f"评测崩溃：{异常}",
                "关键信号": [], "期望标识": "", "期望在候选里": False,
                "期望排第几": 0, "Top1对": False, "错误": True}
        结果们.append(项)
        if not 参数.安静:
            标 = "✅" if 项["Top1对"] else ("❌" if 项["期望标识"] else "？")
            print(f"  [{序号:>3}/{len(样本们)}] {标} {条['样本'][:42]:44}"
                  f"{项['档位']}　{项['分数']:6.1f} 分　间距 {项['间距']:5.1f}"
                  f"　{项['首选标题'][:16]}", flush=True)
    用时 = time.time() - 起点
    客户端.关闭()

    汇总 = 算指标(结果们)
    # 写 JSON 前摘掉只在内存里用的重算对象（它不是 JSON 可序列化的，也不该落盘）
    纯结果们 = [{键: 值 for 键, 值 in x.items() if 键 != "_重算"} for x in 结果们]
    报告 = 生成报告(结果们, 汇总, 标注路径, 用时, 富化=not 参数.不富化,
                 富化上限=参数.富化上限, 详情=详情, 缓存=缓存, 离线=离线,
                 门槛=门槛)
    报告路径.parent.mkdir(parents=True, exist_ok=True)
    报告路径.write_text(报告, encoding="utf-8")
    打印摘要(结果们, 汇总, 报告路径, 门槛)

    if 参数.json:
        落点 = Path(参数.json)
        if not 落点.is_absolute():
            落点 = 项目根 / 落点
        落点.parent.mkdir(parents=True, exist_ok=True)
        落点.write_text(json.dumps({"汇总": 汇总, "逐条": 纯结果们},
                                  ensure_ascii=False, indent=1, default=str),
                      encoding="utf-8")
        print(f"（逐条原始结果已写入 {落点}）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
