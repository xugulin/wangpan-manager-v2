# ============================ 一条样本的完整链 ============================


def 跑一条(条: dict, 客户端, 缓存: 检索缓存, 详情: 候选详情, *,
          富化: bool = True, 门槛=None) -> dict:
    """一条标注样本 → 整条链的结果（结构/查询/候选/分数/决策，全部留档）。

    P5 起链本身（``结构 → 候选 → 检索 → 打分 → 决策``）由 ``identify.管线.全链``
    提供 —— 与 ``wangpan/scrape/服务.py`` 是**同一份代码**。这个函数只负责"把链的
    产物摊成报告要的字段"，不再自己拼链（拼两份就迟早有一份先改，指标就成了别人的指标）。
    """
    门槛 = 门槛 or 默认门槛
    名字, 父 = P1评测.拆样本(条["样本"], 条["父目录"])
    链 = 全链(条["样本"], 客户端, 父目录名=父, 缓存=缓存,
             详情=详情, 富化=富化, 门槛=门槛)
    结构, 查询集, 检索结果, 最终, 判定 = (链.结构, 链.查询集, 链.检索结果,
                                  链.打分结果, 链.决策结果)
    范围表 = 链.范围表

    期望 = 条["期望"]
    期望标识 = str(期望["tmdb_id"]) if 期望.get("tmdb_id") is not None else ""
    候选标识们 = [str(x.标识) for x in 检索结果.候选们]
    首选 = 最终.首选()
    命中排序 = 0
    for 序号, 项 in enumerate(最终.分数们, start=1):
        if 期望标识 and 项.标识 == 期望标识:
            命中排序 = 序号
            break

    return {
        "样本": 条["样本"], "父目录": 条["父目录"], "期望": 期望,
        "结构": {"标题": 结构.标题, "年份": 结构.年份, "类型": 结构.类型,
               "季": 结构.季, "集": 结构.集, "一句话": 结构.一句话()},
        "查询词们": [(x.文本, x.来源, round(x.权重, 1)) for x in 查询集.查询词们],
        "候选数": len(检索结果.候选们),
        "检索汇总": 检索结果.汇总(),
        "错误们": [x.可读() for x in 检索结果.错误们],
        "观察标题们": 最终.观察标题们,
        "已富化": sorted(范围表),
        "首选标识": 首选.标识 if 首选 else "",
        "首选标题": 首选.标题 if 首选 else "",
        "首选类型": 首选.类型 if 首选 else "",
        "首选年份": getattr(首选.候选, "年份", None) if 首选 else None,
        "分数": 首选.总分 if 首选 else 0.0,
        "间距": 最终.间距(),
        "信号们": [(x.名字, round(x.得分, 1), x.说明) for x in (首选.信号们 if 首选 else [])],
        "档位": 判定.档位,
        "原因": 判定.原因,
        "关键信号": 判定.关键信号,
        "期望标识": 期望标识,
        "期望在候选里": bool(期望标识) and 期望标识 in 候选标识们,
        "期望排第几": 命中排序,
        "Top1对": bool(期望标识) and 首选 is not None and 首选.标识 == 期望标识,
        "错误": bool(检索结果.错误们),
        # 下面这个键**只在内存里用**（写 JSON 前会摘掉）：敏感性分析要拿它重跑 ⑥ 决策，
        # 这样"换个门槛会怎样"就是零成本的（不用再打一次接口）。
        "_重算": (结构, 最终),
    }


# ============================ 指标 ============================


def 算指标(结果们: list[dict]) -> dict:
    """按模块文档字符串的口径算指标。**只算已标注样本**（未标注的另列）。"""
    已标 = [x for x in 结果们 if x["期望标识"]]
    自动 = [x for x in 已标 if x["档位"] == 档_自动]
    正确 = [x for x in 已标 if x["Top1对"]]
    自动正确 = [x for x in 自动 if x["Top1对"]]
    汇总 = {
        "总数": len(结果们),
        "已标注": len(已标),
        "未标注": len(结果们) - len(已标),
        "召回命中": sum(1 for x in 已标 if x["期望在候选里"]),
        "Top1命中": len(正确),
        "自动数": len(自动),
        "自动正确数": len(自动正确),
        "待确认数": sum(1 for x in 已标 if x["档位"] == 档_待确认),
        "丢弃数": sum(1 for x in 已标 if x["档位"] == 档_丢弃),
        "自动里未标注数": sum(1 for x in 结果们 if not x["期望标识"] and x["档位"] == 档_自动),
        "未标注档位": {档: sum(1 for x in 结果们
                           if not x["期望标识"] and x["档位"] == 档)
                   for 档 in (档_自动, 档_待确认, 档_丢弃)},
        "错误样本数": sum(1 for x in 结果们 if x["错误"]),
    }

    def 率(分子: int, 分母: int) -> float | None:
         return (分子 / 分母) if 分母 else None

    汇总["候选召回率"] = 率(汇总["召回命中"], 汇总["已标注"])
    汇总["Top1准确率"] = 率(汇总["Top1命中"], 汇总["已标注"])
    汇总["自动入库精确率"] = 率(汇总["自动正确数"], 汇总["自动数"])
    汇总["自动入库覆盖率"] = 率(汇总["自动数"], 汇总["已标注"])
    汇总["自动且正确覆盖率"] = 率(汇总["自动正确数"], 汇总["已标注"])
    汇总["待确认率"] = 率(汇总["待确认数"], 汇总["已标注"])
    汇总["丢弃率"] = 率(汇总["丢弃数"], 汇总["已标注"])
    return 汇总


