def 敏感性(结果们: list[dict], 基准门槛) -> list[dict]:
    """拿**已经算好的分数对象**重跑 ⑥ 决策，看"门槛松/紧"对精确率与覆盖率的影响。

    为什么值得单列一节：P3 的验收里"自动入库精确率 ≥99%"是硬线，而覆盖率是**取舍**。
    把取舍摊开给用户看（"松到 90 分能多入库 7 条、精确率还是 100%"），比只报一个
    默认门槛下的数字更有用 —— 调门槛的人不用自己改代码重跑整条链。
    """
    行们 = []
    for 名字, 覆盖 in 敏感组合们:
        试门槛 = dataclasses.replace(基准门槛, **覆盖) if 覆盖 else 基准门槛
        自动 = 自动对 = 已标 = Top1 = 0
        for 项 in 结果们:
            重算 = 项.get("_重算")
            if 重算 is None:
                continue
            结构, 分数结果 = 重算
            判定 = 决策(结构, 分数结果, 门槛=试门槛)
            if not 项["期望标识"]:
                continue
            已标 += 1
            Top1 += 1 if 项["Top1对"] else 0
            if 判定.档位 == 档_自动:
                自动 += 1
                自动对 += 1 if 项["Top1对"] else 0
        行们.append({"名字": 名字, "门槛": 试门槛, "已标注": 已标, "自动": 自动,
                   "自动对": 自动对, "Top1": Top1})
    return 行们


def _百分比(值: float | None, 分母说明: str = "") -> str:
    if 值 is None:
        return f"—（分母为 0{('：' + 分母说明) if 分母说明 else ''}）"
    return f"{值 * 100:.1f}%"


def _达标(值: float | None, 门槛: float) -> str:
    if 值 is None:
        return "样本不足"
    return "✅" if 值 >= 门槛 else "❌"


