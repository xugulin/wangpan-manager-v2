#!/usr/bin/env python3
"""P5 端到端**真机**复验：光鸭真目录 → 识别 → 落库（**临时库**），跑两轮。

为什么非要真机（而不是再写一个单测）
==================================
架构文档第六节第 5 条：「这套东西最终要在**这台电脑上、用真实网盘目录**跑通才算完成」。
单测里的假 TMDB 只能证明"接口串起来了"，证明不了：

* 光鸭真适配器列出来的 16 个文件（``146.SDR.8bit…mp4`` / ``Renegade.Immortal.S01E138…``）
  真的能被结构层认出来（集号 131~146、标题只能从目录名 ``仙逆.4K高码.SDR.60fps`` 兜底）；
* 真 TMDB 上「仙逆」确实能搜到、且敢自动入库（不靠个案写死）；
* 一部 16 集的剧落库后是**一张海报 + 16 个集都挂上文件**（不是 16 张卡，也不是只挂第一集）。

它验的是什么（按顺序）
====================
1. **列目录**：``wangpan.pan.光鸭.光鸭适配器.列出(目录)``（真网络、真令牌）；
2. **造单元 → 合并成一部剧**：``扫描.造远端单元`` → ``扫描.合并远端单元``
   （这一步的形状与界面里 ``媒体库页.扫描全部来源`` 完全一致）；
3. **走整条识别链**：每一集都调 ``identify.管线.全链``（**与 ``服务.py`` 同一份代码**），
   逐集打印"自动入库 / 待确认（为什么）/ 丢弃"；
4. **落库到临时库**：``刮削服务.记远端单元 + 续跑``，然后断言
   1 条媒体 / 标题=仙逆 / 类型=tv / 季=1 / **16 个集都挂上文件**；
5. **第二轮（学习命中）**：临时学习库里先写死「这个目录 → tv:223911」，
   重跑一遍 —— 应当**全部命中学习库直接自动入库**，并打印这一轮有多少集靠学习命中。

跑完**恢复现场**（这是硬要求）
============================
* 学习库：全程指向临时文件（``V2_识别学习库`` 环境变量），**用户的 ``数据/识别学习.json``
  一个字节都不会动**（跑完还会把环境变量还原）；
* 检索缓存：``数据/识别检索缓存.json`` 跑前备份、跑完还原（它是缓存，但"不许污染"更省心）；
* 资料库：落的是 ``tempfile`` 里的临时库；跑完连临时目录一起删掉。

跑法::

    运行环境/venv/bin/python 工具/识别端到端真机.py
    运行环境/venv/bin/python 工具/识别端到端真机.py --目录 /来自：分享/仙逆.4K高码.SDR.60fps

退出码
======
* ``0``：两轮都跑通且断言全过；
* ``1``：命令行用法错；``2``：TMDB 凭据没配 / 光鸭没登录；
* ``3``：连不上（TMDB 或光鸭）；
* ``5``：**断言失败**（识别结果不符合预期 —— 这时要去看上面打出来的逐集档位与原因）。
"""

