仙逆标识 = "223911"


# ============================ 小工具 ============================


def 打印(文本: str = "") -> None:
    print(文本, flush=True)


def 一集一行(序号: int, 总: int, 文件名: str, 链) -> None:
    """逐集打一行：档位 + 分数 + 为什么（待确认的原因要原样打出来，不许掩）。"""
    判定 = 链.决策结果
    首选 = 链.打分结果.首选()
    谁 = f"[{首选.类型}#{首选.标识}] {首选.标题}" if 首选 else "（没有候选）"
    打印(f"  [{序号:>2}/{总}] {文件名[:46]:48} {判定.档位:6} {判定.分数:6.1f} 分"
        f"　{谁}")
    打印(f"         结构：{链.结构.一句话()}")
    打印(f"         为什么：{判定.原因}")


def 学习命中(链) -> bool:
    """这一集是不是**靠学习库**定的（学习库信号非中性且系数 > 0）。"""
    首选 = 链.打分结果.首选()
    项 = 首选.取("学习库") if 首选 is not None else None
    return bool(项 is not None and not 项.中性 and 项.系数 > 0)


# ============================ 现场备份/恢复 ============================


class 现场保护:
    """跑完必须恢复的东西（检索缓存文件 + ``V2_识别学习库`` 环境变量）。"""

    def __init__(self, 临时根: Path) -> None:
        self.临时根 = Path(临时根)
        self.缓存文件 = 项目根 / "数据" / "识别检索缓存.json"
        self._缓存原样: bytes | None = None
        self._学习变量原样: str | None = None

    def 备份(self) -> None:
        self.临时根.mkdir(parents=True, exist_ok=True)
        if self.缓存文件.is_file():
            self._缓存原样 = self.缓存文件.read_bytes()
            (self.临时根 / "识别检索缓存.json.备份").write_bytes(self._缓存原样)
        self._学习变量原样 = os.environ.get("V2_识别学习库")
        # 学习库全程指向**临时文件**：服务层的"人工确认 → 写学习库"也落在临时文件里，
        # 用户那份 数据/识别学习.json 根本不会被读到、更不会被写。
        os.environ["V2_识别学习库"] = str(self.临时根 / "识别学习.json")

    def 恢复(self) -> None:
        if self._学习变量原样 is None:
            os.environ.pop("V2_识别学习库", None)
        else:
            os.environ["V2_识别学习库"] = self._学习变量原样
        try:
            if self._缓存原样 is None:
                self.缓存文件.unlink(missing_ok=True)
            else:
                self.缓存文件.write_bytes(self._缓存原样)
        except OSError as 错:                                                # noqa: BLE001
            打印(f"⚠️ 检索缓存恢复失败（请手工检查 {self.缓存文件}）：{错}")


# ============================ 主流程 ============================


def _取参数() -> argparse.Namespace:
    解析 = argparse.ArgumentParser(
        description="P5 端到端真机复验（光鸭真目录 → 识别 → 临时库 → 第二轮学习命中）",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    解析.add_argument("--目录", default=默认目录, help=f"光鸭里的目录（默认 {默认目录}）")
    解析.add_argument("--网盘", default=默认网盘, help="网盘标识（默认 guangya）")
    解析.add_argument("--下载图片", action="store_true",
                    help="也把海报/剧照下下来（默认关：146 集剧照要下很久，"
                         "本脚本关心的是识别与挂文件）")
    解析.add_argument("--保留现场", action="store_true", help="跑完不删临时目录（排查用）")
    return 解析.parse_args()


def main() -> int:
    参数 = _取参数()

    # ---- 0) 临时根 + 现场备份 ----
    临时根 = Path(tempfile.mkdtemp(prefix="v2识别真机_"))
    保护 = 现场保护(临时根)
    保护.备份()
    打印(f"临时目录：{临时根}（临时库、临时学习库都放这里；跑完删掉）")

    try:
        return _跑(参数, 临时根)
    except _断言失败 as 错:
        打印(f"\n❌ 断言失败：{错}")
        return 5
    finally:
        保护.恢复()
        if not 参数.保留现场:
            shutil.rmtree(临时根, ignore_errors=True)
            打印(f"（已清理临时目录 {临时根}；检索缓存/学习库已恢复原样）")
        else:
            打印(f"（--保留现场：临时目录留在 {临时根}）")


class _断言失败(Exception):
    """断言不成立（与"网络/凭据问题"分开，退出码不同）。"""


def _断言(条件, 说明: str) -> None:
    if not 条件:
        raise _断言失败(说明)


def _跑(参数, 临时根: Path) -> int:
    from wangpan.pan.光鸭 import 光鸭适配器
    from wangpan.scrape.库 import 资料库
    from wangpan.scrape.服务 import 刮削服务, 刮削设置
    from wangpan.scrape.扫描 import 合并远端单元, 造远端单元
    from wangpan.scrape.图片 import 图片缓存
    from wangpan.scrape.tmdb import TMDB客户端, TMDB配置
    from wangpan.identify.详情 import 候选详情
    from wangpan.identify.检索 import 默认缓存 as 默认检索缓存
    from wangpan.identify.管线 import 全链
    from wangpan.identify.学习 import 读库 as 读学习库, 写库 as 写学习库

    # ---- 1) 真 TMDB + 真光鸭 ----
    配置 = TMDB配置.从环境与配置()
    if not 配置.可用():
        打印("❌ 没配 TMDB 凭据（数据/刮削.json 的 tmdb 节点，或 V2_TMDB_TOKEN）")
        return 2
    客户端 = TMDB客户端(配置)
    打印("TMDB 配置：" + str({k: v for k, v in 客户端.配置摘要().items()
                          if k in ("可用", "鉴权", "语言", "代理")}))
    适配器 = 光鸭适配器()
    状态 = 适配器.登录状态()
    if not 状态.get("已登录"):
        打印("❌ 光鸭没登录（先在网盘页登录/导入令牌）")
        return 2
    打印(f"光鸭：已登录（用户 {状态.get('用户标识')}，令牌剩余 "
        f"{float(状态.get('过期剩余秒') or 0) / 60:.0f} 分钟）")

    try:
        条目们 = 适配器.列出(参数.目录)
    except Exception as 错:                                                  # noqa: BLE001
        打印(f"❌ 光鸭列目录失败（{参数.目录}）：{type(错).__name__}: {错}")
        return 3
    文件们 = [str(x.路径) for x in 条目们 if not x.是目录]
    打印(f"\n① 列目录：{参数.目录} → {len(文件们)} 个文件")
    if not 文件们:
        打印("❌ 目录里没有文件")
        return 3
    for 名 in sorted(文件们)[:4]:
        打印(f"    {Path(名).name}")
    打印(f"    …（共 {len(文件们)} 个）")

    # ---- 2) 造单元 → 合并成一部剧（与界面同一条路）----
    单元们 = 造远端单元(参数.网盘, 参数.目录, 文件们)
    分组: dict = {}
    for 单元 in 单元们:
        分组.setdefault(str(单元.路径), []).append(单元)
    合并 = 合并远端单元(单元们)
    _断言(合并 is not None, "造不出远端单元")
    打印(f"\n② 造单元：{len(单元们)} 个「一集一个」→ 合并成 {len(分组)} 个剧目录")
    打印(f"    {合并.一句话()}（合并后的路径：{合并.路径}）")

    # ---- 3) 第一轮：逐集走识别链 + 用服务落库到临时库 ----
    缓存 = 默认检索缓存()                 # 进程内共享；落盘由服务层负责（跑完还原）
    详情 = 候选详情(客户端, 上限=3)
    打印("\n③ 第一轮：逐集走「结构 → 候选 → 检索 → 打分 → 决策」")
    第一轮结果 = _逐集(全链, 客户端, 缓存, 详情, 文件们, 参数.目录, 读学习库())

    库路径 = 临时根 / "资料库.db"
    库 = 资料库(库路径)
    日志: list[str] = []
    服务 = 刮削服务(库, 客户端, 图片缓存(临时根 / "图缓存"),
                刮削设置(最小文件字节=0, 本批上限=50,
                     抓季集详情=True, 下载图片=bool(参数.下载图片)),
                日志回调=日志.append, 远端单元=分组)
    try:
        服务.记远端单元(单元们)
        结果 = 服务.续跑()
        打印(f"\n④ 落库（临时库 {库路径.name}）：{结果.摘要()}")
        for 行 in 日志:
            打印(f"    {行}")

        _核对库(库, 结果)
        _核对逐集(第一轮结果, 期望自动=len(文件们))
    finally:
        服务.关闭()
        库.关闭()

    # ---- 4) 第二轮：学习库里先写死「这个目录 → tv:223911」----
    打印("\n⑤ 第二轮：学习库先写入「这个目录 → tv:223911」，再跑一遍")
    学习路径 = Path(os.environ["V2_识别学习库"])
    写学习库({"版本": 1, "更新时间": time.strftime("%Y-%m-%d %H:%M:%S"),
           "别名": {}, "作品": {},
           "目录": {Path(参数.目录).name: {
               "tmdb_id": 仙逆标识, "类型": "tv", "标题": "仙逆", "年份": 2023,
               "次数": 1, "最后确认": time.strftime("%Y-%m-%d %H:%M:%S")}}},
          学习路径)
    打印(f"    学习库：{学习路径}（**临时文件**，用户那份没动）")
    第二轮结果 = _逐集(全链, 客户端, 缓存, 详情, 文件们, 参数.目录, 读学习库())
    靠学习 = sum(1 for x in 第二轮结果 if x["学习命中"])
    自动 = sum(1 for x in 第二轮结果 if x["档位"] == "自动入库")
    打印(f"\n⑥ 第二轮汇总：自动入库 {自动}/{len(文件们)}，"
        f"其中**靠学习库命中直接定**的有 {靠学习} 集")
    _核对逐集(第二轮结果, 期望自动=len(文件们))
    _断言(靠学习 == len(文件们),
         f"第二轮应当每一集都命中学习库，实际只有 {靠学习}/{len(文件们)} 集")

    打印("\n" + "=" * 78)
    打印(f"✅ 端到端真机复验通过：{len(文件们)} 集 · 库里 1 条媒体 · "
        f"16 个集都挂上文件 · 第二轮 {靠学习} 集靠学习命中")
    打印("=" * 78)
    return 0


def _逐集(全链, 客户端, 缓存, 详情, 文件们, 目录: str, 学习库对象) -> list[dict]:
    """每一集都单独走一遍链（这就是阶段③/⑤要看的"每集走了哪一档"）。"""
    出: list[dict] = []
    for 序号, 文件 in enumerate(sorted(文件们), start=1):
        链 = 全链(文件, 客户端, 父目录名=Path(目录).name,
                 缓存=缓存, 详情=详情, 学习库=学习库对象)
        一集一行(序号, len(文件们), Path(文件).name, 链)
        出.append({"文件": 文件, "档位": 链.决策结果.档位,
                 "原因": 链.决策结果.原因, "学习命中": 学习命中(链),
                 "首选标识": (链.打分结果.首选().标识
                           if 链.打分结果.首选() else "")})
    return 出


def _核对逐集(结果们: list[dict], 期望自动: int) -> None:
    """逐集档位：**不许有待确认/丢弃**，有就把原因一条条打出来（不掩盖）。"""
    没自动 = [x for x in 结果们 if x["档位"] != "自动入库"]
    if not 没自动:
        return
    打印(f"\n⚠️ 有 {len(没自动)} 集没走自动入库（原因如下，**不掩盖**）：")
    for x in 没自动:
        打印(f"    {Path(x['文件']).name}：{x['档位']} —— {x['原因']}")
    raise _断言失败(f"{len(没自动)} 集没有自动入库（期望 {期望自动} 集全自动）")


def _核对库(库, 结果) -> None:
    """库里必须是"一部剧一张海报 + 16 个集都挂上文件"。"""
    from wangpan.scrape.模型 import 媒体类型
    _断言(结果.失败 == 0, f"刮削有失败：{结果.错误们}")
    _断言(库.计数() == 1, f"库里应当恰好 1 条媒体，实际 {库.计数()} 条")
    行 = 库.列表()[0]
    条目 = 库.取媒体(int(行["id"]))
    _断言(条目.标题 == "仙逆", f"标题应当是「仙逆」，实际「{条目.标题}」")
    _断言(条目.类型 is 媒体类型.剧集, f"类型应当是剧集，实际 {条目.类型}")
    普通季 = [s for s in 条目.季们 if s.季号 == 1]
    _断言(bool(普通季), f"应当有第 1 季，实际季号：{[s.季号 for s in 条目.季们]}")
    挂了 = [c for 季 in 条目.季们 for c in 季.集们 if c.文件路径]
    文件们 = 库.文件们(int(行["id"]))
    打印(f"    库里：id={行['id']}｜{条目.标题}（{条目.年份}）｜{条目.类型.value}｜"
        f"季 {[s.季号 for s in 条目.季们]}｜在线总集数 {条目.汇总集数()}｜"
        f"**挂上文件的集 {len(挂了)}**｜文件表 {len(文件们)} 条")
    for 集对象 in sorted(挂了, key=lambda c: c.集号)[:3]:
        打印(f"      S{集对象.季号:02d}E{集对象.集号:03d} ← {Path(str(集对象.文件路径)).name}")
    打印("      …")
    _断言(len(挂了) == 16, f"应当有 16 个集挂上文件，实际 {len(挂了)}")
    _断言(len(文件们) == 16, f"文件表应当有 16 条，实际 {len(文件们)}")
    _断言(all(Path(str(c.文件路径)).name for c in 挂了), "挂上的文件路径不能是空的")
    _断言(len({c.集号 for c in 挂了}) == 16, "16 个集必须是不同的集号")


if __name__ == "__main__":
    raise SystemExit(main())
