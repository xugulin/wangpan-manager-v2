def 主函数(参数: list[str] | None = None) -> int:
    解析器 = argparse.ArgumentParser(
        description="识别评测：拿标注集当尺子量识别管线（架构文档 P0）",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    解析器.add_argument("--标注", default=str(默认标注集),
                     help=f"标注集路径（默认 {默认标注集}）")
    解析器.add_argument("--报告", default=str(默认报告),
                     help=f"报告输出路径（默认 {默认报告}）")
    解析器.add_argument("--实现", choices=("旧", "新"), default="旧",
                     help="取解析结果用哪套：旧 = wangpan.scrape.命名解析.解析（现状）；"
                          "新 = wangpan.identify.管线（P1 之后，现在会报 3）")
    参数 = 解析器.parse_args(参数)

    标注路径 = Path(参数.标注)
    报告路径 = Path(参数.报告)
    try:
        样本们 = 读标注(标注路径)
        汇总 = 跑评测(样本们, 参数.实现)
    except 评测错误 as 错:
        print(f"评测跑不动（尺子本身有问题）：{错}", file=sys.stderr)
        return 2
    except 实现不可用 as 错:
        print(f"评测跑不动（实现不可用）：{错}", file=sys.stderr)
        return 3

    try:
        报告路径.parent.mkdir(parents=True, exist_ok=True)
        报告路径.write_text(生成报告(汇总, 标注路径, 报告路径), encoding="utf-8")
    except OSError as 错:
        print(f"评测跑不动（报告写不出去）：{报告路径}（{错}）", file=sys.stderr)
        return 2

    打印摘要(汇总, 标注路径, 报告路径)
    return 0                       # 有失败样例也是 0：评测不是断言


if __name__ == "__main__":
    raise SystemExit(主函数())
