        "个案，个案可以靠 `if` 蒙过去，但没人知道整体是进步还是退步。这张表就是"
        "\"更准了\"的定义：每次改动跑同一个脚本，数字只许升、不许降。",
        "",
        "**口径**（读数字前先看，详见脚本文档字符串）：季的来源优先级 = 目录季 > 文件名季 > "
