#!/usr/bin/env python3
"""识别评测：把"识别到底准不准"变成一串可复现的数字 —— P0 阶段先造尺子。

为什么先造尺子（见 ``docs/识别/00_架构.md`` 第二节）
==================================================
现在的识别是"一个 ``解析()`` + 一次 TMDB 搜索 + 一个分数阈值"，于是"改了规则到底是
变好还是变坏"根本没法回答：真机上暴露的 ``146.SDR.8bit…mp4``（标题被画质标签污染、
季集全丢）与 ``Renegade.Immortal.S01E138…mkv``（识别正确）都只是**个案** ——
修完一个又冒一个，没人知道整体是进步还是退步。

架构文档列的第四条根因就是"没有尺子"。所以 P0 只做两件事：攒一份来自**真机真实文件名**
的标注集（``数据/识别标注.jsonl``），再写这个评测脚本，每次改动都跑出同一张指标表 +
失败样例清单。**指标只许升不许降，降了就是回归。**

这个脚本设计成"将来接新管线也用它"：取解析结果只走 :func:`取解析结果` 一个函数，
现在它调 ``wangpan.scrape.命名解析.解析``，P1 之后换成 ``wangpan.identify.管线``
（换法写在那个函数的 TODO 里，命令行也可以 ``--实现 新`` 直接试）。

口径（不看这段，指标数字会看歪）
==============================
* **类型**：标注用 ``tv`` / ``movie`` / ``unknown``；旧解析层内部叫 ``集`` / ``剧集`` /
  ``电影`` / ``未知`` / ``非视频``，这里统一映射：``电影`` → movie，``集``/``剧集`` → tv，
  其余 → unknown。类型对不上时，标题/季/集往往会一起错，所以指标表里两者分开算。
* **季**：季号有三个来源，优先级是 **目录季**（``Season 02`` / ``第2季``）> **文件名季**
  （``S02`` / ``第二季``）> **默认 1**。也就是说：只要这条样本是"某一集"或"某几集的打包"
  （集号有了）而上面两处都没写季，期望就是 **1** —— 这是 Jellyfin/Emby 对"没有季目录的剧"
  的默认行为，也是真机 `146.SDR…` / `131.SDR…` 两条样本确认过的值（仙逆是单季剧）。
  反过来，**整季包 / 合集 / 完结这种没有集号的**（``某剧.合集``）期望 季 = null ——
  没有集号就不许瞎填 1；电影（movie）的季/集必须都是 null。特别篇/SP/OVA/NCOP/NCED 走
  Jellyfin 的"第 0 季"惯例 → 期望 季 = 0。
* **集**：期望 ``null`` 表示"这不是某一集"（电影、整季包、合集）；除此之外必须精确相等。
  打包写法见下一条。集号写法的"季"必须一致：``01.mp4`` 与 ``第03集.mp4`` 在同一层目录里
  必须得到同一个季 —— 旧解析层这两种写法一个给 S01、一个给 null，这正是尺子要钉住的
  内部不一致。
* **打包写法**：``E01-E12`` / ``01-12`` / ``更新至12`` / ``更新至第24集`` / ``全12集`` 的
  语义都是"从第 1 集开始的打包"，所以期望 ``集`` = 1（区间上界属于 ② 结构输出的 ``集到``，
  标注 schema 里没有这一列）；``合集`` / ``完结`` 这种完全不带集号的，期望 ``集`` = null。
* **年份**：理想做法是"从后往前找能留下非空标题的那个年份"。所以 ``2012.mp4`` 期望
  ``年份 = null``（2012 是片名）、``1984.1984.1080p.mkv`` 期望 ``年份 = 1984``、
  ``2001.A.Space.Odyssey.1968.1080p.mkv`` 期望 ``年份 = 1968``（1968 是年份、2001 是片名）。
* **标题**：比对前归一（转半角、小写、去空格与标点），否则 ``Spider-Man`` 与 ``Spider Man``
  会被算成两个标题。中英混排的期望标题 = **两种写法都保留**（空格连接），因为 ③ 候选生成
  阶段两种写法都要拿去搜；只留一种会让中文剧集又退回"靠模糊搜索碰运气"。
* **样本写法**：``样本`` 可以是 ``目录/文件名``（真实扫描给的就是路径）。此时
  :func:`拆样本` 取最后一段当文件名、倒数第二段当父目录（``父目录`` 字段仍可覆盖它）。
  旧解析层只吃 (文件名, 父目录名)，看不到更上层目录 —— 所以像
  ``葬送的芙莉莲/Season 01/05.mkv`` 这种样本现在标题必然拿不到，这是**已知缺口**，
  正好留给 P1 的管线（它应该拿到整条路径）。

跑法
====
::

    运行环境/venv/bin/python 工具/识别评测.py                    # 默认用现有解析层（旧）
    运行环境/venv/bin/python 工具/识别评测.py --实现 新            # P1 之后的 identify.管线
    运行环境/venv/bin/python 工具/识别评测.py --标注 数据/识别标注.jsonl --报告 数据/识别评测.md

退出码
======
* **有失败样例照样返回 0** —— 这是尺子，不是 CI 测试：P0 阶段分数低是正常的，
  拿失败样例去改解析层才是它的用法；
* ``2``：标注集缺失 / 带 BOM / 某行不是合法 JSON / 字段不合法（**尺子本身坏了**，
  这时候指标一个都不可信，必须报错停下）；
* ``3``：被 ``--实现 新`` 点名的管线还不在（不静默退回旧实现 —— 静默退回会让人以为
  新管线已经达标）。
"""

