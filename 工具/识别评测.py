# ============================ 读标注集 ============================


def 读标注(路径: Path) -> list[dict]:
    """读标注集并校验字段。**任何一处不合法都抛 :class:`评测错误`**。

    为什么校验这么严：标注集是唯一权威（架构文档第六节第 1 条）。一行写错（少个引号、
    类型写成 ``TV``）会让指标偷偷偏掉，而这种错不会自己报错 —— 必须在这里就拦住。
    """
    if not 路径.exists():
        raise 评测错误(f"标注集不存在：{路径}\n（P0 的第一件事就是攒这份标注集，"
                    f"每行一个 JSON 对象，见 工具/识别评测.py 的文档字符串）")
    try:
        文本 = 路径.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as 错:
        raise 评测错误(f"标注集读不动（要求 UTF-8）：{路径}（{错}）") from 错
    if 文本.startswith("\ufeff"):
        raise 评测错误(f"标注集带 BOM，请存成无 BOM 的 UTF-8：{路径}")

    样本们: list[dict] = []
    for 行号, 行 in enumerate(文本.splitlines(), 1):
        行 = 行.strip()
        if not 行:
            continue                       # 空行容忍（方便手工编辑时留段落）
        try:
            条 = json.loads(行)
        except json.JSONDecodeError as 错:
            raise 评测错误(f"{路径} 第 {行号} 行不是合法 JSON：{错}") from 错
        样本们.append(_校验一条(条, 路径, 行号))
    if not 样本们:
        raise 评测错误(f"标注集里一条样本都没有：{路径}")
    return 样本们


def _校验一条(条: dict, 路径: Path, 行号: int) -> dict:
    """校验一条标注，返回规范化后的副本（缺省字段补 null，省得下游到处判空）。"""
    谁 = f"{路径} 第 {行号} 行"
    if not isinstance(条, dict):
        raise 评测错误(f"{谁}：一行必须是一个 JSON 对象")
    样本 = 条.get("样本")
    if not isinstance(样本, str) or not 样本.strip():
        raise 评测错误(f"{谁}：缺 样本（真实文件名，或 \"目录/文件名\"）")
    父目录 = 条.get("父目录") or ""
    if not isinstance(父目录, str):
        raise 评测错误(f"{谁}：父目录 必须是字符串（没有就给空串）")
    期望 = 条.get("期望")
    if not isinstance(期望, dict):
        raise 评测错误(f"{谁}：缺 期望 对象")
    标题 = 期望.get("标题")
    if not isinstance(标题, str) or not 标题.strip():
        raise 评测错误(f"{谁}：期望.标题 必须是非空字符串")
    类型 = 期望.get("类型")
    if 类型 not in 类型值域:
        raise 评测错误(f"{谁}：期望.类型 只能是 {'/'.join(类型值域)}，收到 {类型!r}")
    干净期望 = {"标题": 标题, "类型": 类型}
    for 键 in ("年份", "季", "集", "tmdb_id"):
        值 = 期望.get(键)
        if 值 is not None and not isinstance(值, int):
            raise 评测错误(f"{谁}：期望.{键} 只能是整数或 null，收到 {值!r}")
        干净期望[键] = 值
    return {"样本": 样本.strip(), "父目录": 父目录.strip(), "期望": 干净期望}


def 拆样本(样本: str, 父目录: str) -> tuple[str, str]:
    """``目录/文件名`` → ``(文件名, 父目录)``；``父目录`` 给了就不看路径里的倒数第二段。

    为什么支持这种写法：真实扫描给的是**路径**，"剧名目录/季目录/文件" 这种上下文光靠
    "文件名 + 一层父目录"表达不出来（例如 ``葬送的芙莉莲/Season 01/05.mkv``）。
    旧解析层只吃 (文件名, 父目录名)，所以这里把路径压成两段；新管线应该整条路径都拿到
    （见 :func:`取解析结果` 里的 TODO）。
    """
    段们 = [x for x in (样本 or "").replace("\\", "/").split("/") if x]
    if len(段们) >= 2:
        return 段们[-1], (父目录 or 段们[-2])
    return (样本 or "").strip(), 父目录 or ""


