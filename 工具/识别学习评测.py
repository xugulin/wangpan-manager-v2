def _取参数() -> argparse.Namespace:
    解析 = argparse.ArgumentParser(
        description="P4 学习评测：空库 / 有库两轮对照（真 TMDB + 标注集）",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    解析.add_argument("--标注", default=str(默认标注集))
    解析.add_argument("--报告", default=str(默认报告))
    解析.add_argument("--限制", type=int, default=0, help="只跑前 N 条（调试用，0 = 全跑）")
    解析.add_argument("--不落盘", action="store_true", help="不用/不写 数据/识别检索缓存.json")
    解析.add_argument("--不富化", action="store_true", help="不取 TMDB 详情补季集范围")
    解析.add_argument("--富化上限", type=int, default=3)
    解析.add_argument("--不取别名", action="store_true")
    解析.add_argument("--允许离线", action="store_true")
    解析.add_argument("--安静", action="store_true")
    解析.add_argument("--保留库", action="store_true",
                    help="跑完**不**恢复 数据/识别学习.json（排查用；默认恢复原样）")
    解析.add_argument("--json", default="", metavar="路径", help="把两轮逐条结果写一份 JSON")
    return 解析.parse_args()


def main() -> int:
    参数 = _取参数()
    标注路径 = Path(参数.标注)
    if not 标注路径.is_absolute():
        标注路径 = 项目根 / 标注路径
    报告路径 = Path(参数.报告)
    if not 报告路径.is_absolute():
        报告路径 = 项目根 / 报告路径

    try:
        样本们 = P3.P1评测.读标注(标注路径)
    except P3.P1评测.评测错误 as 错:
        print(f"❌ 标注集读不动（尺子本身坏了，指标一个都不可信）：\n{错}")
        return 4
    if 参数.限制:
        样本们 = 样本们[:参数.限制]

    # ---- 凭据与连通性（与 P3 脚本同一套：必须绕开 7 天磁盘缓存真发一次）----
    try:
        from wangpan.scrape.tmdb import TMDB客户端, TMDB配置, 请求失败
    except Exception as 异常:                                                # noqa: BLE001
        print(f"❌ 导不进 TMDB 客户端：{type(异常).__name__}: {异常}")
        return 2
    配置 = TMDB配置.从环境与配置()
    if not 配置.可用():
        print("❌ 没配 TMDB 凭据（token / apiKey）：写进 数据/刮削.json 的 tmdb 节点，"
              "或设环境变量 V2_TMDB_TOKEN / V2_TMDB_API_KEY。")
        return 2
    客户端 = TMDB客户端(配置)
    离线 = bool(参数.允许离线)
    探针 = TMDB客户端(dataclasses.replace(配置, 缓存TTL秒=0))
    try:
        探针.搜电影("沙丘", 2021)
        print("连通性自检：✅ 真发了一次请求（已绕开 7 天磁盘缓存）")
    except 请求失败 as 错:
        print("❌ 连不上 TMDB（或凭据不对）。原样原因如下：\n   " + str(错))
        print("   本机实测直连到不了 api.themoviedb.org，要走代理："
              "数据/刮削.json 的 tmdb.proxy（例如 socks5://127.0.0.1:10808）")
        if not 离线:
            探针.关闭()
            客户端.关闭()
            return 3
        print("   （--允许离线：继续跑，但只能吃落盘缓存里的旧结果）")
    finally:
        探针.关闭()

    # ---- 学习库：先备份，跑完恢复（评测绝不污染用户的真实库）----
    库路径 = 默认学习库路径()
    原样: Optional[str] = None
    if 库路径.is_file():
        原样 = 库路径.read_text(encoding="utf-8")
    print(f"学习库：{库路径}"
          f"（{'已备份原库，' if 原样 is not None else '原本不存在，'}"
          f"跑完{'保留' if 参数.保留库 else '恢复原样'}）")

    try:
        # 第一轮：**空库**（目录里那一份先挪开，免得第一轮就被上一轮的实验数据影响）
        if 库路径.is_file():
            库路径.unlink()
        清空(库路径)         # 写一份带版本号的空库：文件在、但内容是空的
        print("第一轮（空学习库）开始…")
        起点 = time.time()
        缓存 = P3.检索缓存(落盘=None if 参数.不落盘 else P3.默认落盘缓存路径())
        详情 = P3.候选详情(客户端, 上限=0 if 参数.不富化 else 参数.富化上限,
                       取别名=not 参数.不取别名)
        第一 = 跑一轮(样本们, 客户端, 缓存, 详情, 库=None, 富化=not 参数.不富化,
                   门槛=P3.默认门槛, 安静=参数.安静)
        概1 = 算指标(第一)

        # 中间：模拟"用户在待确认队列里点了正确的那一条"
        确认, 没确认 = 自动确认(第一, 样本们, 库路径)
        print(f"\n模拟用户确认：{len(确认)} 条"
              f"（另有 {len(没确认)} 条待确认没有变成学习样本）")
        for 项 in 确认:
            print(f"   🧠 {项['样本'][:40]:42}{项['摘要']}")
        库对象 = 读库(库路径)
        print("学习库：" + json.dumps({k: v for k, v in 统计(库路径).items()},
                                ensure_ascii=False))

        # 第二轮：带学习库（同一批样本、同一条链、同一个缓存）
        print("\n第二轮（带学习库）开始…")
        第二 = 跑一轮(样本们, 客户端, 缓存, 详情, 库=库对象, 富化=not 参数.不富化,
                   门槛=P3.默认门槛, 安静=参数.安静)
        概2 = 算指标(第二)
        用时 = time.time() - 起点
        库原始 = 读原始(库路径)
    finally:
        客户端.关闭()
        # 恢复用户的真实库（原本没有就删掉）：评测是评测，实验数据不许留在用户库里
        if not 参数.保留库:
            try:
                if 原样 is None:
                    库路径.unlink(missing_ok=True)
                else:
                    库路径.write_text(原样, encoding="utf-8")
                print(f"（学习库已恢复：{'删除（原本不存在）' if 原样 is None else '还原原内容'}）")
            except OSError as 错:                                            # noqa: BLE001
                print(f"⚠️ 学习库恢复失败（请手工检查 {库路径}）：{错}")

    第一轮 = {"结果们": 第一, "汇总": 概1}
    第二轮 = {"结果们": 第二, "汇总": 概2, "库原始": 库原始}
    报告 = 生成报告(第一轮, 第二轮, 确认, 没确认, 库路径, 标注路径, 用时,
                 富化=not 参数.不富化, 富化上限=参数.富化上限, 详情=详情,
                 缓存=缓存, 门槛=P3.默认门槛)
    报告路径.parent.mkdir(parents=True, exist_ok=True)
    报告路径.write_text(报告, encoding="utf-8")
    打印摘要(第一轮, 第二轮, 确认, 报告路径)

    if 参数.json:
        落点 = Path(参数.json)
        if not 落点.is_absolute():
            落点 = 项目根 / 落点
        落点.parent.mkdir(parents=True, exist_ok=True)
        落点.write_text(json.dumps(
            {"第一轮": {"汇总": 概1, "逐条": [{k: v for k, v in x.items() if k != "_确认用"}
                                        for x in 第一]},
             "第二轮": {"汇总": 概2, "逐条": [{k: v for k, v in x.items() if k != "_确认用"}
                                        for x in 第二]},
             "确认": 确认, "没确认": 没确认, "库": 库原始},
            ensure_ascii=False, indent=1, default=str), encoding="utf-8")
        print(f"（两轮逐条结果已写入 {落点}）")
    return 0


