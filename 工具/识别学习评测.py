"""P4 学习评测：**同一批 91 条标注跑两轮**，量化"越用越准"到底涨了多少。

为什么要有这个脚本（而不是"再来一个 demo"）
==========================================
P3 的验收是"Top-1 ≥95%、自动入库精确率 ≥99%"，跑出来是
**Top-1 63/63、自动 43/43（精确率 100%）、覆盖率 68.3%、待确认 31.7%**
（``数据/识别打分评测.md``）。P3 报告第八节第 4 条把 P4 的入口写得很清楚：

> 待确认 20 条全是「分不够高 / 领先不够多」，不是「选错了」：用户点一下就写成
> 「目录→作品 / 别名→作品」的学习样本，第二次识别直接命中（那时 ⑤ 的学习库信号
> +45 分会把它们送进自动档）。

所以 P4 只有一个可验收的说法：**覆盖率涨上去，而精确率一条都不许掉**。这个脚本把这件事
做成可复现的两轮对照：

* **第一轮**：学习库空的（= 用户第一次遇到这些片子）→ 记录自动入库覆盖率 + 待确认清单；
* **中间**：把那 20 条待确认里**实际是对的**（用标注集的 ``tmdb_id`` 判定）逐条
  "自动确认"——等价于"用户点了正确的那一条"，据此写学习库；
* **第二轮**：带着学习库重跑同一批 → 覆盖率提升多少、"精确率仍为 100%"是否成立、
  有多少条是**靠学习命中直接定**的。

为什么"只确认对的"是**偏乐观但正确**的模拟
==========================================
真实用户也可能点错，那时学习库会脏（P3 的 ⑥ 决策对此有防守：学习库命中**免不掉**
年份/类型/季集的反证，见 ``决策.决策`` 里那段注释）。本脚本要回答的是
"**这套机制的上限在哪**"，所以按"用户每次都点对"来模拟；脏库的防守由
``tests/test_识别学习.py::打分联动测试`` 钉住（构造年份/类型反证，断言仍然待确认）。

口径与 P3 **完全一致**（不然两轮数字没法比）
==========================================
复用 ``工具/识别打分评测.py`` 的模块：同一个标注集读取、同一个 ``跑一条`` 形状、
同一个 ``算指标``、同一个候选详情富化（头部 3 条）、同一个检索缓存与门槛。
两轮之间**只有"学习库"这一个变量不同**。

评测完**必须把 ``数据/识别学习.json`` 恢复原样**（原本没有就删掉）：评测是评测，
用户的真实学习库不能被实验数据污染（脚本在 ``finally`` 里恢复，包括异常退出）。

跑法
====
::

    运行环境/venv/bin/python 工具/识别学习评测.py
    运行环境/venv/bin/python 工具/识别学习评测.py --限制 20        # 只跑前 20 条（调试）
    运行环境/venv/bin/python 工具/识别学习评测.py --保留库          # 跑完不恢复（排查用）

退出码（与 P3 脚本一致）
========================
* ``0``：跑完了（**有失败样例也返回 0**：这是尺子，不是 CI 测试）；
* ``1``：命令行用法错；``2``：TMDB 凭据没配；``3``：连不上 TMDB（除非 ``--允许离线``）；
* ``4``：标注集读不动 / 字段不合法（尺子本身坏了，这时指标一个都不可信）。
"""

