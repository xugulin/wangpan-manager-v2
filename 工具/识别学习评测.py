# ============================ 一条样本（带学习库） ============================


def 样本路径(条: dict) -> str:
    """标注条目 → 一条"像真机那样"的路径（学习层的目录键要从路径里看出来）。

    标注里两种写法都有：``("146.SDR….mp4", 父="仙逆.4K高码.SDR.60fps")`` 与
    ``("葬送的芙莉莲/Season 01/05.mkv", 父="")``。前者要拼成路径、后者本来就是路径。
    """
    样本 = str(条.get("样本") or "")
    父 = str(条.get("父目录") or "")
    if "/" in 样本 or "\\" in 样本 or not 父:
        return 样本
    return f"{父.rstrip('/')}/{样本}"


def 跑一条(条: dict, 客户端, 缓存, 详情, *, 库=None, 富化: bool = True,
          门槛=None) -> dict:
    """一条标注样本 → 整条链的结果（与 P3 的 ``跑一条`` 同形状，多带一个学习库）。

    为什么不能直接复用 P3 的 ``跑一条``：它给 ⑤ 打分传的是**没有学习库**的调用
    （P3 的验收口径就是"不含学习库的理论满分 126"）。学习库只能作为**新增的入参**
    加进来，两轮的其它环节必须逐字相同 —— 那样 68.3% → ? 的差值才全部归因于学习。

    P5 起链本身由 ``identify.管线.全链`` 提供（**与服务层同一份代码**）：这里只把
    "学习库 / 别名表"两个入参喂进去，链内部怎么走由管线决定（免得评测自己维护一份）。
    """
    from wangpan.identify.管线 import 全链

    门槛 = 门槛 or P3.默认门槛
    别名表 = None if (库 is None or 库.空的()) else dict(库.别名)
    链 = 全链(条["样本"], 客户端, 父目录名=条["父目录"], 学习库=库, 别名表=别名表,
             缓存=缓存, 详情=详情, 富化=富化, 门槛=门槛)
    结构, 最终, 检索结果 = 链.结构, 链.打分结果, 链.检索结果
    判定 = 链.决策结果

    期望 = 条["期望"]
    期望标识 = str(期望["tmdb_id"]) if 期望.get("tmdb_id") is not None else ""
    候选标识们 = [str(x.标识) for x in 检索结果.候选们]
    首选 = 最终.首选()
    学习项 = 首选.取("学习库") if 首选 is not None else None
    学习命中 = bool(学习项 is not None and not 学习项.中性 and 学习项.系数 > 0)
    命中排序 = 0
    for 序号, 项 in enumerate(最终.分数们, start=1):
        if 期望标识 and 项.标识 == 期望标识:
            命中排序 = 序号
            break

    return {
        "样本": 条["样本"], "父目录": 条["父目录"], "期望": 期望,
        "结构": {"标题": 结构.标题, "年份": 结构.年份, "类型": 结构.类型,
               "季": 结构.季, "集": 结构.集, "一句话": 结构.一句话()},
        "候选数": len(检索结果.候选们),
        "观察标题们": 最终.观察标题们,
        "首选标识": 首选.标识 if 首选 else "",
        "首选标题": 首选.标题 if 首选 else "",
        "首选类型": 首选.类型 if 首选 else "",
        "首选年份": getattr(首选.候选, "年份", None) if 首选 else None,
        "分数": 首选.总分 if 首选 else 0.0,
        "间距": 最终.间距(),
        "信号们": [(x.名字, round(x.得分, 1), x.说明) for x in (首选.信号们 if 首选 else [])],
        "档位": 判定.档位,
        "原因": 判定.原因,
        "期望标识": 期望标识,
        "期望在候选里": bool(期望标识) and 期望标识 in 候选标识们,
        "期望排第几": 命中排序,
        "Top1对": bool(期望标识) and 首选 is not None and 首选.标识 == 期望标识,
        "错误": bool(检索结果.错误们),
        "学习命中": 学习命中,
        "学习说明": 学习项.说明 if 学习项 is not None else "",
        "_确认用": (结构, 最终) if (首选 is not None) else None,
    }


# ============================ 一轮 ============================


def 跑一轮(样本们: list[dict], 客户端, 缓存, 详情, *, 库=None, 富化: bool = True,
         门槛=None, 安静: bool = False) -> list[dict]:
    结果们: list[dict] = []
    for 序号, 条 in enumerate(样本们, start=1):
        try:
            项 = 跑一条(条, 客户端, 缓存, 详情, 库=库, 富化=富化, 门槛=门槛)
        except Exception as 异常:                                            # noqa: BLE001
            # 一条炸了不许毁掉整轮（否则两轮数字不可比）
            项 = {"样本": 条["样本"], "父目录": 条["父目录"], "期望": 条["期望"],
                "结构": {}, "候选数": 0, "观察标题们": [], "首选标识": "", "首选标题": "",
                "首选类型": "", "首选年份": None, "分数": 0.0, "间距": 0.0, "信号们": [],
                "档位": 档_丢弃, "原因": f"评测崩溃：{type(异常).__name__}: {异常}",
                "期望标识": "", "期望在候选里": False, "期望排第几": 0, "Top1对": False,
                "错误": True, "学习命中": False, "学习说明": "", "_确认用": None}
        结果们.append(项)
        if not 安静:
            标 = "✅" if 项["Top1对"] else ("❌" if 项["期望标识"] else "？")
            学 = "🧠" if 项["学习命中"] else "  "
            print(f"  [{序号:>3}/{len(样本们)}] {标}{学} {条['样本'][:38]:40}"
                  f"{项['档位']}　{项['分数']:6.1f} 分　间距 {项['间距']:5.1f}", flush=True)
    return 结果们


# ============================ 模拟"用户点确认" ============================


def 自动确认(结果们: list[dict], 样本们: list[dict], 库路径: Path) -> tuple[list[dict], list[dict]]:
    """把"待确认里**实际是对的**"逐条写进学习库（模拟用户点了正确的那一条）。

    返回 ``(确认明细, 没确认的清单)``。判定对错用标注集的 ``tmdb_id``（唯一权威）：
    首选 id == 标注 id 才确认 —— 用户不会把错的选进来（这是"上限"模拟）。
    未标注（``tmdb_id`` 为空）的待确认**没法判定**，一律不确认（宁可少学，不瞎学）。
    """
    确认: list[dict] = []
    没确认: list[dict] = []
    for 项 in 结果们:
        if 项["档位"] != 档_待确认:
            continue
        if not (项["期望标识"] and 项["Top1对"]):
            没确认.append({"样本": 项["样本"], "期望标识": 项["期望标识"],
                       "首选标识": 项["首选标识"], "首选标题": 项["首选标题"],
                       "原因": ("未标注，无法判定对错" if not 项["期望标识"]
                              else "首选就不是期望的作品（点了也是错的）")})
            continue
        if 项["_确认用"] is None:
            没确认.append({"样本": 项["样本"], "期望标识": 项["期望标识"],
                       "首选标识": "", "首选标题": "", "原因": "没有候选，无从确认"})
            continue
        结构, 分数结果 = 项["_确认用"]
        首选 = 分数结果.首选()
        条 = next((x for x in 样本们 if x["样本"] == 项["样本"]
                 and str(x.get("父目录") or "") == str(项["父目录"] or "")), None)
        路径文本 = 样本路径(条) if 条 else 项["样本"]
        记下 = 记确认(样本=路径文本, 结构=结构, 选中=首选.候选,
                    类型=项["首选类型"], 库路径=库路径)
        确认.append({"样本": 项["样本"], "路径": 路径文本, "期望标识": 项["期望标识"],
                   "首选标题": 项["首选标题"], "分数": 项["分数"], "间距": 项["间距"],
                   "目录": list(记下["目录"]), "别名": list(记下["别名"]),
                   "摘要": 记下["摘要"]})
    return 确认, 没确认


# ============================ 指标（复用 P3 的口径） ============================


def 算指标(结果们: list[dict]) -> dict:
    """与 P3 的 ``算指标`` 完全同一口径（只算已标注样本；分母为 0 写"—"）。"""
    汇总 = P3.算指标(结果们)
    汇总["学习命中数"] = sum(1 for x in 结果们 if x["学习命中"])
    已标 = [x for x in 结果们 if x["期望标识"]]
    汇总["学习命中已标注"] = sum(1 for x in 已标 if x["学习命中"])
    汇总["学习定的自动"] = sum(1 for x in 已标
                           if x["学习命中"] and x["档位"] == 档_自动)
    汇总["学习定的自动且正确"] = sum(1 for x in 已标
                              if x["学习命中"] and x["档位"] == 档_自动 and x["Top1对"])
    return 汇总


def _百分比(值) -> str:
    return "—" if 值 is None else f"{值 * 100:.1f}%"


def _差(新, 旧) -> str:
    if 新 is None or 旧 is None:
        return "—"
    return f"{(新 - 旧) * 100:+.1f} 个百分点"


