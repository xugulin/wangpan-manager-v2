"""⑤ 打分（``wangpan/identify/打分.py``）的单测：**纯函数 + 构造数据**。

为什么不联网也能测
==================
打分是纯函数（结构 + 候选进，分数出），所以这里全部用**构造数据**：真机上的候选长什么样
（《仙逆》223911、《仙逆合集篇》292307、《逆天成仙》287998…的标题/年份/热度/票数/来源证据
都是从真 TMDB 抄下来的真实值，见 ``工具/识别打分评测.py`` 的报告），但一个请求都不发。
理由很直接：打分是"规则"，规则必须能在**没有网络、没有凭据**的机器上被逐条钉住；
真网验证是评测脚本的活（``工具/识别打分评测.py``），不是单测的活。

钉住的是哪几件事
================
* **近名干扰**：``仙逆`` 必须赢 ``逆天成仙`` / ``逆仙而上`` / ``都市之逆天仙尊``；
* **同名前传**：``仙逆`` 必须赢 ``仙逆合集篇``（靠标题相似度 + (季,集) 范围）；
* **年份**：一致 > 差 1 年 > 差 2 年 > 差 ≥3 年（后者是反证，系数为负）；
* **类型**：混进剧集结果的电影候选被压下去；
* **证据**：中英两条查询词同时命中的候选比只被一个词命中的更可信；
* **热度**：弱先验 —— 票数 44 的正确项必须赢票数 99999 的错项（这是真机的坑）；
* **学习库**：空库中性；命中就是强加权（P4 的接口，文件还不存在）。
"""

from __future__ import annotations

import unittest
from dataclasses import dataclass, field
from typing import Optional

from wangpan.identify.打分 import (季集范围, 中文相似度, 英文相似度, 学习库, 打分,
                             学习命中, 季集范围系数, 年度系数, 标题相似度, 类型系数,
                             文本相似度, 权重表, 满分不含学习库, 观察标题们, 证据系数,
                             从候选取范围, 读学习库, 默认学习库路径)
from wangpan.identify.检索 import 检索候选


# ============================ 构造数据的小工具 ============================


@dataclass
class 假结构:
    """P1 结构结果的替身（只带打分要用的字段，用来顺带证明"鸭子类型"）。"""

    标题: str = ""
    年份: Optional[int] = None
    类型: str = "unknown"
    季: Optional[int] = None
    集: Optional[int] = None
    集到: Optional[int] = None
    文件标题: str = ""
    目录标题: str = ""
    标题候选们: list = field(default_factory=list)
    目录链: tuple = ()


def 造候选(标识: str, 标题: str, *, 类型: str = "tv", 年份=None, 原名: str = "",
         热度: float = 10.0, 票数: int = 100, 来源=None) -> 检索候选:
    """``来源=None`` 才给默认证据；显式传 ``{}`` 就是"没有证据"（别被 ``or`` 吃掉）。"""
    return 检索候选(标识=标识, 类型=类型, 标题=标题, 原名=原名 or 标题, 年份=年份,
                热度=热度, 票数=票数,
                来源=dict({标题: 80.0} if 来源 is None else 来源))


#: 真机《仙逆》那一批候选（值来自真 TMDB，见数据/识别打分评测.md 的真机样本小节）。
#: 做成函数是因为每次都要拿到**新的**候选对象（测试里会往候选上挂季集范围）。
def 仙逆那批() -> list:
    return [
        造候选("223911", "仙逆", 年份=2023, 热度=212.9, 票数=44,
             来源={"仙逆": 80.0, "Renegade Immortal": 56.0}),
        造候选("287998", "逆天成仙", 年份=2025, 热度=6.2, 票数=10, 来源={"仙逆": 60.0}),
        造候选("299719", "逆仙而上", 年份=2025, 热度=3.5, 票数=4, 来源={"仙逆": 60.0}),
        造候选("276954", "都市之逆天仙尊", 年份=2024, 热度=0.5, 票数=2, 来源={"仙逆": 60.0}),
    ]


# ============================ 标题相似度 ============================


class 标题相似度测试(unittest.TestCase):
    def test_中文完全一致(self):
        self.assertEqual(中文相似度("仙逆", "仙逆"), 1.0)
        self.assertEqual(中文相似度("葬送的芙莉莲", "葬送的芙莉莲"), 1.0)

    def test_中文近名干扰分数要拉开(self):
        正 = 中文相似度("仙逆", "仙逆")
        for 干扰 in ("逆天成仙", "逆仙而上", "都市之逆天仙尊", "仙逆合集篇"):
            分 = 中文相似度("仙逆", 干扰)
            self.assertLess(分, 0.5, f"{干扰} 不该拿到高相似度，实际 {分}")
            self.assertGreater(正, 分 + 0.4)

    def test_中文部分重合按比例(self):
        # 二元组 Dice 与编辑距离都算出 0.4：2 个共同字 / 5 个字
        self.assertAlmostEqual(中文相似度("仙逆", "仙逆合集篇"), 0.4, places=2)

    def test_日文原名与中文名本来就不该像(self):
        # 真机：209867 的标题是「葬送的芙莉莲」、原名是「葬送のフリーレン」。
        # 这两个词的相似度**必须**低，否则"拿原名去比"就失去了意义。
        self.assertLess(中文相似度("葬送的芙莉莲", "葬送のフリーレン"), 0.35)

    def test_英文按词重合忽略标点(self):
        self.assertEqual(英文相似度("The Bear", "The Bear"), 1.0)
        self.assertEqual(英文相似度("Spider Man No Way Home", "Spider-Man: No Way Home"), 1.0)
        self.assertAlmostEqual(英文相似度("The Office US", "The Office"), 0.8, places=2)

    def test_标题相似度对原名也各算一次(self):
        # 真机：《The Bear》的 TMDB 中文名是「熊家餐馆」，原名才是 The Bear。
        # 只看标题会判 0 分，必须"标题/原名各算一次取较优"。
        候选 = 造候选("136315", "熊家餐馆", 原名="The Bear")
        分, 说明 = 标题相似度(["The Bear"], 候选)
        self.assertEqual(分, 1.0)
        self.assertIn("The Bear", 说明)

    def test_观察标题过滤画质标记但保留纯数字片名(self):
        结构 = 假结构(标题="仙逆", 文件标题="1080p", 目录标题="仙逆.4K高码.SDR.60fps",
                  标题候选们=["x265", "仙逆"])
        观察 = 观察标题们(结构)
        self.assertIn("仙逆", 观察)
        self.assertNotIn("1080p", 观察)
        self.assertNotIn("x265", 观察)
        # 纯数字片名（2012.mp4）不许被当噪声删掉
        self.assertEqual(观察标题们(假结构(标题="2012")), ["2012"])

    def test_纯数字片名要能比出相似度(self):
        """``2012`` / ``1917`` 这类片名既没有汉字也没有字母。

        :func:`~wangpan.identify.候选.英文段` 故意要求"至少一个字母"（那是 ③ 生成查询词
        时的规矩），于是两个"空段"会比出 0 分 —— 真机上 ``2012.mp4`` 因此被打成 23 分、
        被判**丢弃**（正确的候选反而被丢掉）。这条测试钉住这个回归。
        """
        self.assertEqual(文本相似度("2012", "2012"), 1.0)
        self.assertEqual(文本相似度("1917", "1917"), 1.0)
        self.assertLess(文本相似度("2012", "2012 世界末日"), 0.5)
        结构 = 假结构(标题="2012", 类型="movie")
        对 = 造候选("14161", "2012", 类型="movie", 年份=2009, 热度=19.2, 票数=13048)
        结果 = 打分(结构, [对])
        self.assertEqual(结果.首选().系数("标题"), 1.0)
        self.assertGreater(结果.首选().总分, 30)      # 不该掉进"丢弃"档


# ============================ 年份 ============================


class 年份测试(unittest.TestCase):
    def test_四档系数(self):
        一致, _, 中性 = 年度系数(2021, 2021)
        差一, _, _ = 年度系数(2021, 2020)
        差二, _, _ = 年度系数(2021, 2019)
        差多, 说明, _ = 年度系数(2021, 1984)
        self.assertEqual(一致, 1.0)
        self.assertGreater(一致, 差一)
        self.assertGreater(差一, 差二)
        self.assertLess(差多, 0)          # 差 ≥3 年是**反证**，不是"少得一点分"
        self.assertIn("反证", 说明)

    def test_年份未知是中性而不是罚分(self):
        系数, 说明, 中性 = 年度系数(None, 2021)
        self.assertTrue(中性)
        self.assertEqual(系数, 0.0)
        self.assertIn("不奖不罚", 说明)

    def test_年份把重拍片分开(self):
        # 真机：《沙丘》2021(438631) 与《沙丘》1984(841) 同名，只靠年份分开
        结构 = 假结构(标题="沙丘", 年份=2021, 类型="movie")
        新 = 造候选("438631", "沙丘", 类型="movie", 年份=2021, 热度=41.4, 票数=12000)
        旧 = 造候选("841", "沙丘", 类型="movie", 年份=1984, 热度=16.5, 票数=3000)
        结果 = 打分(结构, [旧, 新])
        self.assertEqual(结果.首选().标识, "438631")
        self.assertLess(结果.分数们[1].系数("年份"), 0)


# ============================ 类型 / 上下文 ============================


class 类型测试(unittest.TestCase):
    def test_剧集样本里的电影候选被压下去(self):
        结构 = 假结构(标题="沙丘", 类型="tv", 季=1, 集=3)
        剧 = 造候选("900001", "沙丘", 类型="tv", 年份=2021)
        影 = 造候选("438631", "沙丘", 类型="movie", 年份=2021, 热度=999.0, 票数=99999)
        结果 = 打分(结构, [影, 剧])
        self.assertEqual(结果.首选().标识, "900001")
        self.assertEqual(结果.首选().系数("类型"), 1.0)
        self.assertEqual(结果.分数们[1].系数("类型"), -1.0)

    def test_类型未知时按上下文推(self):
        # 有集号 → 就是剧集（电影没有"第 146 集"）：候选类型不符要挨罚
        结构 = 假结构(标题="仙逆", 类型="unknown", 集=146)
        影 = 造候选("1", "仙逆", 类型="movie")
        剧 = 造候选("223911", "仙逆", 类型="tv")
        self.assertLess(类型系数(结构, 影)[0], 0)
        self.assertEqual(类型系数(结构, 剧)[0], 1.0)

    def test_两边都未知时中性(self):
        结构 = 假结构(标题="某片", 类型="unknown")
        self.assertTrue(类型系数(结构, 造候选("1", "某片", 类型="unknown"))[2])


# ============================ (季,集) 范围 ============================


class 季集范围测试(unittest.TestCase):
    #: 真机数据：仙逆 223911 = S0:8 + S1:200；仙逆合集篇 292307 = S1:22
    仙逆范围 = 季集范围({0: 8, 1: 200})
    合集范围 = 季集范围({1: 22})

    def test_集号落在季内(self):
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
        系数, 说明, 中性 = 季集范围系数(结构, 造候选("223911", "仙逆"), self.仙逆范围)
        self.assertEqual(系数, 1.0)
        self.assertFalse(中性)
        self.assertIn("200 集内", 说明)

    def test_集号超出全剧集数是反证(self):
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
        系数, 说明, _ = 季集范围系数(结构, 造候选("292307", "仙逆合集篇"), self.合集范围)
        self.assertLess(系数, -0.5)
        self.assertIn("合集", 说明)

    def test_跨季连续编号只轻扣(self):
        # 真机：《黑镜》07.mkv 是"跨季第 7 集"（S1 只有 3 集，全剧 33 集）——
        # 这是文件名习惯与 TMDB 季划分不一致的常见情形，绝不能当反证。
        黑镜 = 季集范围({1: 3, 2: 4, 3: 6, 4: 6, 5: 3, 6: 5, 7: 6})
        结构 = 假结构(标题="黑镜", 类型="tv", 季=1, 集=7)
        系数, 说明, _ = 季集范围系数(结构, 造候选("42009", "黑镜"), 黑镜)
        self.assertGreater(系数, 0)
        self.assertLess(系数, 1.0)
        self.assertIn("连续编号", 说明)

    def test_没有季集信息是中性(self):
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
        系数, 说明, 中性 = 季集范围系数(结构, 造候选("223911", "仙逆"), None)
        self.assertTrue(中性)
        self.assertIn("不奖不罚", 说明)

    def test_电影候选却有集号(self):
        结构 = 假结构(标题="沙丘", 类型="movie", 集=None)
        系数, _, _ = 季集范围系数(结构, 造候选("438631", "沙丘", 类型="movie"), None)
        self.assertEqual(系数, 0.0)
        结构带集 = 假结构(标题="沙丘", 类型="movie", 集=3)
        self.assertLess(季集范围系数(结构带集, 造候选("438631", "沙丘", 类型="movie"), None)[0], 0)

    def test_特别篇季号校验(self):
        # 特别篇/NCOP/NCED → 第 0 季；候选有第 0 季就算对上了
        结构 = 假结构(标题="某番", 类型="tv", 季=0, 集=None)
        self.assertEqual(季集范围系数(结构, 造候选("1", "某番"), self.仙逆范围)[0], 0.5)
        self.assertLess(季集范围系数(结构, 造候选("1", "某番"), 季集范围({1: 12}))[0], 0)

    def test_从候选读范围认多种形状(self):
        # 形状一：候选上挂着 季集范围
        self.assertEqual(从候选取范围(_带范围(12)).每季集数, {1: 12})
        # 形状二：什么都没有 → None（**不许猜**）
        self.assertIsNone(从候选取范围(造候选("1", "甲")))
        # 形状三：TMDB 的 季们（有 季号/集数 的对象列表）
        季们 = [type("季", (), {"季号": 1, "集数": 12})(),
                type("季", (), {"季号": 2, "集数": 10})()]
        self.assertEqual(从候选取范围(_带季们(季们)).每季集数, {1: 12, 2: 10})
        # 形状四：只有总集数
        self.assertEqual(从候选取范围(_带集数(30)).总集数, 30)


def _带范围(集数: int) -> 检索候选:
    候选 = 造候选("1", "甲")
    候选.季集范围 = 季集范围({1: 集数})
    return 候选


def _带季们(季们) -> 检索候选:
    候选 = 造候选("1", "甲")
    候选.季们 = 季们
    return 候选


def _带集数(集数: int) -> 检索候选:
    候选 = 造候选("1", "甲")
    候选.集数 = 集数
    return 候选


# ============================ 证据 / 热度 ============================


class 证据与热度测试(unittest.TestCase):
    def test_中英双证比单词命中强(self):
        单词 = 造候选("223911", "仙逆", 来源={"仙逆": 80.0})
        双词 = 造候选("223911", "仙逆", 来源={"仙逆": 80.0, "Renegade Immortal": 56.0})
        self.assertGreater(证据系数(双词)[0], 证据系数(单词)[0])
        self.assertIn("中英双证", 证据系数(双词)[1])

    def test_没有来源证据时中性(self):
        候选 = 造候选("1", "甲", 来源={})
        self.assertTrue(证据系数(候选)[2])

    def test_票数只做弱先验_44票的正确项照样赢99999票的错项(self):
        # 真机的坑：《仙逆》在 TMDB 上票数只有 44，而近名干扰片热度更高。
        # 如果票数不做对数压缩/权重压低，正确项会被热门错项压死。
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
        对 = 造候选("223911", "仙逆", 年份=2023, 热度=212.9, 票数=44,
                  来源={"仙逆": 80.0, "Renegade Immortal": 56.0})
        错 = 造候选("999999", "仙逆 逆天", 年份=2023, 热度=900.0, 票数=99999,
                  来源={"仙逆": 80.0})
        结果 = 打分(结构, [错, 对], 季集范围表={"223911": 季集范围({1: 200})})
        self.assertEqual(结果.首选().标识, "223911")
        self.assertLess(权重表["热度"], 权重表["标题"] / 5)   # 弱先验的"弱"要能被断言

    def test_热度票数都缺失时中性(self):
        from wangpan.identify.打分 import 热度系数
        候选 = 造候选("1", "甲", 热度=0, 票数=0)
        self.assertTrue(热度系数(候选)[2])


# ============================ 端到端（构造数据） ============================


class 打分端到端测试(unittest.TestCase):
    def test_近名干扰里正确项胜出(self):
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
        结果 = 打分(结构, 仙逆那批(),
                  季集范围表={"223911": 季集范围({0: 8, 1: 200})})
        self.assertEqual(结果.首选().标识, "223911")
        self.assertEqual(结果.首选().系数("标题"), 1.0)
        # 后面三名都不能靠得太近：margin 必须够大（否则会掉进待确认，见决策测试）
        self.assertGreater(结果.间距(), 30)

    def test_合集篇被标题与季集范围双重压住(self):
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
        正片 = 造候选("223911", "仙逆", 年份=2023, 热度=212.9, 票数=44,
                   来源={"仙逆": 80.0, "Renegade Immortal": 56.0})
        合集 = 造候选("292307", "仙逆合集篇", 年份=2025, 热度=1.6, 票数=3,
                   来源={"仙逆": 80.0})
        结果 = 打分(结构, [合集, 正片],
                  季集范围表={"223911": 季集范围({0: 8, 1: 200}),
                            "292307": 季集范围({1: 22})})
        self.assertEqual(结果.首选().标识, "223911")
        self.assertEqual(结果.分数们[1].标识, "292307")
        self.assertLess(结果.分数们[1].系数("季集范围"), 0)
        # 就算**没有**季集信息，标题相似度也足以让正片赢（两条独立的理由）
        无范围 = 打分(结构, [合集, 正片])
        self.assertEqual(无范围.首选().标识, "223911")

    def test_排序与输入顺序无关(self):
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
