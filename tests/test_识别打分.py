class 学习库测试(unittest.TestCase):
    def test_空库是中性不是罚分(self):
        结构 = 假结构(标题="仙逆", 类型="tv")
        候选 = 造候选("223911", "仙逆")
        系数, 说明, 中性 = 学习命中(结构, 候选, 学习库())
        self.assertTrue(中性)
        self.assertIn("空", 说明)
        self.assertEqual(系数, 0.0)

    def test_目录命中是强加权(self):
        结构 = 假结构(标题="仙逆", 类型="tv", 集=146, 目录链=("仙逆.4K高码.SDR.60fps",))
        库 = 学习库(目录={"仙逆.4K高码.SDR.60fps": {"tmdb_id": "223911", "标题": "仙逆"}})
        对 = 造候选("223911", "仙逆")
        错 = 造候选("292307", "仙逆合集篇")
        系数, 说明, _ = 学习命中(结构, 对, 库)
        self.assertEqual(系数, 1.0)
        self.assertIn("目录命中", 说明)
        self.assertEqual(学习命中(结构, 错, 库)[0], 0.0)
        结果 = 打分(结构, [错, 对], 学习库=库)
        self.assertEqual(结果.首选().标识, "223911")
        self.assertEqual(结果.首选().系数("学习库"), 1.0)

    def test_别名命中与空库文件(self):
        结构 = 假结构(标题="146", 类型="tv", 集=146)
        库 = 学习库(别名={"146": "仙逆"})
        对 = 造候选("223911", "仙逆")
        self.assertEqual(学习命中(结构, 对, 库)[0], 1.0)

    def test_库文件不存在等于空库(self):
        库 = 读学习库(默认学习库路径().with_name("这个文件肯定不存在_P3.json"))
        self.assertTrue(库.空的())

    def test_别名表参数等于学习库的别名节点(self):
        结构 = 假结构(标题="Renegade Immortal", 类型="tv")
        对 = 造候选("223911", "仙逆", 原名="仙逆")
        结果 = 打分(结构, [对], 别名表={"Renegade Immortal": "仙逆"})
        self.assertEqual(结果.首选().系数("学习库"), 1.0)


