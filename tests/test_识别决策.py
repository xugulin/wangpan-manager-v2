"""⑥ 决策（``wangpan/identify/决策.py``）的单测：三档 + margin + **精确率优先**。

这一组测试存在的唯一理由
======================
架构文档第六节第 2 条与第二节的表格把话说死了：**自动入库精确率 ≥ 99%**，
"宁可进待确认，也绝不把错的写进库"。所以这里的用例都是**反面**的：
想尽办法构造"看起来分很高但其实不该自动"的候选，然后断言它**没有**进自动档。

覆盖：
* 高分 + 大 margin → 自动；
* **两个几乎同分的候选 → 必须待确认**（margin 的意义）；
* 类型不一致 / 年份反证 / 集号越界 → 就算分高、margin 大也不许自动（硬条件）；
* 一条铁律：**分数最高的候选是错的时，不许自动入库**；
* 低分 → 丢弃、零候选 → 丢弃；
* 学习库命中免 margin（P4 的"越用越准"），但免不掉年份/类型的反证；
* 门槛可注入（评测脚本做敏感性分析用）。
"""

from __future__ import annotations

import unittest
from dataclasses import dataclass, field
from typing import Optional

from wangpan.identify.打分 import 季集范围, 学习库, 打分
from wangpan.identify.决策 import 决策, 门槛, 档_丢弃, 档_待确认, 档_自动, 默认门槛
from wangpan.identify.检索 import 检索候选


@dataclass
class 假结构:
    标题: str = ""
    年份: Optional[int] = None
    类型: str = "unknown"
    季: Optional[int] = None
    集: Optional[int] = None
    集到: Optional[int] = None
    文件标题: str = ""
    目录标题: str = ""
    标题候选们: list = field(default_factory=list)
    目录链: tuple = ()


def 造候选(标识: str, 标题: str, *, 类型: str = "tv", 年份=None, 热度: float = 10.0,
         票数: int = 100, 来源=None) -> 检索候选:
    return 检索候选(标识=标识, 类型=类型, 标题=标题, 原名=标题, 年份=年份,
                热度=热度, 票数=票数,
                来源=dict({标题: 80.0} if 来源 is None else 来源))


def 判(结构, 候选们, *, 季集范围表=None, 学习库对象=None, 门槛值=None):
    return 决策(结构, 打分(结构, 候选们, 学习库=学习库对象,
                        季集范围表=季集范围表), 门槛=门槛值)


# ============================ 自动档 ============================


class 自动档测试(unittest.TestCase):
    def test_高分且大间距就自动(self):
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
        对 = 造候选("223911", "仙逆", 年份=2023, 热度=212.9, 票数=44,
                  来源={"仙逆": 80.0, "Renegade Immortal": 56.0})
        干扰 = 造候选("287998", "逆天成仙", 年份=2025, 热度=6.2, 票数=10, 来源={"仙逆": 60.0})
        结果 = 判(结构, [干扰, 对], 季集范围表={"223911": 季集范围({0: 8, 1: 200})})
        self.assertEqual(结果.档位, 档_自动)
        self.assertEqual(结果.首选.标识, "223911")
        self.assertGreaterEqual(结果.间距, 默认门槛.自动间距)
        self.assertIn("领先第二名", 结果.原因)
        self.assertTrue(结果.关键信号)

    def test_原因要说清为什么自动(self):
        结构 = 假结构(标题="沙丘", 年份=2021, 类型="movie")
        对 = 造候选("438631", "沙丘", 类型="movie", 年份=2021, 热度=41.4, 票数=12000,
                  来源={"沙丘": 80.0, "Dune": 56.0})
        旧 = 造候选("841", "沙丘", 类型="movie", 年份=1984, 热度=16.5, 票数=3000)
        结果 = 判(结构, [旧, 对])
        self.assertEqual(结果.档位, 档_自动)
        self.assertIn("标题", 结果.原因)
        self.assertIn("总分", 结果.原因)


# ============================ margin：两个都像 → 待确认 ============================


class 间距测试(unittest.TestCase):
    def test_两个几乎同分的候选必须待确认(self):
        # 真机常见：TMDB 上同一部剧有**两条重复条目**（标题、年份、类型全一样），
        # 这时"谁对"根本无从判断 —— 分数可以很高，但没有理由自动选一个。
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146, 年份=2023)
        甲 = 造候选("1000001", "仙逆", 年份=2023, 热度=210.0, 票数=44,
                  来源={"仙逆": 80.0, "Renegade Immortal": 56.0})
        乙 = 造候选("1000002", "仙逆", 年份=2023, 热度=205.0, 票数=43,
                  来源={"仙逆": 80.0, "Renegade Immortal": 56.0})
        结果 = 判(结构, [甲, 乙], 季集范围表={"1000001": 季集范围({1: 200}),
                                         "1000002": 季集范围({1: 200})})
        self.assertEqual(结果.档位, 档_待确认)
        self.assertLess(结果.间距, 默认门槛.自动间距)
        self.assertIn("领先幅度", 结果.原因)
        self.assertGreater(结果.分数, 默认门槛.丢弃分)     # 分不低，但就是不能自动

    def test_门槛可注入_间距门槛调低就会自动(self):
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
        甲 = 造候选("1", "仙逆", 年份=2023, 热度=210.0, 票数=44, 来源={"仙逆": 80.0})
        乙 = 造候选("2", "仙逆", 年份=2023, 热度=205.0, 票数=43, 来源={"仙逆": 80.0})
        宽 = 门槛(自动间距=0.0, 自动分=0.0)
        self.assertEqual(判(结构, [甲, 乙], 门槛值=宽).档位, 档_自动)
        self.assertEqual(判(结构, [甲, 乙]).档位, 档_待确认)


# ============================ 硬条件（精确率的最后一道闸） ============================


class 硬条件测试(unittest.TestCase):
    def test_类型不一致时分数再高也不自动(self):
        # 构造：电影候选标题完全一致、年份一致，而剧集候选标题差一点。
        # 电影那条分数可能被热度/证据堆起来，但类型不一致必须一票否决。
        结构 = 假结构(标题="沙丘", 类型="tv", 季=1, 集=3, 年份=2021)
        影 = 造候选("438631", "沙丘", 类型="movie", 年份=2021, 热度=999.0, 票数=99999,
                  来源={"沙丘": 100.0, "Dune": 80.0})
        剧 = 造候选("900001", "沙丘 剧版", 类型="tv", 年份=2021, 热度=1.0, 票数=1,
                  来源={"沙丘": 60.0})
        # 把电影那条顶成第一名：给它足够的证据与热度（剧集那条相反）
        结果 = 判(结构, [剧, 影], 季集范围表={"438631": 季集范围({1: 1})})
        首选 = 结果.首选
        if 首选.标识 == "438631":
            self.assertNotEqual(结果.档位, 档_自动)
            self.assertIn("类型", 结果.原因)
        else:
            # 就算电影那条没顶到第一，类型不一致的候选也绝不能是"被自动采纳"的那条
            self.assertEqual(结果.档位, 档_待确认)

    def test_年份反证挡住自动(self):
        # 只有一条候选、且它年份差 37 年（《沙丘》1984 对 2021）→ 反证，不许自动
        结构 = 假结构(标题="沙丘", 年份=2021, 类型="movie")
        旧 = 造候选("841", "沙丘", 类型="movie", 年份=1984, 热度=16.5, 票数=3000,
                  来源={"沙丘": 100.0, "Dune": 80.0})
        结果 = 判(结构, [旧])
        self.assertEqual(结果.档位, 档_待确认)
        self.assertIn("年份是反证", 结果.原因)

    def test_集号越界挡住自动(self):
        # 《仙逆》146 集 vs《仙逆合集篇》只有 22 集：标题**足够像**（"仙逆 合集" ×
        # "仙逆合集篇" ≈ 0.86，过了标题下限），所以挡住自动的必须是季集范围那一条 ——
        # 这正是"(季,集) 范围校验"在架构里被单列出来的原因。
        结构 = 假结构(标题="仙逆 合集", 类型="tv", 季=1, 集=146)
        合集 = 造候选("292307", "仙逆合集篇", 年份=2023, 热度=212.9, 票数=44,
                   来源={"仙逆 合集": 100.0, "Renegade Immortal": 80.0})
        结果 = 判(结构, [合集], 季集范围表={"292307": 季集范围({1: 22})})
        self.assertGreaterEqual(结果.首选.系数("标题"), 默认门槛.标题下限)
        self.assertLess(结果.首选.系数("季集范围"), 默认门槛.范围重罚线)
        self.assertEqual(结果.档位, 档_待确认)
        self.assertIn("季集越界", 结果.原因)

    def test_标题不像时靠证据堆分也不自动(self):
        # 错项：标题相似度 0.4，但被三个查询词命中、热度票数拉满。
        # 分数能被堆到接近自动门槛，标题下限必须把它挡住。
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146, 年份=2023)
        蹭名 = 造候选("999999", "仙逆外传之逆天", 年份=2023, 热度=300.0, 票数=5000,
                   来源={"仙逆": 100.0, "Renegade Immortal": 80.0, "仙逆 外传": 48.0})
        结果 = 判(结构, [蹭名], 季集范围表={"999999": 季集范围({1: 500})})
        self.assertEqual(结果.档位, 档_待确认)
        self.assertIn("标题相似度", 结果.原因)


# ============================ 铁律 ============================


class 铁律测试(unittest.TestCase):
    def test_分数最高的候选是错的就绝不许自动(self):
        """**这是 P3 最硬的一条**：宁可待确认，也不许把错的写进库。

        构造（数字都是算好的）：
        * 错候选《仙逆外传》：标题 0.5 像、年份一致、类型一致、集号在范围内、
          被中英两个查询词命中、热度票数拉满 → 约 98 分；
        * 正确候选《仙逆》：标题完全一致，但年份差 1 年、只被一个查询词命中、
          没有季集信息、热度票数很低 → 约 84 分。
        错的那个**就是**第一名（真机上"错项靠热度/证据堆分"完全可能发生），
        此时唯一正确的处置是待确认（甚至丢弃），而不是自动入库。
        """
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=5, 年份=2020)
        错 = 造候选("999999", "仙逆外传", 年份=2020, 热度=200.0, 票数=5000,
                  来源={"仙逆": 100.0, "Renegade Immortal": 80.0})
        对 = 造候选("223911", "仙逆", 年份=2019, 热度=1.0, 票数=1,
                  来源={"仙逆": 60.0})
        结果 = 判(结构, [错, 对], 季集范围表={"999999": 季集范围({1: 100})})
        self.assertEqual(结果.首选.标识, "999999", "这个构造就是要让**错的**当第一名")
        self.assertNotEqual(结果.档位, 档_自动)
        self.assertEqual(结果.档位, 档_待确认)

    def test_自动档永远不会在标题不像时给出(self):
        """把一个"标题一律不像"的候选表跑一遍：自动档必须一条都不出。

        这是"精确率优先"的可执行版本：只要标题不像，就算它热度/证据/类型全满，
        也不可能自动入库。
        """
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146, 年份=2023)
        假候选们 = [
            造候选("1", "某某大剧", 年份=2023, 热度=300.0, 票数=5000,
                 来源={"仙逆": 100.0, "Renegade Immortal": 80.0, "某剧": 60.0}),
            造候选("2", "逆天成仙", 年份=2023, 热度=300.0, 票数=5000,
                 来源={"仙逆": 100.0, "Renegade Immortal": 80.0}),
            造候选("3", "都市之逆天仙尊", 年份=2023, 热度=300.0, 票数=5000,
                 来源={"仙逆": 100.0, "Renegade Immortal": 80.0}),
        ]
        结果 = 判(结构, 假候选们, 季集范围表={x.标识: 季集范围({1: 500}) for x in 假候选们})
        self.assertNotEqual(结果.档位, 档_自动)


# ============================ 丢弃 ============================


class 丢弃测试(unittest.TestCase):
    def test_零候选就丢弃(self):
        结果 = 判(假结构(标题="某剧", 类型="tv", 季=1, 集=3), [])
        self.assertEqual(结果.档位, 档_丢弃)
        self.assertIsNone(结果.首选)
        self.assertIn("一个候选都没有", 结果.原因)

    def test_分数太低就丢弃(self):
        # 标题完全不像、只有类型分与一点点证据 → 连人工都不值得看
        结构 = 假结构(标题="某剧", 类型="tv", 季=1, 集=3)
        垃圾 = 造候选("1", "完全不相干的东西", 热度=1.0, 票数=1, 来源={"某剧": 60.0})
        结果 = 判(结构, [垃圾])
        self.assertEqual(结果.档位, 档_丢弃)
        self.assertIn("不值得看", 结果.原因)

    def test_分数低但标题像的_仍然待确认而不是丢弃(self):
        # "拿不准一律待确认"：差一点点就能入库的候选值得人工花 3 秒
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
        对 = 造候选("223911", "仙逆", 年份=2023, 热度=1.0, 票数=1, 来源={})
        结果 = 判(结构, [对], 季集范围表={"223911": 季集范围({1: 200})})
        self.assertEqual(结果.档位, 档_待确认)
        self.assertIn("没到自动门槛", 结果.原因)


# ============================ 学习库（P4 接口） ============================


class 学习库决策测试(unittest.TestCase):
    def test_学习库命中免掉间距要求(self):
        # 人工确认过的答案不需要再"领先第二名"：同一目录里两个候选完全同分也照样自动
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146,
                   目录链=("仙逆.4K高码.SDR.60fps",))
        库 = 学习库(目录={"仙逆.4K高码.SDR.60fps": {"tmdb_id": "223911"}})
        甲 = 造候选("223911", "仙逆", 年份=2023, 热度=212.9, 票数=44,
                  来源={"仙逆": 80.0, "Renegade Immortal": 56.0})
        乙 = 造候选("292307", "仙逆合集篇", 年份=2023, 热度=212.9, 票数=44,
                  来源={"仙逆": 80.0, "Renegade Immortal": 56.0})
        结果 = 判(结构, [甲, 乙], 学习库对象=库,
                 季集范围表={"223911": 季集范围({0: 8, 1: 200}),
                           "292307": 季集范围({0: 8, 1: 200})})
        self.assertEqual(结果.档位, 档_自动)
        self.assertEqual(结果.首选.标识, "223911")
        self.assertIn("学习库命中", 结果.原因)

    def test_学习库免不掉年份反证(self):
        # 库是脏的（同一目录换过内容/人工点错过）时不许盲目自动
        结构 = 假结构(标题="沙丘", 年份=2021, 类型="movie", 目录链=("电影",))
        库 = 学习库(目录={"电影": {"tmdb_id": "841"}})
        旧 = 造候选("841", "沙丘", 类型="movie", 年份=1984, 热度=16.5, 票数=3000)
        结果 = 判(结构, [旧], 学习库对象=库)
        self.assertEqual(结果.档位, 档_待确认)
        self.assertIn("库可能脏了", 结果.原因)

    def test_空库不影响正常判定(self):
        结构 = 假结构(标题="仙逆", 类型="tv", 季=1, 集=146)
        对 = 造候选("223911", "仙逆", 年份=2023, 热度=212.9, 票数=44,
                  来源={"仙逆": 80.0, "Renegade Immortal": 56.0})
        结果 = 判(结构, [对], 学习库对象=学习库(),
                 季集范围表={"223911": 季集范围({0: 8, 1: 200})})
        self.assertEqual(结果.档位, 档_自动)


